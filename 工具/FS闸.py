def _末章():
    ns = []
    for f in glob.glob(os.path.join(ROOT, '正文', '*.md')):
        m = re.search(r'第([零〇一二三四五六七八九十百千]+)章', os.path.basename(f))
        if not m:
            continue
        CN = {'零': 0, '〇': 0, '一': 1, '二': 2, '三': 3, '四': 4, '五': 5,
              '六': 6, '七': 7, '八': 8, '九': 9}
        s, tot, cur = m.group(1), 0, 0
        for ch in s:
            if ch in CN:
                cur = CN[ch]
            elif ch == '十':
                tot += (cur or 1) * 10
                cur = 0
            elif ch == '百':
                tot += (cur or 1) * 100
                cur = 0
            elif ch == '千':
                tot += (cur or 1) * 1000
                cur = 0
        ns.append(tot + cur)
    return max(ns) if ns else 0


