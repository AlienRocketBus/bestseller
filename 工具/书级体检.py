# ── ② 章型连锁 ────────────────────────────────────────
def sig_of(body):
    ps = [x.strip() for x in body.split('\n') if x.strip()][2:]
    ps2 = [net_len(x) for x in ps if x != '＊']
    if not ps2:
        return None, 0, 0
    n = len(ps2)
    # ★2026-08-20 订：先前分母用 len(ps)，而 ps 含「＊」分隔行；
    # ★★而分子 total 只算实字，故均段被虚增之分母腰斩，全书尽判「短」。
    # ★★★今分子分母同源：皆只算实段（ps2）。
    total = sum(ps2)
    avg = total / max(1, n)
    # 章型以均段分档：短（<15）／中（15-18）／中长（18-21）／长（>21）
    # ★★★★★2026-09-17 订·⛔**这四档已量不着它本来要量的那一样了**（本坐今日逐章亲跑所逮）：
    #   ★**本检所问者係「纹理是不是一成不变」**，其量係「均段长」；
    #   ⛔**而「段」这个单位，本书自 332 前後换过一回**：
    #     **从前一拍之内分数段（故均段十几二十）；今一拍即一段**（白文一拍一行，拍与拍之间只隔 `＊`）。
    #   ★★**於是同一个数，量的已不是同一样东西**——**它从「一段有多长」变成了「一拍有多长」。**
    #   ★★★**其实（0917 亲跑 331—344 之均段）**：
    #     331:20.0｜332:37.5｜333:39.4｜334:51.4｜335:67.3｜336:90.4｜337:65.7｜338:55.4｜
    #     339:69.9｜340:73.5｜341:76.9｜342:101.2｜343:74.7｜344:93.6
    #     ——⛔**自 332 起无一章落在 21 以下，故章章判「长」，连锁必逾十二，且此後永远如此。**
    #   ⛔**即：这是一条永远清不掉的红**（与 `COLD-336` 同形，本日已记其害：
    #     **一条永远清不掉的红，会把人教成见红就绕**）。
    #   ★★★★**而其治不是把四档之数往上挪**（那是拿闸去就今日之数·㊸），
    #     **亦不是放宽连锁之限**（`2026-08-22` 那一订自书「那是把闸调松」，其判今日照旧在役）；
    #     ★**其治係把「型」改成一个相对之判**：**本章之均段，落在近窗之第几档**。
    #     ⛔**其由**：**「纹理一成不变」这一问，本来就是相对的**——
    #     **问的是「这一章与它左右邻章像不像」，不是「它有没有超过某个绝对之数」**；
    #     **故其档须随窗走，而窗一变，档自变。**★**此与本日 `重出趋` 那一处之判不相犯**：
    #     **那一处所拒者係「一条判好坏之线随群漂」；此处所立者係「一个分类，其义本就相对」。**
    # ★2026-08-22 订（259第1轮所逮·实证）：此档与冷轮二五四之令相犯。
    #   ★★二五四立於256，其令为「净重÷拍数须落在18至22之间」（其由：246起每章拍数减三分之一，
    #      而治之之法是把同一件事摆得更开，非拉长每一拍）；
