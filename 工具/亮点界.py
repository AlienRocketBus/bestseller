import io, os, re, sys

根 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(根, '工具'))
from 亮点对表 import 诸章  # noqa: E402

标 = re.compile(r'[\s*★·【】，。、；：？！…—「」『』（）()／/"\'’‘“”0-9a-zA-Z]')
窗 = 8
最短 = 12


def 剥(s):
    return 标.sub('', s)


def 分章(路):
    t = io.open(路, encoding='utf-8').read()
    if '【本章亮点】' in t:
        a, b = t.split('【本章亮点】', 1)
    else:
        a, b = t, ''
    return a, b


def 切句(s):
    return [x for x in re.split(r'(?<=[。？！])', s) if x.strip()]


def 命中(句骨, 正骨):
    n = 0
    for k in range(0, max(1, len(句骨) - 窗 + 1)):
        if 句骨[k:k + 窗] in 正骨:
            n += 1
    return n


def 诸对():
    """自施工表读「（N拆出）」——返回 [(源章, 拆出章), ...]。"""
    p = os.path.join(根, '设定', '01_镇冢秘术_逐章施工与伏笔回收表.md')
    out = []
    for ln in io.open(p, encoding='utf-8'):
        m = re.match(r'\|\s*(\d+)\s*\|', ln)
        if not m:
            continue
        m2 = re.search(r'（(\d+)拆出）', ln)
        if m2:
            out.append((int(m2.group(1)), int(m.group(1))))
    return out


# ★已裁之例外（逐条带其由·非白名单，是判过的案）：
#   键＝(写的那一章, 被写的那一章)；值＝该句之片段与其裁由。
#   凡入此表者，印作「ℹ 已裁例外」而不计红——**加一条须上盘核过并把由写在这里**。
例外 = {
    (148, 147): [(
        '拿四十尺除下来：老头一尺三，东头一尺一二，他一尺六',
        '148亮点此括注係就本章自己的数作除法：正文481「老头三十一。东头三十五。我二十五。」'
        '＋483「同一段四十尺」，四十除三十一得一尺三、除三十五得一尺一二、除二十五得一尺六；'
        '其果与147正文原句逐字相同，故被本器逮住，然它引的不是隔章之事，是本章之算。'
        '（2026-09-05 本坐上盘核过；不为消一个红去正文添笔。）'
    )],
}


def 裁过(我, 邻, s):
    for 片, _由 in 例外.get((我, 邻), []):
        if 片 in s:
            return True
    return False


def 验一对(a, b, 章):
    """a 源、b 拆出。返回 [(章号, 句, 本命中, 对命中), ...]。"""
    出 = []
    if a not in 章 or b not in 章:
        return 出
    体 = {}
    亮 = {}
    for n in (a, b):
        x, y = 分章(章[n])
        体[n] = 剥(x)
        亮[n] = y
    for 我, 邻 in ((a, b), (b, a)):
        for s in 切句(亮[我]):
            g = 剥(s)
            if len(g) < 最短:
                continue
            h1, h2 = 命中(g, 体[我]), 命中(g, 体[邻])
            if h1 == 0 and h2 > 0:
                出.append((我, 邻, s, h1, h2, 裁过(我, 邻, s)))
    return 出


def 跑(只=None):
    章 = 诸章()
    对 = 诸对()
    if 只:
        对 = [t for t in 对 if 只 in t]
    print('════ 亮点界 · %d 对（全书「N拆出」共 %d 对）════' % (len(对), len(诸对())))
    红 = 0
    例 = 0
    for a, b in 对:
        r = 验一对(a, b, 章)
        新 = [x for x in r if not x[5]]
        老 = [x for x in r if x[5]]
        for 我, 邻, s, h1, h2, _ in 老:
            例 += 1
            print('  ℹ 第%d／%d章·已裁例外：%s' % (我, 邻, s.strip()[:40]))
        if not 新:
            continue
        红 += 1
        字 = sum(len(x[2]) for x in 新)
        print('  ⛔ 第%d／%d章：越界 %d 句 %d 字' % (a, b, len(新), 字))
        for 我, 邻, s, h1, h2, _ in 新[:6]:
            print('     · %d 之亮点写着 %d 的事（本0／对%d）：%s' % (我, 邻, h2, s.strip()[:46]))
        if len(新) > 6:
            print('     · …另 %d 句' % (len(新) - 6))
    if 红 == 0:
        print('  ✓ %d 对，亮点之界与正文之界皆合（另有已裁例外 %d 处）。' % (len(对), 例))
    return 红


def 自测():
    R = []
    体a = '他说：过。就一个字。老头把绳解开一根，换了个绑法，一前一后。'
    体b = '刘二又回头问你那个数。我说过了。他说不是那个。'
    def mk(体, 亮):
        return 剥(体), 亮
    # ①真越界：a 之亮点讲 b 的事
    ga, _ = mk(体a, '')
    gb, _ = mk(体b, '')
    s = '刘二又回头问你那个数，我说过了，他说不是那个。'
    R.append(('①真越界·本0对>0', 命中(剥(s), ga) == 0 and 命中(剥(s), gb) > 0))
    # ②不越界：a 之亮点讲 a 的事
    s2 = '老头把绳解开一根，换了个绑法，一前一后。'
    R.append(('②不越界·本>0', 命中(剥(s2), ga) > 0))
    # ③短句不判
    R.append(('③短句剥後不足12字者不判', len(剥('就一个字。')) < 最短))
    # ④标点不同不算相犯
    R.append(('④剥标点後同句仍算命中', 命中(剥('就一个字'), 剥('就，一个字。')) >= 0 and
              剥('就，一个字。') == '就一个字'))
    # ⑤诸对读得出且含 133/134
    d = 诸对()
    R.append(('⑤自施工表读出 23 对且含 (133,134)', len(d) == 23 and (133, 134) in d))
    # ⑥本器在今日之树上，133／134 一对须绿（今日已治）
    章 = 诸章()
    R.append(('⑥133／134 今日已治·零越界', 验一对(133, 134, 章) == []))
    R.append(('⑦例外只认写死的那一句·换一字即不认',
              裁过(148, 147, '拿四十尺除下来：老头一尺三，东头一尺一二，他一尺六。') and
              not 裁过(148, 147, '拿四十尺除下来：老头一尺四，东头一尺一二，他一尺六。')))
    R.append(('⑧例外不越对·(133,134)无例外可援',
              not 裁过(133, 134, '拿四十尺除下来：老头一尺三，东头一尺一二，他一尺六。')))
    # ⑨⑩ 旧式回灌（拿盘上真章作夹具，非造句）：
    #   133／134 今日已治，故把 134 正文的一句放回 133 之亮点位上，本器须判红；
    #   而 133 正文自己的一句放在 133 之亮点位上，须判绿。两条一并钉住「它到底会不会响」。
    体133 = 剥(分章(章[133])[0])
    体134 = 剥(分章(章[134])[0])
    s9 = '他两只手都空着，掌心朝壁，走一步按一下：不是扶，是拿手心先探那面壁是不是实的'
    s10 = '他说这三个字的时候没有回头，说完站着没有动'
    R.append(('⑨旧式回灌·134之句放回133亮点位即判红',
              命中(剥(s9), 体133) == 0 and 命中(剥(s9), 体134) > 0))
    R.append(('⑩133自己的句放在133亮点位判绿', 命中(剥(s10), 体133) > 0))
    for 名, ok in R:
        print(('  ✓ ' if ok else '  ⛔ ') + 名)
    print('  自测 %d/%d' % (sum(1 for _, o in R if o), len(R)))
    return all(o for _, o in R)


