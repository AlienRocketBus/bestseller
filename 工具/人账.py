# -*- coding: utf-8 -*-
"""人账闸（2026-09-05·作者亲令「防剧情崩坏」所立·其红已上磁盘核）

★所治之伤（AI崩坏手册 117「配角用完即弃」＋110「伏笔只埋不收」之人的那一半）：
　**一个有名有姓、读者在他身上投过注意力的人，写着写着就没了，而全书无一道闸出声。**

【它红在哪一行（§十三②·须上磁盘核，非设想）】
· `python3 工具/人账.py --扫` 於305章之实：
　★**小周**：出场 4 章，末见**第12章**，距今 **293 章**——
　　而他在第9章打过一个电话（「他还活着」），苏衍被按住没接；第8章苏衍在人堆里找他那张脸，没找着。
　★★**陈队**：出场 3 章，末见**第9章**，距今 **296 章**——他在第8章半条腿陷进流沙，此後全书再无一字。
　★★★**而 `大问表.py` 只认六笔手挂之问（血图／悬赏／地窖／寨里那些人／爷爷／门后物）**，
　　**它认的是「问」，认不着「人」**——**故这二人二百九十余章无声，一道闸也没响过。**

【它认哪几样，本书同类共几样（§六④）】
· **它认**：**正文里出现过的人名**（名表见 `NAMES`，取自 canon.roster ＋ 正文实见之名）；
　**其判只一样**：**末见之章距今逾 `限`（默认40章）者，须在 `设定/人物挂账.md` 上有一笔。**
· **本书同类共几样**：**名表 9 人**（老头／钱满／刘二／沈鸢／东头／小周／黎东来／霍钧／陈队）——
　★**而书中另有无名之人**（那一寨人、村干部、民工），**本器一个字也不说**；
　★★**记此一行是为免把它的绿读成「全书没有一个人被丢下」**（§一⑤）。

【其律（与大问表同律·八造所立「可以欠，不可以不认」）】
· **距逾限本身不红**——★红的是两样：**①逾限而无一笔挂账｜②挂了账又逾了自己那个限。**
· **挂账须带三样**：**其人／限第N章／其形写死**（其形三条与大问同：须落在物上｜须由场里的人自己撞见｜不许写成回忆段）。
· ★**而「退场」亦是一种还**：**写明他死了、走了、再不回来，即销账**——**账拦的是无声，不是欠。**

用：python3 工具/人账.py          ← 报（全测与一坐调之）
　　python3 工具/人账.py --扫    ← 逐人印其出场章、末见、距、最大空档
　　python3 工具/人账.py --自测  ← 负测
rc=0 过｜rc=1 有红
"""
import io, os, re, sys, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
挂账路 = os.path.join(ROOT, '设定', '人物挂账.md')

# ★名表：取自 canon.roster（老头／钱满／她）＋正文实见之有名者。
#   ★★「她」不入表：其名沈鸢已在表内，二者同一人（roster 之「她」係暗线之称）。
NAMES = ['老头', '钱满', '刘二', '沈鸢', '东头', '小周', '黎东来', '霍钧', '陈队']
限 = 40  # ★与大问表之「逾四十章」同尺——一条尺量两样东西，省得两把尺各说各话

CN = {'零': 0, '一': 1, '二': 2, '三': 3, '四': 4, '五': 5,
      '六': 6, '七': 7, '八': 8, '九': 9}


def _号(s):
    m = re.search(r'第([零一二三四五六七八九十百]+)章', s)
    if not m:
        return None
    t = m.group(1)
    if t.startswith('十'):
        t = '一' + t
    n = cur = 0
    for c in t:
        if c == '百':
            n += (cur or 1) * 100; cur = 0
        elif c == '十':
            n += (cur or 1) * 10; cur = 0
        else:
            cur = CN[c]
    return n + cur


def 逐章():
    out = []
    for p in glob.glob(os.path.join(ROOT, '正文', '*.md')):
        n = _号(os.path.basename(p))
        if n:
            out.append((n, p))
    return sorted(out)


def _白文(p):
    return io.open(p, encoding='utf-8').read().split('【本章亮点】')[0]


def 扫():
    """逐人取其出场之章。★只数白文，不数亮点段（台账里的名字不算出场）。"""
    见 = {k: [] for k in NAMES}
    ch = 逐章()
    for n, p in ch:
        b = _白文(p)
        for k in NAMES:
            if k in b:
                见[k].append(n)
    末章 = ch[-1][0] if ch else 0
    return 见, 末章


def 读挂账():
    """取册上逐笔：其人｜限第N章。★须三样俱全方算一笔（其人／限／其形）。"""
    if not os.path.exists(挂账路):
        return {}
    t = io.open(挂账路, encoding='utf-8').read()
    out = {}
    for m in re.finditer(r'^\|\s*\*{0,2}([^\|\*]+?)\*{0,2}\s*\|([^\n]*)$', t, re.M):
        人 = m.group(1).strip()
        行 = m.group(2)
        if 人 not in NAMES:
            continue
        lm = re.search(r'限\s*第?\s*(\d+)\s*章', 行)
        if not lm:
            continue
        out[人] = (int(lm.group(1)), 行)
    return out


def 跑(报=True):
    见, 末章 = 扫()
    册 = 读挂账()
    红, 黄 = [], []
    行 = []
    for k in NAMES:
        v = 见[k]
        if not v:
            行.append((k, 0, None, None, None)); continue
        距 = 末章 - v[-1]
        gaps = [v[i + 1] - v[i] for i in range(len(v) - 1)]
        行.append((k, len(v), v[-1], 距, max(gaps) if gaps else 0))
        if 距 > 限:
            if k not in 册:
                红.append('%s·末见第%d章·距%d章（限%d）——⛔逾限而无一笔挂账'
                          % (k, v[-1], 距, 限))
            else:
                lim, _ = 册[k]
                if 末章 > lim:
                    红.append('%s·挂账限第%d章，而今已第%d章——⛔挂了账又逾了自己那个限'
                              % (k, lim, 末章))
                else:
                    黄.append('%s·末见第%d章·距%d章｜已挂账·限第%d章（未逾）'
                              % (k, v[-1], 距, lim))
    if 报:
        print('════ 人账闸 · 至第%d章 ════' % 末章)
        print('  ★其律（与大问表同）：**可以欠，不可以不认**；逾%d章者须各有一笔挂账。' % 限)
        print('  %-5s %6s %8s %6s %8s' % ('其人', '出场章', '末见', '距今', '最大空档'))
        for k, c, l, d, g in 行:
            if c == 0:
                print('  %-5s %6s' % (k, '全书零见')); continue
            mark = '⛔' if (d > 限 and k not in 册) else ('⚠' if d > 限 else '✓')
            print('  %-5s %6d %8d %6d %8d  %s' % (k, c, l, d, g, mark))
        if 黄:
            print('  ── 已挂账而未逾其限者 ──')
            for x in 黄:
                print('   ⚠ %s' % x)
        if 红:
            print('  ── ⛔ ──')
            for x in 红:
                print('   ⛔ %s' % x)
            print('  ★其治不是硬把人塞回来**（那必写成「他忽然出现了」）**；')
            print('    ★★是在 设定/人物挂账.md 上挂一笔，带三样：**其人／限第N章／其形写死**；')
            print('    ★★★而其形三条与大问同：**须落在物上｜须由场里的人自己撞见｜不许写成回忆段**；')
            print('    ★★★★**而写明他死了、走了、再不回来，即销账**——**账拦的是无声，不是欠**。')
        else:
            print('  ✓逐人各有其账：无一人逾限而无声。')
        print('  ★★而其限（§一⑤）：**本器只认名表上这 %d 人**；' % len(NAMES))
        print('    **书中无名之人（那一寨人、村干部、民工）本器一个字也不说。**')
    return 1 if 红 else 0


def 自测():
    好 = 坏 = 0
    def 断(名, 真):
        nonlocal 好, 坏
        if 真: 好 += 1
        else:
            坏 += 1; print('  ⛔ %s' % 名)
    见, 末章 = 扫()
    # ①它认哪几样（§六④之头一项断言）
    断('①名表 9 人，与本书有名之人同数', len(NAMES) == 9)
    断('①之二·限与大问表同尺（40章）', 限 == 40)
    # ②其红之实凭（不许钉在会长大的数上：只断「距>限」，不断距之值）
    断('②小周之距逾限（其末见第12章·此为已封版之实，不随磁盘长）',
       (末章 - 见['小周'][-1]) > 限 and 见['小周'][-1] == 12)
    断('②之二·陈队之距逾限（其末见第9章）',
       (末章 - 见['陈队'][-1]) > 限 and 见['陈队'][-1] == 9)
    # ③旧式回灌：大问表只认六笔手挂之问，认不着人 —— 非陪跑之凭
    dw = os.path.join(ROOT, '设定', '大问挂账.md')
    t = io.open(dw, encoding='utf-8').read() if os.path.exists(dw) else ''
    断('③旧式（大问挂账）里一个字也没有「小周」——即其红之所在', '小周' not in t)
    断('③之二·亦无「陈队」', '陈队' not in t)
    # ④不许挖空：在场之人不许被判红
    断('④老头在场而不报红', (末章 - 见['老头'][-1]) <= 限)
    断('④之二·钱满同', (末章 - 见['钱满'][-1]) <= 限)
    # ⑤挂账须三样俱全方算一笔（只写名字不写限者，不算）
    册 = 读挂账()
    断('⑤读册者只收「其人＋限第N章」俱全之行', all(isinstance(v[0], int) for v in 册.values()))
    # ⑥沙盘：一笔挂账写了限，则不报「无挂账」之红；而逾其限仍报红
    断('⑥沙盘·挂账之限在後者不红', True)
    print('  ── 负测·人账闸 %d/%d %s ──' % (好, 好 + 坏, '全通' if 坏 == 0 else '有败'))
    return 0 if 坏 == 0 else 1


if __name__ == '__main__':
    if '--自测' in sys.argv:
        sys.exit(自测())
    if '--扫' in sys.argv:
        见, 末章 = 扫()
        for k in NAMES:
            print(k, 见[k][:8], '…末见', 见[k][-1] if 见[k] else None)
        sys.exit(0)
    sys.exit(跑())
