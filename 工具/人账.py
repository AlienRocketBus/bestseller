"""人账闸（2026-09-05·作者亲令「防剧情崩坏」所立·其红已上磁盘核）

★所治之伤（AI崩坏手册 117「配角用完即弃」＋110「伏笔只埋不收」之人的那一半）：
　**一个有名有姓、读者在他身上投过注意力的人，写着写着就没了，而全书无一道闸出声。**

【它红在哪一行（§十三②·须上磁盘核，非设想）】
· `python3 工具/人账.py --扫` 於305章之实：
　★**小周**：出场 4 章，末见**第12章**，距今 **293 章**——
　　而他在第9章打过一个电话（「他还活着」），苏衍被按住没接；第8章苏衍在人堆里找他那张脸，没找着。
　★★**陈队**：出场 3 章，末见**第9章**，距今 **296 章**——他在第8章半条腿陷进流沙，此後全书再无一字。
　★★★**而 `大问表.py` 只认六笔手挂之问（血图／悬赏／地窖／寨里那些人／爷爷／门后物）**，
　　**它认的是「问」，认不着「人」**——**故这二人二百九十余章无声，一道闸也没响过。**

【它认哪几样，本书同类共几样（§六④）】
· **它认**：**正文里出现过的人名**（名表见 `NAMES`，取自 canon.roster ＋ 正文实见之名）；
　**其判只一样**：**末见之章距今逾 `限`（默认40章）者，须在 `设定/人物挂账.md` 上有一笔。**
· **本书同类共几样**：**名表 9 人**（老头／钱满／刘二／沈鸢／东头／小周／黎东来／霍钧／陈队）——
　★**而书中另有无名之人**（那一寨人、村干部、民工），**本器一个字也不说**；
　★★**记此一行是为免把它的绿读成「全书没有一个人被丢下」**（§一⑤）。

【其律（与大问表同律·八造所立「可以欠，不可以不认」）】
· **距逾限本身不红**——★红的是两样：**①逾限而无一笔挂账｜②挂了账又逾了自己那个限。**
· **挂账须带三样**：**其人／限第N章／其形写死**（其形三条与大问同：须落在物上｜须由场里的人自己撞见｜不许写成回忆段）。
· ★**而「退场」亦是一种还**：**写明他死了、走了、再不回来，即销账**——**账拦的是无声，不是欠。**

用：python3 工具/人账.py          ← 报（全测与一坐调之）
　　python3 工具/人账.py --扫    ← 逐人印其出场章、末见、距、最大空档
　　python3 工具/人账.py --自测  ← 负测
rc=0 过｜rc=1 有红
"""
import io, os, re, sys, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
挂账路 = os.path.join(ROOT, '设定', '人物挂账.md')

# ★名表：取自 canon.roster（老头／钱满／她）＋正文实见之有名者。
#   ★★「她」不入表：其名沈鸢已在表内，二者同一人（roster 之「她」係暗线之称）。
NAMES = ['老头', '钱满', '刘二', '沈鸢', '东头', '寨老', '小周', '黎东来', '霍钧', '陈队']
限 = 40  # ★只作「该不该看一眼」之窗，**不作判据**（2026-09-05 作者驳正：距不是判据）

# ★★★★★2026-09-05·作者驳正（逐字存档）：
#   「**有的这个配角……交代还是不交代都行，但是有个前提**：**就算不交代了，也要符合逻辑**……
#    **这可能属于那种转瞬即逝的路人甲，对不对？那你觉得有必要刻意去交代他们的下场吗？**」
# ★而其驳正之所以立得住，是本器头一版的判据错了：
#   ★★**头一版拿「距今多少章」当判据**——**於是小周（4章·0句对白）与老头（266章）用同一把尺量**；
#   ★★★**而距从来不是判据**：**一个人不再出现，本身从来不是伤**；
#   ★★★★**伤只有一种：这本书自己让读者欠了他一个下落，而那个下落既没还，也没断。**
#
# 【新判据：投注 × 下落】
# · **投注**（可数·下之 `投注()`）：有名+1｜入canon档案+3｜出场≥10章+2｜开口≥5回+2｜
#   主角挂念之句+2（「X呢。」「X怎么样了」——**其不在场时还被人问起，才算读者投过注意力**）
# · **门槛 5**：投注<5 者判**哑**——**本来无欠可言**；★**刻意去交代它反而是伤**：
#   **读者会以为你还要用他**（AI崩坏手册110之反面：**不该埋的钩子也别撒**）。
# · **下落三者，皆销账，无高下**：
#   ★**还**——交代其下场（死了／走了／还活着）；
#   ★★**断**——**写明主角够不着**：**一次即足，且须落在物上**（他自己摁灭了电源、报上没有名单、他不敢问）；
#   ★★★**哑**——投注不到门槛，本来不欠。
# · ★★★★**而「断」比「还」更硬的时候，是断本身要付代价**：
#   **第9章「不许接」、他自己摁灭电源｜第11章「从今夜起，上头那个苏记者，没了」｜第13章关机、断电、取卡**
#   ——**这三处不是作者忘了交代小周与陈队，是主角亲手把这条线掐了，而那一掐是有价钱的。**
投注门槛 = 5
CANON = ('老头', '钱满', '沈鸢', '黎东来', '霍钧')   # 圣经§七人物唯一档案所列（苏衍為主角，不入表）
# ★断词分二等（2026-09-05·本器头一版之自伤所立）：
#   ★★头一版把「没了」也算作断词，於是寨老之断被判在「第四天他心里那个数没了」上
#     ——**那一句与寨老一个字的关系也没有**；★★★**一个会喊狼的核对器，比没有更糟**。
#   ★★★★故分二等：**强词**（其句自明，不须带名）｜**弱词**（须与其名同句方算）。
断词强 = ('不许接', '不该再出现', '一个不留', '打不通', '问不着')
断词弱 = ('关机', '断电', '够不着', '没了', '再没见', '再没来')

CN = {'零': 0, '一': 1, '二': 2, '三': 3, '四': 4, '五': 5,
      '六': 6, '七': 7, '八': 8, '九': 9}


def _号(s):
    m = re.search(r'第([零一二三四五六七八九十百]+)章', s)
    if not m:
        return None
    t = m.group(1)
    if t.startswith('十'):
        t = '一' + t
    n = cur = 0
    for c in t:
        if c == '百':
            n += (cur or 1) * 100; cur = 0
        elif c == '十':
            n += (cur or 1) * 10; cur = 0
        else:
            cur = CN[c]
    return n + cur


def 逐章():
    out = []
    for p in glob.glob(os.path.join(ROOT, '正文', '*.md')):
        n = _号(os.path.basename(p))
        if n:
            out.append((n, p))
    return sorted(out)


def _白文(p):
    return io.open(p, encoding='utf-8').read().split('【本章亮点】')[0]


def 扫():
    """逐人取其出场之章。★只数白文，不数亮点段（台账里的名字不算出场）。"""
    见 = {k: [] for k in NAMES}
    ch = 逐章()
    for n, p in ch:
        b = _白文(p)
        for k in NAMES:
            if k in b:
                见[k].append(n)
    末章 = ch[-1][0] if ch else 0
    return 见, 末章


def 投注(k, 见, 开口, 挂念):
    """★可数之投注**（其义见档头）**：有名1｜canon档案3｜出场≥10章2｜开口≥5回2｜主角挂念2。"""
    v = 1
    if k in CANON: v += 3
    if len(见) >= 10: v += 2
    if 开口 >= 5: v += 2
    if 挂念: v += 2
    return v


def 断之验(k, 见, ch):
    """★「断」之实：**末见之章及其後二章之内，有一处落在物上的「够不着」**。
    ★★其取窗只到末见+2，**其由**：**断是当场付的，不是往後补的**；
       ★★★而窗内须与其名同章，或与其名同章之後紧邻二章（本书之断多在人一走即落）。"""
    if not 见:
        return None
    lo, hi = 见[-1], 见[-1] + 2
    for n, p in ch:
        if not (lo <= n <= hi):
            continue
        b = _白文(p)
        for w in 断词强:
            for m in re.finditer(r'[^。！？\n]{0,26}' + w + r'[^。！？\n]{0,18}[。！？]', b):
                s = m.group(0).strip()
                if len(s) > 8:
                    return (n, s)
        for w in 断词弱:
            for m in re.finditer(r'[^。！？\n]{0,26}' + w + r'[^。！？\n]{0,18}[。！？]', b):
                s = m.group(0).strip()
                if len(s) > 8 and k in s:          # ★弱词须与其名同句
                    return (n, s)
    return None


def 读挂账():
    """取册上逐笔：其人｜限第N章。★须三样俱全方算一笔（其人／限／其形）。"""
    if not os.path.exists(挂账路):
        return {}
    t = io.open(挂账路, encoding='utf-8').read()
    out = {}
    for m in re.finditer(r'^\|\s*\*{0,2}([^\|\*]+?)\*{0,2}\s*\|([^\n]*)$', t, re.M):
        人 = m.group(1).strip()
        行 = m.group(2)
        if 人 not in NAMES:
            continue
        lm = re.search(r'限\s*第?\s*(\d+)\s*章', 行)
        if not lm:
            continue
        out[人] = (int(lm.group(1)), 行)
    return out


def 跑(报=True):
    见, 末章 = 扫()
    ch = 逐章()
    册 = 读挂账()
    开口, 挂念 = {}, {}
    for k in NAMES:
        c = 0; q = None
        for n, p in ch:
            b = _白文(p)
            c += len(re.findall(re.escape(k) + r'[^。\n]{0,6}?(说|问|答|道|喊)[：:，,「“]', b))
            if q is None:
                m = re.search(r'[^。！？\n]{0,18}' + re.escape(k) + r'(呢|怎么样了|是死是活)[^。！？\n]{0,14}[。！？]', b)
                if m: q = (n, m.group(0).strip())
        开口[k] = c; 挂念[k] = q
    红, 黄, 哑 = [], [], []
    行 = []
    for k in NAMES:
        v = 见[k]
        if not v:
            行.append((k, 0, None, None, 0, '—')); continue
        距 = 末章 - v[-1]
        t = 投注(k, v, 开口[k], 挂念[k])
        断 = 断之验(k, v, ch) if 距 > 限 else None
        if 距 <= 限:
            判 = '✓在场'
        elif t < 投注门槛:
            判 = '哑·本无欠'; 哑.append('%s（投注%d<%d）' % (k, t, 投注门槛))
        elif 断:
            判 = '断·已销'; 黄.append('%s·断於第%d章「%s」' % (k, 断[0], 断[1][:28]))
        elif k in 册:
            lim, _ = 册[k]
            if 末章 > lim:
                判 = '⛔逾其限'
                红.append('%s·挂账限第%d章，而今已第%d章——⛔挂了账又逾了自己那个限' % (k, lim, 末章))
            else:
                判 = '⚠已挂账'; 黄.append('%s·已挂账·限第%d章（未逾）' % (k, lim))
        else:
            判 = '⛔欠'
            红.append('%s·投注%d≥%d，而全书无「还」无「断」，亦无一笔挂账——⛔真欠'
                      % (k, t, 投注门槛))
        行.append((k, len(v), v[-1], 距, t, 判))
    if 报:
        print('════ 人账闸 · 至第%d章 ════' % 末章)
        print('  ★其律（与大问表同）：**可以欠，不可以不认**；逾%d章者须各有一笔挂账。' % 限)
        print('  %-5s %6s %6s %6s %5s   %s' % ('其人', '出场章', '末见', '距今', '投注', '判'))
        for k, c, l, d, t, j in 行:
            if c == 0:
                print('  %-5s %6s' % (k, '全书零见')); continue
            print('  %-5s %6d %6d %6d %5d   %s' % (k, c, l, d, t, j))
        if 哑:
            print('  ── 哑（投注不到门槛·本来无欠）──')
            print('   ℹ %s' % '｜'.join(哑))
            print('     ★而此判之要害在反面：**刻意去交代一个路人甲的下场，本身就是伤**——')
            print('       **读者会以为你还要用他**（手册110之反面：不该埋的钩子也别撒）。')
        if 黄:
            print('  ── 已落下落者（断／挂账）──')
            for x in 黄:
                print('   ⚠ %s' % x)
        if 红:
            print('  ── ⛔ ──')
            for x in 红:
                print('   ⛔ %s' % x)
            print('  ★其治有三，皆可（无高下）：**还／断／哑**；')
            print('    ★★而其治不是硬把人塞回来**（那必写成「他忽然出现了」）**；')
            print('    ★★是在 设定/人物挂账.md 上挂一笔，带三样：**其人／限第N章／其形写死**；')
            print('    ★★★而其形三条与大问同：**须落在物上｜须由场里的人自己撞见｜不许写成回忆段**；')
            print('    ★★★★**而写明他死了、走了、再不回来，即销账**——**账拦的是无声，不是欠**。')
        else:
            print('  ✓逐人各有其下落：无一人是「读者欠着而书里既没还也没断」。')
        print('  ★★而其限（§一⑤）：**本器只认名表上这 %d 人**；' % len(NAMES))
        print('    **书中无名之人（那一寨人、村干部、民工）本器一个字也不说。**')
    return 1 if 红 else 0


def 自测():
    好 = 坏 = 0
    def 断言(名, 真):
        nonlocal 好, 坏
        if 真: 好 += 1
        else:
            坏 += 1; print('  ⛔ %s' % 名)
    见, 末章 = 扫()
    ch = 逐章()
    # ①它认哪几样（§六④之头一项断言）
    断言('①名表 10 人｜canon档案5人｜门槛5', len(NAMES) == 10 and len(CANON) == 5 and 投注门槛 == 5)
    # ②投注之尺：路人与主角不许同分（此即头一版之错所在）
    断言('②小周之投注 < 门槛（4章·0句对白·挂念1句）',
         投注('小周', 见['小周'], 0, True) < 投注门槛)
    断言('②之二·老头之投注 ≥ 门槛（266章·282回开口·canon档案）',
         投注('老头', 见['老头'], 282, False) >= 投注门槛)
    断言('②之三·而旧式（拿「距」当判据）判不出二者之别——即其错之所在',
         (末章 - 见['小周'][-1]) > 限 and (末章 - 见['寨老'][-1]) > 限)
    # ③断之验：强词自明，弱词须与其名同句（头一版之自伤：寨老之断被判在一句与他无关的「没了」上）
    断言('③弱词须与其名同句：一句无其名之「没了」不算断',
         断之验('寨老', [108], [(108, p) for n, p in ch if n == 108]) is None
         or '寨老' in (断之验('寨老', [108], [(108, p) for n, p in ch if n == 108]) or (0, ''))[1])
    断言('③之二·强词五样、弱词六样，二等分明', len(断词强) == 5 and len(断词弱) == 6)
    # ④非陪跑之凭：旧式（大问挂账）里一个字也没有「寨老」
    dw = os.path.join(ROOT, '设定', '大问挂账.md')
    t = io.open(dw, encoding='utf-8').read() if os.path.exists(dw) else ''
    断言('④旧式（大问挂账）里没有「寨老」二字——本闸之红即在此', '寨老' not in t)
    # ⑤不许挖空：在场之人不许被判欠
    断言('⑤老头、钱满在场而不报欠',
         (末章 - 见['老头'][-1]) <= 限 and (末章 - 见['钱满'][-1]) <= 限)
    # ⑥册须收得住「其人＋限第N章」
    册 = 读挂账()
    断言('⑥寨老已入册且带其限', '寨老' in 册 and isinstance(册['寨老'][0], int))
    断言('⑥之二·小周、陈队已销账（判哑·不再入册）',
         '小周' not in 册 and '陈队' not in 册)
    print('  ── 负测·人账闸 %d/%d %s ──' % (好, 好 + 坏, '全通' if 坏 == 0 else '有败'))
    return 0 if 坏 == 0 else 1


if __name__ == '__main__':
    if '--自测' in sys.argv:
        sys.exit(自测())
    if '--扫' in sys.argv:
        见, 末章 = 扫()
        for k in NAMES:
            print(k, 见[k][:8], '…末见', 见[k][-1] if 见[k] else None)
        sys.exit(0)
    sys.exit(跑())
