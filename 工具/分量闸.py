import os, sys, json, io, re, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
表 = os.path.join(ROOT, '设定', '01_镇冢秘术_逐章施工与伏笔回收表.md')
硬 = 2500   # <此即硬错（≥73章）
审 = 2300   # <此即 REVIEW
起 = 334    # ⛔自此章起硬拦；此前只报不拦（其由见器头）


def 豁免之章():
    if not os.path.exists(表):
        return set()
    return set(int(m) for m in re.findall(r'第\s*(\d+)\s*章短章豁免',
                                          io.open(表, encoding='utf-8').read()))


def 诸章之净重():
    出 = {}
    for d in sorted(glob.glob(os.path.join(ROOT, '版本', '第*章'))):
        m = re.search(r'第(\d+)章', os.path.basename(d))
        p = os.path.join(d, '_台账.json')
        if not m or not os.path.exists(p):
            continue
        try:
            vs = json.load(io.open(p, encoding='utf-8')).get('版本') or []
        except Exception:
            continue
        if vs:
            w = vs[-1].get('soft', {}).get('净重')
            if isinstance(w, int) and w > 0:
                出[int(m.group(1))] = w
    return 出


def 查(净重, 豁免, 起章=None):
    """回 (新红, 旧报)。⛔二者皆 [(章, 净重)]。"""
    q = 起 if 起章 is None else 起章
    新, 旧 = [], []
    for n in sorted(净重):
        if n < 73 or n in 豁免 or 净重[n] >= 硬:
            continue
        (新 if n >= q else 旧).append((n, 净重[n]))
    return 新, 旧


def 自测():
    格 = []
    def 报(名, 得, 期): 格.append((名, 得 == 期, 得, 期))
    # ①足量者不报
    报('①足量不报', 查({334: 2500}, set())[0], [])
    # ②⛔不足者红（新章）
    报('②不足即红', 查({334: 2499}, set())[0], [(334, 2499)])
    # ③★施工表出了短章豁免者·不报（其令自书「可解」）
    报('③豁免不报', 查({334: 2000}, {334})[0], [])
    # ④<73 章不辖（其令自书「新章(≥73章)」）
    报('④七十二章不辖', 查({72: 1000}, set())[0], [])
    报('④七十三章在辖', 查({73: 1000}, set(), 起章=73)[0], [(73, 1000)])
    # ⑤★旧章（<起）只入旧报，不入新红（331 之真局：2271 而未豁免）
    新, 旧 = 查({331: 2271}, set())
    报('⑤旧章不入新红', 新, []); 报('⑤旧章入旧报', 旧, [(331, 2271)])
    # ⑥⛔无台账／净重为零者不报（未写之章非病）
    报('⑥无数不报', 查({}, set())[0], [])
    # ⑦界之齿：2500 不报，2499 报
    报('⑦界上不报', 查({334: 2500}, set())[0], [])
    报('⑦界下即报', [x[0] for x in 查({334: 2499}, set())[0]], [334])
