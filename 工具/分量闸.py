def 诸章之净重():
    出 = {}
    for d in sorted(glob.glob(os.path.join(ROOT, '版本', '第*章'))):
        m = re.search(r'第(\d+)章', os.path.basename(d))
        p = os.path.join(d, '_台账.json')
        if not m or not os.path.exists(p):
            continue
        try:
            vs = json.load(io.open(p, encoding='utf-8')).get('版本') or []
        except Exception:
            continue
        if vs:
            w = vs[-1].get('soft', {}).get('净重')
            if isinstance(w, int) and w > 0:
                出[int(m.group(1))] = w
    return 出


def 查(净重, 豁免, 起章=None, 线表=None):
    """回 (新红, 旧报)。⛔二者皆 [(章, 净重)]。
    ★0917 补：其界由线定（暗线 `暗硬`，余 `硬`）；⛔线不明者照主线之严。"""
    q = 起 if 起章 is None else 起章
    L = {} if 线表 is None else 线表
    新, 旧 = [], []
    for n in sorted(净重):
        if n < 73 or n in 豁免 or 净重[n] >= _硬之界(n, L):
            continue
        (新 if n >= q else 旧).append((n, 净重[n]))
    return 新, 旧


def 暗线之厚(净重, 线表, 末=None):
    """★每五章暗线之中，须有一章 ≥ `暗厚`。⛔返回 (过否, 其语)。
    ⛔**此条係换给暗线的那一条更难的线**：**带放宽了，而「不许整段地薄下去」这一条是新加的。**"""
    暗 = [n for n in sorted(净重) if 线表.get(n) == '暗']
    if 末 is not None:
        暗 = [n for n in 暗 if n <= 末]
    if len(暗) < 5:
        return True, '★暗线之章未满五篇，本条免测'
    窗 = 暗[-5:]
    数 = [净重[n] for n in 窗]
    if max(数) >= 暗厚:
        return True, ('✓末五篇暗线（%s）之中，第%d章 %d ≥ %d'
                      % ('／'.join(str(x) for x in 窗),
                         窗[数.index(max(数))], max(数), 暗厚))
    return False, ('⛔末五篇暗线（%s）之净重 %s，**无一篇及於 %d**'
                   '——★**带已放宽（暗线 %d 起），而放宽之价正是此条**：'
                   '**暗线不许整段地薄下去**；⛔其治在事之择（换一件更大的事），不在字数。'
                   % ('／'.join(str(x) for x in 窗),
                      '／'.join(str(x) for x in 数), 暗厚, 暗硬))


