    N = len(判)
    串, 见 = 同式([(n, x, t[-40:]) for n, x, t in 判]) if 判 else ('', [])
    L = ['════ 刻意之疲 ════（只照镜不拦·末 %d 章之章尾之形：%s）' % (N, '｜'.join('%s %d' % kv for kv in 计.items()))]
    L += ['  %s 第%d章 …%s' % (x.ljust(4, '　'), n, t[-40:]) for n, x, t in 判]
    if N >= 4:
        k, v = max(计.items(), key=lambda kv: kv[1])
        余 = '、'.join('%s %d' % (a, b) for a, b in 计.items() if b and a != k)
        if v == N:
            L.append('  镜·形一律：末 %d 尾俱「%s」。' % (N, k))
        elif v * 4 >= N * 3:
            L.append('  镜·形近一律：末 %d 尾之 %d 为「%s」（余：%s）。' % (N, v, k, 余))
        else:
            L.append('  镜·诸形之最多者「%s」%d／%d（未及四之三）。' % (k, v, N))
    if 串:
        L.append('  镜·收尾同式：「%s」见於 %d 章之尾（%s）；最新一章（第%d章）%s。' % (
            串, len(见), '、'.join('第%d章' % x for x in 见), 判[-1][0], '在其中' if 判[-1][0] in 见 else '不在其中'))
    elif N:
        L.append('  镜·收尾同式：无（末 %d 尾无一 ≥5 字之串同见於 ≥4 章）。' % N)
    return L, 计, 串


