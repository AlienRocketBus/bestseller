def _章号(名):
    _cn = {'零': 0, '〇': 0, '一': 1, '二': 2, '三': 3, '四': 4, '五': 5, '六': 6, '七': 7, '八': 8, '九': 9}
    m = re.search(r'第([零〇一二三四五六七八九十百千]+)章', 名)
    if not m:
        return 0
    tot = cur = 0
    for ch in m.group(1):
        if ch in _cn:
            cur = _cn[ch]
        elif ch in '十百千':
            tot += (cur or 1) * {'十': 10, '百': 100, '千': 1000}[ch]; cur = 0
    return tot + cur


def 末段(文):
    文 = 文.split('【本章亮点】')[0]   # ★亮点段是编者之注，非正文
    段 = [x.strip() for x in 文.split('\n') if x.strip() and x.strip() != '＊' and not x.startswith('#')]
    return 段[-1] if 段 else ''


def 句数(段):
    return len([x for x in _句末.split(段) if x.strip()])


def 收形(段):
    """→ 话收／单句短收／单句长收／多句收（末段空者 → 「无」）。
    话：引号内以句末之号收（「夯」一类引一字一词者⛔算话），且引号後无尾、或只余 ≤6 字之短尾（「走。」他说。）。"""
    t = 段.strip()
    if not t:
        return '无'
    k = max(t.rfind(c) for c in _闭引)
    if k > 0 and t[k - 1] in _话末 and any(c in t[:k] for c in _开引) \
            and len(re.sub(r'[\s。！？!?…，、]', '', t[k + 1:])) <= 6:
        return '话收'
    if 句数(t) <= 1:
        return '单句短收' if len(re.sub(r'\s', '', t)) <= 短限 else '单句长收'
    return '多句收'


