def 已交回执之章():
    out = set()
    # ⛔**0924 收回「案席」一名**（其详在 `全测.py::_已封版` 之注）：
    #   **案席係第 10 段所交，⛔它不是「走完了」之凭**；**363 之席断在第 10 段，而器里已作封版。**
    for k in ('作业单', '封版席'):
        for f in glob.glob(os.path.join(ROOT, '设定', '回执_*_第*章%s.md' % k)):
            m = re.search(r'第(\d+)章', os.path.basename(f))
            if m:
                out.add(int(m.group(1)))
    return out


def 有十一轮(n):
    return os.path.exists(os.path.join(ROOT, '版本', '第%d章' % n, '_十一轮.json'))


def 判(章集, 有之者, 起章=None):
    """⛔纯判·不碰盘。返回 (新红, 旧缺)。"""
    q = 起 if 起章 is None else 起章
    新, 旧 = [], []
    for n in sorted(章集):
        if n in 有之者:
            continue
        (新 if n >= q else 旧).append(n)
    return 新, 旧


