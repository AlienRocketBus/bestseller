#   ③上章已出而本章又入，而本章册全文无一句它怎么回来的（借／拿／递／取／回／还／出／带）→ ⚠。
#   ★只⛔第①问：其主是死账，换了就是换了；②③係提醒，逼这一章说一句话。
def 线(body):
    """三值（与 开轮六检._line_of 同尺）：主（我≥3/千）｜她（沈鸢）｜他（霍钧／黎东来之视角章）。"""
    净 = len(re.sub(r'\s', '', body)) or 1
    if body.count('我') / 净 * 1000 >= 3:
        return '主'
    return '她' if body.count('她') >= body.count('他') else '他'


def 上一同线章(n):
    """往前找与第n章同线且有器物册之章。"""
    b = 正文(n)
    if b is None:
        return None
    我线 = 线(b)
    for k in range(n - 1, max(0, n - 12), -1):
        bk = 正文(k)
        if bk is None or 线(bk) != 我线:
            continue
        if os.path.exists(os.path.join(ROOT, '版本', '第%d章' % k, '_器物.md')):
            return k
    return None


def 比(prev_rows, cur_rows, cur_body, cur_册文):
    """返回 (坏, 疑)。纯函数，供负测。"""
    坏, 疑 = [], []
    cur = {r['名']: r for r in cur_rows}
    for r in prev_rows:
        名 = r['名']
        c = cur.get(名)
        if c is not None:
            if r.get('主') and c.get('主') and r['主'] != c['主']:
                坏.append('★%s·其主换了：上一同线章「主=%s」，本章「主=%s」——一件东西的主人不许隔章换人（303铜听针之伤）' % (名, r['主'], c['主']))
            if '出' in r and '入' in c:
                # ★只看册之注文，不看格行（格行「出=134」自带「出」字，会把这一问蒙过——负测⑱所逮）
                窗 = [x for x in re.findall(r'[^。\n]*' + re.escape(名) + r'[^。\n]*', cur_册文)
                     if not re.search(r'(入|用|出)\s*=\s*\d', x)]
                if not any(re.search(r'借|拿|递|取|回|还|出|带|拆', x) for x in 窗):
                    疑.append('%s·上一同线章已出（拍%s），本章又入（拍%s）——册上须写一句它怎么回来的' % (名, r['出'], c['入']))
        else:
            if '用' in r and '出' not in r:
                验名 = r.get('验名', 名)
                if cur_body.count(验名) == 0:
                    疑.append('%s·上一同线章末了还在手上（有用无出），本章册上无它、白文亦无其名——是不过手了，还是忘了' % 名)
    return 坏, 疑


def 跨章(n, quiet=False):
    k = 上一同线章(n)
    if k is None:
        if not quiet:
            print('  ── 跨章 ──\n   ℹ往前十二章无同线之册，跨章不比。')
        return [], []
    prev, _, _ = 读册(k)
    cur, _, 册文 = 读册(n)
    b = 正文(n)
    if prev is None or cur is None or b is None:
        return [], []
    坏, 疑 = 比(prev, cur, b, 册文)
    if not quiet:
        print('  ── 跨章（对上一同线章·第%d章之册）──' % k)
        for x in 坏:
            print('   ⛔ ' + x)
        for x in 疑:
            print('   ⚠ ' + x)
        if not 坏 and not 疑:
            print('   ✓ 同名之器其主未换；上章在手者本章皆有声。')
    return 坏, 疑


def 跑(n):
    _章 = n   # ★下文循环有复用 n 者，跨章须以此为章号
    b = 正文(n)
    if b is None:
        print('⛔ 取不到第%d章正文' % n)
        return 2
    bs = 分拍(b)
    rows, p, 册文 = 读册(n)
    print('████ 器物点名 · 第%d章 ████' % n)
    print('  ★其判据：本章自报之器物册（%s）；★★另一路只提醒，不判。' % os.path.relpath(p, ROOT))
    print('  ★★★全章 %d 拍。' % len(bs))
    坏 = []
    if rows is None:
        print('  ⛔ 器物册不在：%s' % os.path.relpath(p, ROOT))
        print('     ★其式：器物名｜入=拍号｜用=拍号｜出=拍号（每器一行）')
        return 2
    if not rows:
        坏.append('★器物册在而一行也没有——一章之内一件器物也不过手，须当场答其由')
    print('  ── 逐件点名 ──')
    for d in rows:
        名 = d['名']
        line = '   %-8s' % 名
        for g in ('入', '用', '出'):
            if g not in d:
                line += ' %s=⛔缺' % g
                坏.append('★%s·缺「%s」——令§三③：入、用、出，缺一即伤' % (名, g))
                continue
            i = d[g]
            if not (1 <= i <= len(bs)):
                line += ' %s=⛔拍%d不在' % (g, i)
                坏.append('★%s·「%s」指拍%d，而全章只 %d 拍' % (名, g, i, len(bs)))
            elif d.get('验名', 名) not in bs[i - 1]:
                line += ' %s=⛔拍%d无其名' % (g, i)
                坏.append('★%s·「%s」指拍%d，而那一拍的白文里没有「%s」三字——'
                          '拍号是抄的，不是数的' % (名, g, i, d.get('验名', 名)))
            else:
                line += ' %s=拍%-4d' % (g, i)
        # ★序之验（2026-09-04立）：入≤用≤出，且入<出——**「来去」是有方向的**。
        序 = [d[g] for g in ('入', '用', '出') if isinstance(d.get(g), int)]
        if len(序) == 3:
            # ★先验「入出同拍」再验「序倒」：**同拍是更准的一句话**，
            #   若先验序，一份「入=6｜用=91｜出=6」之册会被判作「倒」，而它真正的病是没动。
            if 序[0] == 序[2] and not d.get('出开口') and not d.get('出有去处'):
                line += ' ⛔入出同拍'
                坏.append('★%s·「入」与「出」同指拍%d——'
                          '一件东西在同一拍上又进来又出去，那不是来去，是没动'
                          % (名, 序[0]))
            elif 序[0] == 序[2] and d.get('出有去处'):
                # ★0918：**它走了，只是这一章给它的路只有一拍长**；其去处已当场写明，故不判红。
                line += ' （入出同拍·而出已写明去处）'
            elif 序[0] == 序[2] and d.get('出开口'):
                # ★开口＝**它今日没有出去**，那个拍号说的是「它最後在哪儿」，不是「它从哪儿走的」。
                #   故此处不判红，只印一行，让人看得见这件东西是留在场上的。
                line += ' （出係开口·未离场）'
            elif not (序[0] <= 序[1] <= 序[2]):
                line += ' ⛔序倒'
                坏.append('★%s·三格之拍号倒了（入=%d｜用=%d｜出=%d）——'
                          '令§三③「器物须有来去」，来去是有方向的：'
                          '一件东西不能先出后入' % (名, 序[0], 序[1], 序[2]))
        print(line)
        # ★★★★★【301第9轮立·其名逐拍摆出来】
        #   ★其红在哪一行：本日删拍106之後，本子之「出」旧号 129 一格未改，而器印 ✓3件俱全——
        #     ★★因拍129 亦有「本子」二字（怀里那本子，湿了就没有了），器只验得「其名在」，
        #     ★★★验不得「其名是不是同一处」（令§一⑤）。
        #   ★而本行不判，只把料摆出来：三格之号与其名所在逐拍并列，
        #     ★★一格抄旧而未重数者，肉眼一比即见（本日之 129 不在 128 之位）。
        # ★而此行亦用别名去数（否则一件用别名验过的物，这一行会印「共 0 拍」，
        #   ★★而那个 0 是查法之果，不是场之实——一道闸自己印一个假数，比不印更坏）。
        _验 = d.get('验名', 名)
        在 = [j + 1 for j, x in enumerate(bs) if _验 in x]
        print('     ★「%s」在本章共 %d 拍（以「%s」数）：%s'
              % (名, len(在), _验, ','.join(str(x) for x in 在[:24])))
    # ★★★★★【301第10轮立·册之另一半：带引文之拍号，逐条拿去正文里重找】
    #   ★其红在哪一行：301第10轮逐条重找，册里**七处**带引文之拍号是旧的——
    #     本子之义写「出＝拍129」（数据行已改作128）｜指甲之读数四处（25至28／31至32／42、45／126）
    #     ｜本轮之一刀写「补拍130／131」｜判据行写「针25拍」。
    #   ★★而第9轮所加之「其名在本章共N拍」只治得了数据行那一半：
    #     ★★★**一份册有两半：器读得懂的那一半，和只有人读得懂的那一半；器从前只验前一半。**
    #   ★★★★其法：凡册里作「拍N（引文…）」之形者，取引文头八字去正文里找，
    #     找着而不在拍N者即红；引文里一个字也找不着者只⚠（多为转述，非引）。
    #   ★★★★★它认哪几样：**只认「拍N（…」这一形**（全角、半角括号皆认）；
    #     本书同类共几样：七份器物册（296至301）之内，此形共 41 处——故成群，非为一章而立。
    for m in re.finditer(r'拍(\d+)\s*[（(]([^）)]{4,40})', 册文 or ''):
        n = int(m.group(1))
        q = re.sub(r'[｜*★\s]', '', m.group(2))[:8]
        if len(q) < 4:
            continue
        在 = [j + 1 for j, x in enumerate(bs) if q in x]
        if not 在:
            continue
        if n not in 在:
            坏.append('★册之注·「拍%d（%s…」——那一句实在拍%s，不在拍%d：'
                      '带引文之拍号亦是抄的，不是数的'
                      % (n, q, ','.join(str(x) for x in 在), n))
    # ── 未报之疑（只提醒）──
    报了 = {d['名'] for d in rows}
    册名 = 报了 | {d['验名'] for d in rows if d.get('验名')}
    疑, 已答 = [], []
    for k in 手器全集:
        if k in 册名:
            continue
        for w, 拍 in 词计(bs, k, 册名).items():
            if len(拍) < 3 or w in 册名 or any(w == q for q, _ in 疑 + 已答):
                continue
            (已答 if ('「%s」' % w) in 册文 else 疑).append((w, len(拍)))
    if 疑 or 已答:
        print('  ── 未报之疑（按词认·只提醒，不判）──')
        for k, c in 疑:
            print('   ⚠「%s」占 %d 拍而册上没有——是它不过手，还是漏报了？' % (k, c))
        if 已答:
            print('   ℹ册之注已以「」提过，不再问：%s'
                  % '、'.join('「%s」%d拍' % x for x in 已答))
    # ── 身上的尺之疑（开集·只提醒，不判）──
    尺 = {}
    for i, x in enumerate(bs, 1):
        for pat in 尺之型:
            for mm in re.finditer(pat, x):
                尺.setdefault(mm.group(1), []).append(i)
    尺疑 = [(k, v) for k, v in sorted(尺.items())
            if k not in 报了 and ('「%s」' % k) not in 册文]
    if 尺疑:
        print('  ── 身上的尺之疑（开集·只提醒，不判）──')
        for k, v in 尺疑:
            print('   ⚠本章有一把身上的尺「%s」（拍%s），而册上一字未提——'
                  '入不入册，须当场说一句' % (k, '、'.join(str(z) for z in v[:4])))
    # ── 跨章（2026-09-05·机制总审丙①）──
    坏2, _疑2 = 跨章(_章)
    坏 += 坏2
    if 坏:
        print('  ⛔ 器物点名 %d 处未过' % len(坏))
        for x in 坏:
            print('     ⛔ ' + x)
        return 1
    print('  ✓ 器物点名 %d 件俱全（入／用／出三格皆有拍号，且逐拍验过其名在；跨章其主未换）' % len(rows))
    return 0


