def 词计(bs, k, 册名):
    """k 在诸拍里各处所在之词 → {词: [拍号…]}；册名所覆者（已报）、非器之词、系器之词（归其器）不入。纯函数，供负测。"""
    候 = [(w, '册') for w in 册名 if k in w] + [(w, '物') for w in 别物之词.get(k, ())] \
        + [(w, '系') for w in 系器之词.get(k, {})] + [(w, '非') for w in 非器之词.get(k, ())]
    候.sort(key=lambda x: -len(x[0]))                     # 最长者先；同长则册先於物、物先於系、系先於非
    出 = {}
    for i, x in enumerate(bs, 1):
        for m in re.finditer(re.escape(k), x):
            p, 词, 类 = m.start(), k, None
            for w, c in 候:
                if any(w[j:j + len(k)] == k and p - j >= 0 and x.startswith(w, p - j)
                       for j in range(len(w) - len(k) + 1)):
                    词, 类 = w, c
                    break
            if 类 in ('册', '非', '系'):
                continue
            拍 = 出.setdefault(词, [])
            if not 拍 or 拍[-1] != i:
                拍.append(i)
    return 出

