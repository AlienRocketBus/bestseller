# -*- coding: utf-8 -*-
"""外事尺（2026-09-08 立·为「一章比一章好看」之案 #14）

★所治之伤：诸席通读全书，点了三十二章「掉下去」，而三十二条判语没有一条落在数上——
  「它整章在原地记账」「这一章外头什么也没发生」「它自己在行 393 交了底」。
  ★★而看官之律②早已写着：**「读者会觉得闷」不算判；「拍 93 至 106 连十四拍无一动作」才算。**
  ★★★故此器只办一件事：**把「外头有没有事」量成一个数**，让弱不弱由数说，不由口味说。

★★★★【它认哪几样·本书同类共几样】（令§六④）
  它只认两样，两样都是字面之实，机器判得死：
    ①**有人之拍**——一拍里出现「我」以外的人（老头｜钱满｜刘二｜东头｜沈鸢｜苏衍｜后生）。
      全书正文命中之拍 —— 跑一遍即印。
    ②**有话之拍**——一拍里有 “ （本书之说话式；全书 8952 处，而「」是引文与心里的话，共 2248 处，**此器不认它**）。
  外事拍 ＝ ①∪②。**它不认「手上在动」**：因「他把本子摊在膝盖上」也是手在动，而那正是在原地记账。
  ★**它不判红，也不接进全测**（令§十三②：闸须判得死；而「一章好不好看」判不死，
    强判者必大量假红，而假红多的闸终被绕，绕过的闸等於没有）。**它只报数与位次，供人裁。**
    它之位在 起草闸 乙层（只列不判，供落笔之席自看）。

⛔⛔⛔【立此器之日即验其不称职·须与器同存，不许删】（2026-09-08）
  立它是为了答一个问：**诸席点名「掉下去」的那三十二章，掉在哪儿？**
  我的头一个猜想是「外头什么也没发生」。**跑出来的数把这个猜想打了。**
    · 三十二章里，落在**同线**最低四分位者 **10 章**；若是随手点名，期望约 **8 章**。
    · 而 222 在暗线是 **41/41（最高）**、225 是 43/51、276 是 41/51、287 是 40/51——
      **四章明明在自己那条线的最上头，诸席照样说它掉下去。**
  第二个猜想是「复读前章」（通读册说 160 是「141:257—259 之原句复读」）。**这个也打了**：
    · 以「本章与前三章之逐字≥10 公共串所覆盖之拍」计，三十二章里落在最高四分位者 **6 章**，
      **比随手点名的 8 还少。**
    · 有意思的是它**逮得住通读册明写的那几章**（160＝0.26／163＝0.17／165＝0.16／174＝0.15，
      皆在全书最高十五名之内）——**它量对了一样东西，只是那三十二章不是为这一样被点名的。**

  ★★**故此器之结论，是一条否定**：**那三十二章不是一种病。**
    它们是不同的席、读不同的段、按各自的由头点的名；
    **拿一个数去统它们，是把三十二件事当成一件办。**
  ★★★而这一条否定值它自己的价钱：**#14 不许由一道数来办，得由读者之眼一章一章地读**
    （看官之律②：「读者会觉得闷」不算判，「拍 93 至 106 连十四拍无一动作」才算）。
  ★★★★它今日留下来，不是因为它办成了 #14，是因为**它量得准第 306 章往后每一章外头有多少事**：
    主线中位 0.10、暗线中位 0.02，是这本书自己走出来的度；新章离这个度太远，落笔之席该自己看一眼。

用法：
  python3 工具/外事尺.py            全书逐章之外事率与位次（低十五章另列）
  python3 工具/外事尺.py N          一章之详（逐拍标出它凭哪一样算外事）
  python3 工具/外事尺.py --弱        只印诸席点名之三十二章，与全书之位次并看
"""
import io, os, re, sys

根 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(根, '工具'))
from 亮点对表 import 诸章                                  # noqa: E402

人 = re.compile(r'老头|钱满|刘二|东头|沈鸢|苏衍|后生|那个人|那人')
# ★立器之日即验其不称职（与器同存，不许删）：
#   头一版之名册只列六名，於是暗线诸章（235／244／247／249／251／253／255…）
#   **整章零命中**——因沈鸢那一线里，对面那一个从头到尾叫「那个人」，一次也没叫过名字。
#   ★一个只认得住名字的尺，量不了一整条不叫名字的线。今补「那个人／那人」。
话 = '“'

# 诸席通读全书所点名「掉下去」之章（设定/全书通读_1至305章_20260905.md）
弱三十二 = [182, 184, 188, 191, 194, 204, 208, 212, 217, 222, 225, 228, 230, 233,
            238, 239, 241, 243, 250, 254, 260, 261, 265, 266, 275, 276, 278, 287,
            290, 296, 297, 302]


def 诸拍(txt):
    """★只切「以＊分拍」之章。全书 305 章里，**有＊者 159 章，无＊者 146 章**（皆第181章以前，
    立拍之式尚未定）；无＊之章整篇只切得出一拍，率非 0 即 1，量它等於没量——
    **故此器明说它不判那 146 章**（同 亮点在.py 之例：judge 得了的才判，判不了的写在脸上）。
    而诸席点名之三十二章尽在 182—302 之间，一章也不落在那 146 章里。"""
    bw = txt.split('【本章亮点')[0]
    if '＊' not in bw:
        return None
    return [re.sub(r'\s', '', p) for p in bw.split('＊') if p.strip()]


def 量(txt):
    P = 诸拍(txt)
    if not P:
        return None
    有人 = [p for p in P if 人.search(p)]
    有话 = [p for p in P if 话 in p]
    外 = [p for p in P if 人.search(p) or 话 in p]
    return dict(拍=len(P), 有人=len(有人), 有话=len(有话), 外事=len(外),
                率=len(外) / len(P))


def 全书():
    章 = 诸章()
    d = {}
    for n, p in sorted(章.items()):
        r = 量(io.open(p, encoding='utf-8').read())
        if r:
            d[n] = r
    return d



def 线():
    """★依 比带 之律（「一把带，取错了比的人，就把三处好文判成了伤」）：
    主线（苏衍·坑边四个人）与暗线（沈鸢·一间屋一个人）不能拿同一条带量——
    暗线里对面那一样是「它」，本来就不是人；一章零个人，在暗线是常态，在主线才是病。
    线之属取自施工表锁定行内之「主线／暗线」二字。"""
    import re as _re
    d = {}
    t = io.open(os.path.join(根, '设定', '01_镇冢秘术_逐章施工与伏笔回收表.md'), encoding='utf-8')
    for ln in t:
        m = _re.match(r'\| (\d+) \| 锁定 \|(.*)', ln)
        if not m:
            continue
        n, body = int(m.group(1)), m.group(2)
        if '暗线' in body:
            d[n] = '暗'
        elif '主线' in body:
            d[n] = '主'
    return d


def _位次(d, L=None):
    """位次只在同线之内排（比带之律）；线不明者自成一组。"""
    L = L or {}
    out = {}
    for g in set(L.get(n, '?') for n in d):
        ns = sorted([n for n in d if L.get(n, '?') == g], key=lambda n: d[n]['率'])
        for i, n in enumerate(ns):
            out[n] = (i + 1, len(ns), g)
    return out


def main():
    a = sys.argv[1:]
    d = 全书()
    L = 线()
    位 = _位次(d, L)
    组 = {}
    for n in d:
        组.setdefault(L.get(n, '?'), []).append(n)

    def 印组():
        for g in sorted(组):
            ns = sorted(组[g], key=lambda n: d[n]['率'])
            r = [d[n]['率'] for n in ns]
            m = len(r)
            print('  ── %s线 %d 章：中位 %.2f｜四分位 %.2f／%.2f｜最低 %.2f｜最高 %.2f'
                  % (g, m, r[m // 2], r[m // 4], r[3 * m // 4], r[0], r[-1]))

    if a and a[0] == '--弱':
        print('════ 外事尺 · 诸席点名之三十二章（同线之内排位·比带之律）════')
        印组()
        低 = 全 = 0
        for n in 弱三十二:
            if n not in d:
                continue
            r = d[n]
            i, m, g = 位[n]
            全 += 1
            记 = ''
            if i <= max(1, m // 4):
                低 += 1
                记 = '  ★同线最低四分位'
            print('  %3d[%s]  外事率 %.2f（%2d/%2d 拍）  同线位次 %3d/%d%s'
                  % (n, g, r['率'], r['外事'], r['拍'], i, m, 记))
        print('  ★可量者 %d 章，落在同线最低四分位者 **%d 章**；若诸席是随手点名，期望约 %d 章。'
              % (全, 低, 全 // 4))
        return
    if a and a[0] == '--度' and len(a) > 1:
        n = int(a[1])
        if n not in d:
            print('  外事之度：第%d章无＊，此器不判它。' % n)
            return
        r = d[n]
        i, m, g = 位[n]
        带 = {'主': 0.10, '暗': 0.02}.get(g)
        print('  本章 %d 拍，外头有事者 %d 拍，率 %.2f（%s线之中位 %s；同线位次 %d/%d）'
              % (r['拍'], r['外事'], r['率'], g, ('%.2f' % 带) if 带 else '未定', i, m))
        print('  ★只报不判：立器之日已验过，此数量不出诸席点名之弱（三十二章里只十章落在低四分位，'
              '随手点名之期望是八章）；它是一面镜子，不是判词。')
        return
    if a and a[0].isdigit():
        n = int(a[0])
        章 = 诸章()
        P = 诸拍(io.open(章[n], encoding='utf-8').read())
        if P is None:
            print('  第%d章无＊，此器不判它（无＊之章 146 章，皆第181章以前）。' % n)
            return
        for i, p in enumerate(P, 1):
            m = ('人' if 人.search(p) else '') + ('话' if 话 in p else '')
            print('  %3d %-2s %s' % (i, m or '·', p[:46]))
        r = d[n]
        i, m, g = 位[n]
        print('  ── 第%d章[%s线]：%d 拍，外事 %d 拍，率 %.2f，同线位次 %d/%d ──'
              % (n, g, r['拍'], r['外事'], r['率'], i, m))
        return
    print('════ 外事尺 · 有＊之章 %d（无＊之 146 章不判·皆第181章以前）════' % len(d))
    print('  外事拍＝一拍里有「我」以外的人，或有一句说出口的话（“）')
    印组()
    for g in sorted(组):
        print('  ── %s线·最低十章 ──' % g)
        for n in sorted(组[g], key=lambda n: d[n]['率'])[:10]:
            r = d[n]
            print('  %3d  %.2f（%2d/%2d 拍）%s'
                  % (n, r['率'], r['外事'], r['拍'], '（诸席点名）' if n in 弱三十二 else ''))


if __name__ == '__main__':
    main()
