ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CN = {'零': 0, '〇': 0, '一': 1, '二': 2, '三': 3, '四': 4, '五': 5, '六': 6, '七': 7, '八': 8, '九': 9}


def 章号(f):
    m = re.search(r'第([零〇一二三四五六七八九十百千]+)章', os.path.basename(f))
    if not m:
        return 0
    tot, cur = 0, 0
    for ch in m.group(1):
        if ch in CN:
            cur = CN[ch]
        elif ch == '十':
            tot += (cur or 1) * 10; cur = 0
        elif ch == '百':
            tot += (cur or 1) * 100; cur = 0
        elif ch == '千':
            tot += (cur or 1) * 1000; cur = 0
    return tot + cur


def 正文(f):
    t = io.open(f, encoding='utf-8').read().split('【本章亮点】')[0]
    return re.sub(r'^.*?第.+?章[^\n]*\n', '', t, count=1, flags=re.S)


# ★★2026-09-01 收紧（首版把「引书上的字」当成了出声 ⛔）：
#   ★本书之「」是引**纸上写的字**（285之「四个人」是本子上那一格、286之「三」是第十五行那个字），
#     ★★而 “”（全角双引号）才是说话——其数 1—99章 2,876 处、240—287章 0 处，二者泾渭分明。
#   ★★★故只认二形：①“…” 之内；②「说／问／答／喊／叫＋：＋短句。」
#     ★★★★若把「」也算进来，280—287 会印出「出声 4—16 句」，
#        ★而那一章八章之内真正出声的只有四句十一个字——**量错了就等於没量**。
_引 = re.compile(r'[“]([^”\n]{1,60})[”]')
# ★而此式仍有一分不准，据实记下（不许假装它准）：
#   ★★「我可以改一句去问：昨天你在水里，等着了没有」——那个「问」是打算，不是出口 ⛔；
#     ★★★287 之 2 句里有 1 句是此形，285 之 2 句里亦有 1 句。
#   ★★★★故**出声句之数宁可偏多，不许偏少**；而真正不含糊的那一格是引号之曲线，
#     ★它由标点定，一个字也不含糊：1—99章 2,876 → 100—199章 2,461 → 200—239章 572 → 240—287章 **0**。
_冒 = re.compile(r'(?:^|[。！？\n])[^\n]{0,12}?(?:说|问|答|喊|叫|吼)(?:了[^：:\n]{0,6})?[：:]\s*([^。！？\n]{1,40}[。！？])')


def 量(f):
    t = 正文(f)
    出声 = []
    for m in _引.finditer(t):
        s = m.group(1)
        if len(re.sub(r'[^一-龥]', '', s)):
            出声.append(s)
    for m in _冒.finditer(t):
        s = m.group(1)
        if s not in ''.join(出声):
            出声.append(s)
    字 = sum(len(re.sub(r'[^一-龥]', '', s)) for s in 出声)
    # ★别人问他的：出声之中带问号或以疑问词收者
    问 = sum(1 for s in 出声 if re.search(r'[？?]$|(吗|呢|几|哪|谁|怎么|什么|多少)[。？?]?$', s))
    return {'章': 章号(f), '出声句': len(出声), '出声字': 字, '他人之问': 问,
            '心里之问': t.count('。') and len(re.findall(r'[？?]', t)), '句': 出声[:4]}


def 全书(n_tail=None):
    rows = []
    for f in sorted(glob.glob(os.path.join(ROOT, '正文', '*.md')), key=章号):
        rows.append(量(f))
    rows.sort(key=lambda x: x['章'])
    return rows[-n_tail:] if n_tail else rows


def 连零(rows):
    """★返回末尾连续出声为零之章数。"""
    n = 0
    for r in reversed(rows):
        if r['出声句'] == 0:
            n += 1
        else:
            break
    return n


