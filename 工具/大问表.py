import glob, io, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
上限 = 40
CN = {'零': 0, '〇': 0, '一': 1, '二': 2, '三': 3, '四': 4, '五': 5, '六': 6, '七': 7, '八': 8, '九': 9}

# ★八样·逐样一句「读者心里挂着的那一问」，并附其词（正文之词，非机制词）
表 = [
    ('玉',       ['玉'],                 '那两半玉合上之後，它到底是什么'),
    ('血图',     ['血图'],               '爷爷留下那张图上画的是什么'),
    ('悬赏',     ['悬赏', '十万'],        '十万那张网还追不追得着他'),
    ('听针',     ['听针'],               'E4须用之器：隔水听得见听不见'),
    ('寨里那些人', ['寨老', '岩生'],       '他本来是去救的那一寨人，还在不在'),
    ('走路的理由', ['想活', '走到头是什么'], '他为什么还在往下走'),
    ('爷爷',     ['爷爷'],               '爷爷那一句「发烫就回来」指的是谁'),
    ('地窖',     ['地窖'],               '老宅地窖那一夜到底发生了什么'),
]


def 章号(f):
    m = re.search(r'第([零〇一二三四五六七八九十百千]+)章', os.path.basename(f))
    if not m:
        return 0
    tot, cur = 0, 0
    for ch in m.group(1):
        if ch in CN:
            cur = CN[ch]
        elif ch == '十':
            tot += (cur or 1) * 10; cur = 0
        elif ch == '百':
            tot += (cur or 1) * 100; cur = 0
        elif ch == '千':
            tot += (cur or 1) * 1000; cur = 0
    return tot + cur


def 白文(f):
    t = io.open(f, encoding='utf-8').read().split('【本章亮点】')[0]
    return re.sub(r'^.*?第.+?章[^\n]*\n', '', t, count=1, flags=re.S)


def 量():
    fs = sorted(glob.glob(os.path.join(ROOT, '正文', '*.md')), key=章号)
    末 = 章号(fs[-1]) if fs else 0
    库 = [(章号(f), 白文(f)) for f in fs]
    out = []
    for 名, 词, 问 in 表:
        章 = [n for n, t in 库 if any(w in t for w in 词)]
        末见 = max(章) if 章 else 0
        out.append({'名': 名, '问': 问, '几章': len(章), '末见': 末见,
                    '缺': (末 - 末见) if 末见 else 末, '逾': (末 - 末见) > 上限 if 末见 else True})
    return 末, out


挂账档 = os.path.join(ROOT, '设定', '大问挂账.md')


def 挂():
    """读挂账册：{其样: 限章}。★其律见 设定/大问挂账.md。"""
    if not os.path.exists(挂账档):
        return {}
    out = {}
    for ln in io.open(挂账档, encoding='utf-8'):
        if not ln.startswith('|'):
            continue
        c = [x.strip() for x in ln.strip().strip('|').split('|')]
        if len(c) < 6 or c[-1] != '挂':
            continue
        m = re.search(r'(\d+)', c[3])
        if m:
            out[c[0]] = int(m.group(1))
    return out


def 报(quiet=False):
    末, rows = 量()
    逾 = [r for r in rows if r['逾']]
    G = 挂()
    无挂 = [r['名'] for r in 逾 if r['名'] not in G]
    # 挂了账又逾了自己那个限的：末见还在挂账之前，而限已过 → 拦
    逾限 = [(r['名'], G[r['名']]) for r in 逾 if r['名'] in G and 末 > G[r['名']]]
    if not quiet:
        print('════ 大问表 · 以第%d章计（上限 %d 章）════' % (末, 上限))
        print('  【其律】可以欠，不可以不认：逾限者须各有一笔挂账，挂账须带限章；逾自定之限而未还者，拦。')
        print('  %-10s %-6s %-7s %-7s %s' % ('其样', '出现', '末见', '缺席', '读者挂着的那一问'))
        for r in rows:
            print('  %-10s %-6d %-7s %-7s %s %s'
                  % (r['名'], r['几章'], ('第%d章' % r['末见']) if r['末见'] else '全书无',
                     '%d章' % r['缺'], '⛔' if r['逾'] else '✓', r['问']))
        print('  ── 逾上限者 %d 样 ──' % len(逾))
        if 逾:
            print('  ★而其治不在补写一段回忆**，在让它在手上再出现一回**：')
            print('    ★★一个动作、一个数、一次比——不解释、不回忆、不说破。')
        # ★★★★2026-09-03·八造：改「只报不拦」为「无声不许」。可以欠，不可以不认。
        print('  ── 挂账（设定/大问挂账.md）──')
        if 无挂:
            print('  ⛔ 逾限而无一笔挂账者 %d 样：%s' % (len(无挂), '、'.join(无挂)))
            print('     ★其治不是当章补喂，是**在册上认一笔**：其样／限第N章／其形写死（须落在物上·不许写成回忆）。')
        if 逾限:
            print('  ⛔ 挂了账而逾了自己那个限者 %d 样：%s'
                  % (len(逾限), '、'.join('%s（限%d章，今%d章）' % (a, b, 末) for a, b in 逾限)))
            print('     ★**一道靠自己给自己写限来销的账，若逾了限还不出声，它就不是账。**')
        if not 无挂 and not 逾限:
            print('  ✓ 逾限者俱已挂账，且无一笔逾其自定之限。')
    return 逾, 无挂, 逾限


if __name__ == '__main__':
    _, _wg, _yx = 报()
