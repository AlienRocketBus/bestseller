import glob, io, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
上限 = 40
CN = {'零': 0, '〇': 0, '一': 1, '二': 2, '三': 3, '四': 4, '五': 5, '六': 6, '七': 7, '八': 8, '九': 9}

# ★八样·逐样一句「读者心里挂着的那一问」，并附其词（正文之词，非机制词）
表 = [
    ('玉',       ['玉'],                 '那两半玉合上之後，它到底是什么'),
    ('血图',     ['血图'],               '爷爷留下那张图上画的是什么'),
    ('悬赏',     ['悬赏', '十万'],        '十万那张网还追不追得着他'),
    ('听针',     ['听针'],               'E4须用之器：隔水听得见听不见'),
    ('寨里那些人', ['寨老', '岩生'],       '他本来是去救的那一寨人，还在不在'),
    ('走路的理由', ['想活', '走到头是什么'], '他为什么还在往下走'),
    ('爷爷',     ['爷爷'],               '爷爷那一句「发烫就回来」指的是谁'),
    ('地窖',     ['地窖'],               '老宅地窖那一夜到底发生了什么'),
]


def 章号(f):
    m = re.search(r'第([零〇一二三四五六七八九十百千]+)章', os.path.basename(f))
    if not m:
        return 0
    tot, cur = 0, 0
    for ch in m.group(1):
        if ch in CN:
            cur = CN[ch]
        elif ch == '十':
            tot += (cur or 1) * 10; cur = 0
        elif ch == '百':
            tot += (cur or 1) * 100; cur = 0
        elif ch == '千':
            tot += (cur or 1) * 1000; cur = 0
    return tot + cur


def 白文(f):
    t = io.open(f, encoding='utf-8').read().split('【本章亮点】')[0]
    return re.sub(r'^.*?第.+?章[^\n]*\n', '', t, count=1, flags=re.S)


def 量():
    fs = sorted(glob.glob(os.path.join(ROOT, '正文', '*.md')), key=章号)
    末 = 章号(fs[-1]) if fs else 0
    库 = [(章号(f), 白文(f)) for f in fs]
    out = []
    for 名, 词, 问 in 表:
        章 = [n for n, t in 库 if any(w in t for w in 词)]
        末见 = max(章) if 章 else 0
        out.append({'名': 名, '问': 问, '几章': len(章), '末见': 末见,
                    '缺': (末 - 末见) if 末见 else 末, '逾': (末 - 末见) > 上限 if 末见 else True})
    return 末, out


def 报(quiet=False):
    末, rows = 量()
    逾 = [r for r in rows if r['逾']]
    if not quiet:
        print('════ 大问表 · 以第%d章计（上限 %d 章）════' % (末, 上限))
        print('  【其律】只报不拦。读者心里挂着的那几样，各自最後一次被喂是第几章。')
        print('  %-10s %-6s %-7s %-7s %s' % ('其样', '出现', '末见', '缺席', '读者挂着的那一问'))
        for r in rows:
            print('  %-10s %-6d %-7s %-7s %s %s'
                  % (r['名'], r['几章'], ('第%d章' % r['末见']) if r['末见'] else '全书无',
                     '%d章' % r['缺'], '⛔' if r['逾'] else '✓', r['问']))
        print('  ── 逾上限者 %d 样 ──' % len(逾))
        if 逾:
            print('  ★而其治不在补写一段回忆**，在让它在手上再出现一回**：')
            print('    ★★一个动作、一个数、一次比——不解释、不回忆、不说破。')
    return 逾


if __name__ == '__main__':
    报()
    sys.exit(0)   # ★只报不拦
