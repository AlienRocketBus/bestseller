def 线(n):
    '''第n章是哪条线。★只认「判过的」两处，判不着即 None——**不许拿奇偶相间去补**。',

    ★其由（2026-09-04·300第1轮起草前所买）：奇偶相间是近来之习，不是律；
      拿一个习当据去判一个三五章外之限，正是本表§三当初不肯硬改听针/爷爷的那个理由。
    ★★故本器只读二处**人判过的**：①`版本/第n章/_开镜卡.md` 之「本章为」；
      ②圣经之第n章锚「★而n为**主线/暗线**」。二处皆无者返 None（印⚠，不判）。
    '''
    import io as _io
    c = os.path.join(ROOT, '版本', '第%d章' % n, '_开镜卡.md')
    if os.path.exists(c):
        for ln in _io.open(c, encoding='utf-8'):
            # ★不许用「'暗线' in ln」：那一行括号里还写着**上一章**是哪条线
            #   （299之卡：「**本章为**：**主线**（苏衍…；298为**暗线**…）」）——
            #   头一版即栽在此，三处实例一验就见（§六第5步：一条自己定的法，用一回就该验它一回）。
            #   故只取「本章为**：」紧跟其後那一个**判**，不问那一行别处还写了什么。
                m = re.match(r'-\s*\*\*本章为\*\*[：:]\s*\*\*(主线|暗线)\*\*', ln.lstrip())
                if m:
                    return '苏衍' if m.group(1) == '主线' else '沈鸢'
    b = os.path.join(ROOT, '设定', '00_镇冢秘术_唯一总圣经.md')
    if os.path.exists(b):
        for ln in _io.open(b, encoding='utf-8'):
            if ln.startswith('第 %d 章必须从' % n):
                m = re.search(r'而\s*%d\s*为\*\*(主线|暗线)' % n, ln)
                if m:
                    return '苏衍' if m.group(1) == '主线' else '沈鸢'
    return None


