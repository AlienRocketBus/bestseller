def 章号(f):
    m = re.search(r'第([零〇一二三四五六七八九十百千]+)章', os.path.basename(f))
    if not m:
        return 0
    tot, cur = 0, 0
    for ch in m.group(1):
        if ch in CN:
            cur = CN[ch]
        elif ch == '十':
            tot += (cur or 1) * 10; cur = 0
        elif ch == '百':
            tot += (cur or 1) * 100; cur = 0
        elif ch == '千':
            tot += (cur or 1) * 1000; cur = 0
    return tot + cur


def 白文(f):
    t = io.open(f, encoding='utf-8').read().split('【本章亮点】')[0]
    return re.sub(r'^.*?第.+?章[^\n]*\n', '', t, count=1, flags=re.S)


