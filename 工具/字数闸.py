import io, os, re, sys

根 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(根, '工具'))
from 亮点对表 import 诸章  # noqa: E402

CN = {'零': 0, '一': 1, '二': 2, '三': 3, '四': 4, '五': 5, '六': 6, '七': 7, '八': 8, '九': 9, '两': 2}
式 = re.compile(r'[“「]([^”」]{1,30})[”」]([^，。！？\n这那]{0,2}?)([一二三四五六七八九十两]+)个字')
剥 = re.compile(r'[，。！？、：；…\s]')
立二 = re.compile(r'^(?:我)?写的是：([^「」“”]+)。$')          # 路二·冒号立言，独占一行
数二A = re.compile(r'^(?:写完)?我?数了一遍字：([一二三四五六七八九十两]+)个?[。；]?$')
数二B = re.compile(r'^([一二三四五六七八九十两]+)个字')


def _num(t):
    n = c = 0
    for ch in t:
        if ch == '百':
            n += (c or 1) * 100; c = 0
        elif ch == '十':
            n += (c or 1) * 10; c = 0
        elif ch in CN:
            c = CN[ch]
    return n + c


def 取(txt):
    """自一段正文取 [(引文, 所称之数, 实数, 其後两字), ...]。"""
    out = []
    for m in 式.finditer(txt):
        q, cnt = m.group(1), _num(m.group(3))
        尾 = txt[m.end():m.end() + 2]
        if cnt == 1 and 尾[:1] in ('都', '也'):      # 「一个字都／也」是成语，不是数
            continue
        out.append((q, cnt, len(剥.sub('', q)), 尾))
    return out


def 取二(txt):
    """路二·同章冒号立言式。返回 [(立言之行, 报数之行, 引文, 所称之数, 实数), ...]。"""
    L = [x.strip() for x in txt.split('\n')]
    out = []
    for i, l in enumerate(L):
        m = 立二.match(l)
        if not m:
            continue
        q = m.group(1)
        real = len(剥.sub('', q))
        for j in range(i + 1, min(i + 9, len(L))):
            s = L[j]
            if not s or s == '＊':
                continue
            if 立二.match(s):          # 又起一言，不跨
                break
            m2 = 数二A.match(s) or 数二B.match(s)
            if m2:
                out.append((i + 1, j + 1, q, _num(m2.group(1)), real))
                break
    return out


def 行号(路, q, cnt):
    for i, l in enumerate(io.open(路, encoding='utf-8'), 1):
        if q in l and '个字' in l:
            return i
    return 0


def 跑(报=True):
    章 = 诸章()
    tot = tot二 = 0
    红 = []
    红二 = []
    for n, p in sorted(章.items()):
        body = io.open(p, encoding='utf-8').read().split('【本章亮点】')[0]
        for q, cnt, real, _尾 in 取(body):
            tot += 1
            if cnt != real:
                红.append((n, 行号(p, q, cnt), q, cnt, real))
        for 立行, 数行, q, cnt, real in 取二(body):
            tot二 += 1
            if cnt != real:
                红二.append((n, 立行, 数行, q, cnt, real))
    if 报:
        print('════ 字数闸 · 紧邻式 %d 处｜冒号立言式 %d 处 ════' % (tot, tot二))
        for n, ln, q, cnt, real in 红:
            print('  ⛔ 第%d章:%d 「%s」称%d字，实%d字' % (n, ln, q, cnt, real))
        for n, 立行, 数行, q, cnt, real in 红二:
            print('  ⛔ 第%d章:%d 立言「%s」，%d 行报作%d字，实%d字' % (n, 立行, q, 数行, cnt, real))
        if not 红 and not 红二:
            print('  ✓ 全书「N个字」逐处数得上（紧邻式 %d 处、冒号立言式 %d 处）。' % (tot, tot二))
    return len(红) + len(红二), tot + tot二


def 自测():
    R = []
    # ①式子认得出紧邻式
    t1 = 取('他说：“那就不是留的。”六个字。')
    R.append(('①认得出紧邻式并剥标点（六字）', t1 == [('那就不是留的。', 6, 6, '。')]))
    # ②数错者逮得出
    t2 = 取('他说：“那就不是留的。”五个字。')
    R.append(('②称五而实六者逮得出', bool(t2) and t2[0][1] != t2[0][2]))
    # ③回指式不认（166:91 之形）
    R.append(('③回指式（「，这N个字」）不认', 取('一个人说了“明天扶得动半天”，这三个字就不够用了') == []))
    # ④「一个字都」之成语不认
    R.append(('④「一个字都听不懂」不认', 取('他嘴里那些“同气连枝的东西”，我一个字都听不懂') == []))
    # ⑤今日之树
    红, tot = 跑(报=False)
    R.append(('⑤今日全书 %d 处紧邻式，红 %d 处' % (tot, 红), True))
    R.append(('⑥其群足以作闸（对得上者 ≥ 九成）', tot and (tot - 红) / tot >= 0.9))
    # ⑦路二认得出 242 之形（立言与报数隔一拍）
    t7 = 取二('写的是：从今天起，我先动手。\n＊\n写完我数了一遍字：七个。')
    R.append(('⑦路二认得出隔拍之形，并逮出称七实八', t7 == [(1, 3, '从今天起，我先动手', 7, 8)]))
    # ⑧路二不跨言（中间又起一言即断）
    t8 = 取二('写的是：从今天起，我先动手。\n＊\n写的是：这本账。\n＊\n三个字。')
    R.append(('⑧路二遇下一处立言即断，不跨言', t8 == [(3, 5, '这本账', 3, 3)]))
    for 名, o in R:
        print(('  ✓ ' if o else '  ⛔ ') + 名)
    print('  自测 %d/%d' % (sum(1 for _, o in R if o), len(R)))
    return all(o for _, o in R)


if __name__ == '__main__':
    if '--自测' in sys.argv:
        sys.exit(0 if 自测() else 1)
    红, _ = 跑()
    sys.exit(1 if 红 else 0)
