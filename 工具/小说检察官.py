    lines = text.split('\n')
    iss = []

    n = text.count('"')
    if n: iss.append(f'[引号] 英文直引号 " {n} 处 → 改全角 " "')
    n = text.count('——')
    if n: iss.append(f'[破折号] "——"(两道) {n} 处 → 改单道 "—",且少用')
    sgl = text.count('—') - 2 * text.count('——')
    if sgl >= 5:
        iss.append(f'[破折号多] 单破折号 {sgl} 处,偏多 —— 话完用句号、没说完/拖音用省略号、并列用逗号,破折号只留给"猛然打断"')
    if '您' in text:
        ln = [i + 1 for i, l in enumerate(lines) if '您' in l]
        iss.append(f'[称呼] "您" {text.count("您")} 处(行 {ln}) → 确认是否该用"你"')

    w_chars,w_paras,w_long=_weight_stats(text)
    if w_chars and w_chars<MIN_CHARS_REVIEW:
        iss.append(f'[分量] 全章仅{w_chars}字(<{MIN_CHARS_REVIEW}) —— 偏薄；历史章由加厚轮处理，新章另有硬闸')
    if w_paras and w_long==0:
        iss.append(f'[分量] 全章没有一段≥{LONG_PARA_CHARS}字 —— 全是碎步，没有一段跑起来；该给的慢镜头要给足')
    if w_paras and w_chars/w_paras<30:
        iss.append(f'[分量] 均段长{w_chars/w_paras:.0f}字(<30) —— 段段皆短，查是否砍成了电报体')

    for pat, why in PHYS:
        for m in re.finditer(pat, text):
            iss.append(f'[物理] 疑似「{m.group(0)}」—— {why}')

    dense, tot_c, tot_s = [], 0, 0
    for s in split_sentences(text):
        c = s.count('，'); tot_c += c; tot_s += 1
        if c >= DENSE: dense.append((c, s))
    dense.sort(reverse=True)
    if dense:
        iss.append(f'[逗号] {len(dense)} 句逗号≥{DENSE},顿得偏碎(最碎几句):')
        for c, s in dense[:6]:
            iss.append(f'        （{c}逗号）{s if len(s) <= 54 else s[:52] + "…"}')
    avg = (tot_c / tot_s) if tot_s else 0

    def loc(w):  # 该词出现在哪些行
        return [i + 1 for i, l in enumerate(lines) if w in l]

    ban = [f'「{w}」行{loc(w)}（{t}）' for w, t in BANNED.items() if w in text]
    if ban: iss.append('[禁用] 出现禁用词: ' + '；'.join(ban))
    fan = [f'「{w}」×{text.count(w)}行{loc(w)}→换「{t}」' for w, t in FANCY.items() if w in text]
    if fan: iss.append('[卖弄] 生僻/掉书袋,换大白话: ' + '；'.join(fan))
    over = [f'「{w}」×{text.count(w)}行{loc(w)}（{t}）' for w, t in OVERSURE.items() if w in text]
    if over: iss.append('[过度断定] 拿不准的事写太死,留余地: ' + '；'.join(over))
    rep = [f'{w}×{text.count(w)}行{loc(w)}' for w in REPEAT if text.count(w) >= 3]
    if rep: iss.append('[重复] 偏多: ' + '、'.join(rep) + ' —— 同一意象/词别连用')
    clic = [f'「{w}」×{text.count(w)}行{loc(w)}（{t}）' for w, t in CLICHE.items() if w in text]
    if clic: iss.append('[套话] 恐惧/情绪陈词,易AI味、易重复,换个新鲜的: ' + '；'.join(clic))
    logi = [f'「{w}」行{loc(w)}（{t}）' for w, t in LOGICTAG.items() if w in text]
    if logi: iss.append('[逻辑] 判断/形容跟逻辑或事实可能打架,核对: ' + '；'.join(logi))
    jj = sorted(set(m.group(0) for m in re.finditer(r'极(.{1,2})极\1', text)))
    if jj:
        iss.append('[叠词] 极X极X 灌水(任意X都算),老相/程度改具体描写、删一个: '
                   + '、'.join(f'「{w}」行{loc(w)}' for w in jj))
    book = [f'「{w}」行{loc(w)}（{t}）' for w, t in BOOKISH.items() if w in text]
    if book: iss.append('[文白] 太书面/文绉绉,人物对白尤其要接地气: ' + '；'.join(book))
    odd = [f'「{w}」×{text.count(w)}行{loc(w)}→{t}' for w, t in ODD.items() if w in text]
    if odd: iss.append('[生硬] 别扭/不自然的描述,换顺口的: ' + '；'.join(odd))
    gross = [f'「{w}」×{text.count(w)}行{loc(w)}（{t}）' for w, t in GROSS.items() if w in text]
    if gross: iss.append('[暧昧] 带亲密/恶心感的字眼,非情色场景别用: ' + '；'.join(gross))
    wux = [f'「{w}」×{text.count(w)}行{loc(w)}（{t}）' for w, t in WUXIA.items() if w in text]
    if wux: iss.append('[出戏] 现代戏混进古装/武侠套路(蒙面刺客/黑衣人…): ' + '；'.join(wux))

    # 未揭名:女主名字正式揭晓前,苏衍第一人称叙述不能直呼其名(连半个名字都不行)
    ch_no = _chap_num(path)
    for nm in HIDDEN_NAMES:
        _rev = NAME_REVEAL.get(nm, NAME_REVEAL_CH)
        _gate = (_rev is None or ch_no < _rev)
        if _gate and nm in text:
            iss.append(f'[未揭名] 「{nm}」×{text.count(nm)}行{loc(nm)} '
                       f'—— 苏衍这会儿还不知道她叫这名字("我跟她素不相识"),第一人称叙述不能直呼;'
                       f'改"她/那女人/眼前这人",或先在正文里正式交代她自报姓名(揭名后把 NAME_REVEAL_CH 设成该章号)')
        # 单字碎片（来/气/满/鼎/鸢等）在汉语正文中歧义极大，曾制造数百条假警报；
        # 机器只拦完整专名，疑似半名交给第一人称人工复核。

    # 烂比喻黑名单(硬伤):喻体陈腐/不形象,删,换朴素清楚的写法
    bm = [f'「{w}」行{loc(w)}（{t}）' for w, t in BADMETA.items() if w in text]
    if bm: iss.append('[烂比喻] 喻体陈腐/不形象,删掉换朴素写法: ' + '；'.join(bm))

    # 拗口:嵌套"X的Y的人/东西"这种套了两层"的"的从句(反例"能看见的眼睛的人")
    aok = sorted(set(m.group(0) for m in
                     re.finditer(r'的[^，。！？、“”\n]{1,6}的(?:人|东西|玩意儿|玩意|眼睛|家伙)', text)))
    if aok:
        iss.append('[拗口] "…的…的人/东西"套了两层"的",读着绕,拆开说(反例"能看见的眼睛的人"): '
                   + '、'.join(f'「…{w}」' for w in aok))

    # 章内扎堆(FYI,非硬伤):同一鲜明的词在很近处又冒出来,多为正常母题,只挑无意重复的删
    nrep = near_repeat(text)
    if nrep:
        iss.append('[扎堆FYI] 这些词在很近处又冒出来,多数正常(母题/话题词),只挑明显无意重复的删: '
                   + '、'.join(f'「{w}」' for w in nrep))

    _LIKE_NOUN = ('影像', '图像', '想象', '想像', '画像', '雕像', '肖像', '偶像',
                  '录像', '群像', '镜像', '塑像', '佛像', '神像', '遗像', '头像')

    def _has_metaphor(s):                # 把"影像/雕像/想象"这类带"像"的名词剔掉,免得污染比喻核对
        t = s
        for w in _LIKE_NOUN:
            t = t.replace(w, '')
        return any(m in t for m in METAPHOR_MK)
    ms = [s for s in split_sentences(text) if _has_metaphor(s)]
    if ms:
        iss.append(f'[比喻] {len(ms)}处打比方,逐句核对喻体跟本体贴不贴、生不生动(八竿子打不着的=乱比喻,删):')
        for s in ms[:6]:
            iss.append(f'        {s if len(s) <= 50 else s[:48] + "…"}')
        if len(ms) > 6:
            iss.append(f'        ……另有 {len(ms) - 6} 处,可单独跑这一章细看')

    # ===== 最高质量标准:文气层面的"还能更好"(均为给人核对,挑该改的改) =====
    # 套话成语(图省事的现成壳子,换成自己的具体写法)
    stale = [f'「{w}」×{text.count(w)}行{loc(w)}（{t}）' for w, t in STALE.items() if w in text]
    # 物理反逻辑:本来不会动的,不许写它"动/不动"(黑名单逮到就加)
    ANTIPHYS = {
        r'胡茬[^，。]{0,4}动': '胡茬短硬不会动,无所谓动不动(长须被风吹才动)',
        r'皱纹[^，。]{0,4}[跳动]': '皱纹不会自己跳动',
    }
    apv=[]
    for pat,why in ANTIPHYS.items():
        for m in re.finditer(pat, text):
            apv.append('「'+m.group()+'」（'+why+'）')
    if apv: iss.append('[物理反逻辑] 本来不会动的,别写它动/不动: ' + '；'.join(apv))
    # 字数对齐:凡写"X个字",引号里的汉字数必须严丝合缝(标点/省略号不算)
    NUMMAP={'一':1,'两':2,'二':2,'三':3,'四':4,'五':5,'六':6,'七':7,'八':8,'九':9,'十':10}
    def _hanzi(s): return len([c for c in s if '\u4e00'<=c<='\u9fa5'])
    zmis=[]
    for m in re.finditer(r'([一两二三四五六七八九十])个字[，、。：:！？\s]{0,6}["“]([^"”]{1,14})["”]', text, re.S):
        if text[max(0,m.start()-1):m.start()] in ('是','字'): continue  # "一个字是一个字"成语,跳过
        n=NUMMAP.get(m.group(1)); c=_hanzi(m.group(2))
        if n and c!=n: zmis.append('「'+m.group(1)+'个字→“'+m.group(2)+'”实为'+str(c)+'字」')
    for m in re.finditer(r'["“]([^"”]{1,14})["”][^。\n]{0,14}[这那]([一两二三四五六七八九十])个字', text):
        n=NUMMAP.get(m.group(2)); c=_hanzi(m.group(1))
        if n and c!=n: zmis.append('「“'+m.group(1)+'”被写成'+m.group(2)+'个字,实为'+str(c)+'字」')
    for m in re.finditer(r'["“]([^"”]{1,16})["”][。！？]?\s*\n+\s*[这那]?([一两二三四五六七八九十])个字(.)', text):
        if m.group(3) in ('是','也','都','没','一'): continue  # "一个字也/都…"类成语,跳过
        n=NUMMAP.get(m.group(2)); c=_hanzi(m.group(1))
        if n and c!=n: zmis.append('「“'+m.group(1)+'”换行后被写成'+m.group(2)+'个字,实为'+str(c)+'字」')
    if zmis: iss.append('[字数对齐] "X个字"和引文对不上,一个都不许差: ' + '；'.join(zmis))
    # 文采病:为秀文采写出的别扭搭配(具体黑名单,逮到新的就加)
    AWKWARD = {
        r'扎[了]?回.{0,3}耳': '声音不"扎"耳——正常写:回来了/传了回来/进了耳朵',
        r'撞[进回]了?.{0,3}耳': '声音/话不"撞"耳——正常写:在耳边响起/冒了出来/进了耳朵',
        r'胡茬[^，。]{0,3}[动抖颤]': '反逻辑:胡茬是根,不会动(长须迎风才会动),重写',
        r'扎进.{0,3}耳': '同上,声音不"扎"耳',
    }
    awk=[]
    for pat,why in AWKWARD.items():
        for m in re.finditer(pat, text):
            awk.append('「'+m.group()+'」（'+why+'）')
    if awk: iss.append('[文采病] 为秀文采写出的别扭搭配,改成正常说法: ' + '；'.join(awk))
    if stale: iss.append('[套话·过一眼] 下列常用语核一下——偷懒占位的换,直白有效、正当其位的留(不搞一刀切): ' + '；'.join(stale))
    # 直接说破情绪(改成用画面/动作/身体反应演)
    tell = [f'「{w}」行{loc(w)}（{t}）' for w, t in TELLING.items() if w in text]
    if tell: iss.append('[说破情绪] 别直接说"怕/慌/瘆人",改用画面、动作、身体反应演出来: ' + '；'.join(tell))
    # 废词"东西"过多(又虚又懒,能具体就具体,只留有意的"那东西"母题)
    dx = text.count('东西')
    if dx >= 4:
        iss.append(f'[废词] "东西" {dx} 处(行{loc("东西")}) —— 又虚又懒,堆多显廉价;'
                   f'能精确指代就精确(换"它"/准确名词),只留有意的"那东西"母题')
    sm = text.count('什么')
    if sm >= 14:
        iss.append(f'[虚词] "什么" {sm} 处 —— 偏多;先分清:"不知是什么/像有什么"这类必要的虚指(尤其悬疑/恐怖戏)留着,纯凑数的删/换准确词')
    # "越来越"口头禅(递进虽好,堆多成口头禅)
    yy = text.count('越来越')
    if yy >= 4:
        iss.append(f'[口头禅] "越来越" {yy} 处(行{loc("越来越")}) —— 递进虽好,堆多成口头禅;'
                   f'留最有力的一两处,其余换"渐渐/愈发/一点点/没完没了"或重写')


    # "惨白"形容手机/手电/灯的光不靠谱(第二章定论:那是刺眼的白光;"脸色惨白"可留)
    import re as _re2
    for _mo in _re2.finditer('惨白', text):
        _ar = text[max(0,_mo.start()-8):_mo.start()+8]
        if any(k in _ar for k in ['光','手电','手机','灯']):
            iss.append('[用词] "惨白"形容手机/手电/灯的光不靠谱(行%s) —— 那是刺眼的白光,改"白光/白花花的光"("脸色惨白"可留)' % loc('惨白'))
            break
    # 场景词反复砸(同一个场景/地点词整章来回用,读着单调)——窖/地窖 等
    _hz = len(re.findall(r'[\u4e00-\u9fa5]', text))
    for _w in ['窖']:
        _c = text.count(_w)
        if _c >= 8 and _hz and _c / _hz * 1000 >= 2.0:
            iss.append(f'[场景词] "{_w}" {_c} 处(行{loc(_w)},密度{_c/_hz*1000:.1f}/千字) —— 同一个场景词整章反复砸,读着单调;'
                       f'换着说(底下/四下/四周/这地方/脚下),"满{_w}"这类生造词更要换成顺口的("黑暗的地窖里")')
    # 句首单调(老用同一个字起头,节奏发死)——按比例(>12%且≥7),长短章都公平
    _ss = [s.strip() for s in split_sentences(text) if s.strip()]
    if _ss:
        _thr = max(7, int(0.12 * len(_ss)) + 1)
        _hc = Counter(s[0] for s in _ss)
        mono = sorted(((ch, k) for ch, k in _hc.items()
                       if k >= _thr and ch in '我可但却那这他她它你又只就便而然'),
                      key=lambda x: -x[1])
        if mono:
            iss.append(f'[开头单调] 太多句子从同一个字起、读着发死(阈值{_thr}=本章{len(_ss)}句的12%),换着开头(第一人称"我"难免多,也尽量散开): '
                       + '、'.join(f'「{ch}…」×{k}' for ch, k in mono))

    return iss, avg, tot_s


