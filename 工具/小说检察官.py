def jj_hook(n, note=''):
    """【批103】十轮精进挂钩：--验收 跑完自动存版＋棘轮闸；满十轮自动横评。
    立法：机制不设平行命令，一律走检察官单一入口；作者只说"续"与"挑刺"。"""
    try:
        import importlib.util as _ilu
        _p = os.path.join(os.path.dirname(os.path.abspath(__file__)), '十轮精进.py')
        if not os.path.exists(_p):
            return
        _s = _ilu.spec_from_file_location('_jj', _p)
        _m = _ilu.module_from_spec(_s)
        _s.loader.exec_module(_m)
    except Exception as e:
        print('  ⚠十轮精进模块未能加载：%s' % e)
        return
    print('\n' + '=' * 64)
    print('   【十轮精进 · 批103自动挂钩】本轮挑刺完毕，自动存版')
    print('=' * 64)
    _m.save(n, note or '（本轮说明未填，须在回执补记开庭与真伤级别）')
    _d, _led = _m.paths(n)
    try:
        import json as _j
        _v = _j.load(open(_led, encoding='utf-8'))['版本']
        if len(_v) >= 10:
            print('\n  ✓已满十轮，自动横评：')
            _m.compare(n)
        else:
            _tab = ['封版轮', '冷轮补执', '四堂会审', '挑刺王终读', '升华庭',
                    '十庭①(资源/感官)', '十庭②(在场/内面)', '十庭③(时序/节奏/留白)',
                    '跨章复审', '减法轮']
            _nx = _tab[len(_v)] if len(_v) < 10 else '横评'
            print('  ▶下一轮该开：**%s**（第%d轮／共10轮）' % (_nx, len(_v) + 1))
    except Exception:
        pass


def super_main():
    args=sys.argv[1:]
    if args and args[0] in ('-h','--help'):
        _usage(); return 0
    lib=_load_lib()
    files=_chapters()
    if args and args[0] in ('框架','--framework'):
        print(FRAMEWORK.strip()); return 0
    if args and args[0] in ('规范','导出规范','知识','--spec','--knowledge'):
        print_knowledge(); return 0
    if args and args[0]=='--doctor':
        e,_=project_doctor(files,check_reader=True); return 0 if e==0 else 1
    if args and args[0]=='--selftest':
        print('【超级智能体·自检】'); return 0 if selftest(files,lib) else 1
    if args and args[0]=='--伏笔':
        foreshadow_report(upto=int(args[1]) if len(args)>1 else 999); return 0
    if args and args[0]=='--军师':
        if not files:
            print('  ✗ 正文章数=0，不能生成战情简报'); return 2
        n=int(args[1]) if len(args)>1 else (max(files)+1)
        strategist(n, files); return 0
    if args and args[0]=='--心电图':
        if len(args)<2 or not args[1].isdigit() or int(args[1]) not in files:
            print('  ✗ 请给出已存在的章号，例如 --心电图 70'); return 2
        cardiogram(int(args[1]),files); return 0
    if args and args[0]=='--提示词':
        if _os.path.exists(PROMPT_PATH): print(open(PROMPT_PATH,encoding='utf-8').read()); return 0
        print('  ✗ 提示词系统文件缺失: '+PROMPT_PATH); return 2
    if args and args[0]=='--改检':
        if not files: print('  ✗ 正文章数=0'); return 2
        n=int(args[1]) if len(args)>1 and args[1].isdigit() else max(files)
        base=args[2] if len(args)>2 else 'HEAD'
        return diff_gate(n, base)
    if args and args[0]=='--验收':
        if not files: print('  ✗ 正文章数=0'); return 2
        m=max(files)
        n=int(args[1]) if len(args)>1 and args[1].isdigit() else m
        acceptance(n, files)
        note=args[2] if len(args)>2 else ''
        jj_hook(n, note)
        return 0
    if args and args[0]=='--开拍':
        if not files:
            print('  ✗ 正文章数=0，拒绝生成无根简报'); return 2
        wiring,_=project_doctor(files,check_reader=True)
        if wiring:
            print('  ✗ 开拍被项目红灯拦下；先清零 doctor／阅读器错误'); return 1
        expected=max(files)+1
        if len(args)>1 and not args[1].isdigit():
            print(f'  ✗ 开拍章号必须是整数；当前唯一合法下一章为第{expected}章'); return 2
        nx=int(args[1]) if len(args)>1 else expected
        if nx!=expected:
            print(f'  ✗ 不得重复或跳章：当前末章第{max(files)}章，只允许 --开拍 {expected}')
            return 2
        print(f'════ 开拍前复核·第{max(files)}章封版硬闸 ════')
        sealed=priority_one(files,max(files),lib)+mech_layer(files,max(files),lib)
        if sealed:
            print(f'  ✗ 第{max(files)}章封版硬错={sealed}；清零前不生成第{nx}章简报')
            return 1
        briefing(files,lib,nx); return 0
    md=[a for a in args if a.endswith('.md')]; num=[a for a in args if a.isdigit()]
    if md:
        total_error=0; total_review=0
        for p in md:
            path,ch=_resolve_md_arg(p,files)
            if not path:
                print('  ✗ 找不到文件: '+p); total_error+=1; continue
            if ch is None:
                print('  ✗ 文件不属于当前正文集，无法做跨章封版: '+path); total_error+=1; continue
            print(); print(f'════ 超级智能体·第{ch}章封版门 ════')
            e=priority_one(files,ch,lib); abs_collide(files,ch,lib); underwrite_radar(files,ch); e+=mech_layer(files,ch,lib)
            r=legacy_review_layer(files,ch)
            total_error+=e; total_review+=r
            print(f'  封版门:ERROR={e}(须0) REVIEW={r}(人工裁定)')
            ai_homework(ch,files); second_gate(f'第{ch}章')
        return 0 if total_error==0 else 1
    elif num:
        ch=int(num[0])
        if ch not in files:
            print(f'  ✗ 第{ch}章不存在；当前正文范围为'+(f'1—{max(files)}章' if files else '空')); return 2
        print(f'════ 超级智能体·第{ch}章封版门 ════')
        e=priority_one(files,ch,lib); abs_collide(files,ch,lib); underwrite_radar(files,ch); e+=mech_layer(files,ch,lib)
        r=legacy_review_layer(files,ch)
        print(f'  封版门:ERROR={e}(须0) REVIEW={r}(人工裁定)')
        ai_homework(ch,files); second_gate(f'第{ch}章')
        return 0 if e==0 else 1
    else:
        print('════ 超级智能体·全书体检 ════')
        wiring,reader=project_doctor(files,check_reader=True)
        if not files:
            return 2
        e=wiring
        e+=priority_one(files,None,lib); abs_collide(files,None,lib); underwrite_radar(files,None); e+=mech_layer(files,None,lib)
        r=legacy_review_layer(files,None)
        mx=max(files)
        print('─'*46)
        print(f'  全书仪表盘:ERROR={e}(须0) REVIEW={r}(人工裁定) READER={"通过" if reader==0 else "未同步"}')
        print('  封版状态='+('机器硬闸通过（仍须AI回执）' if e==0 else '未放行'))
        second_gate(f'全书1-{mx}章')
        return 0 if e==0 else 1

if __name__ == '__main__':
    print_console()
    raise SystemExit(super_main())
