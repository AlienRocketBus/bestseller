def split_sentences(text):
    parts = re.split(r'([。！？!?])', text)
    sents, buf = [], ''
    for p in parts:
        buf += p
        if p in '。！？!?':
            sents.append(buf.strip()); buf = ''
    if buf.strip():
        sents.append(buf.strip())
    return [s for s in sents if s]


