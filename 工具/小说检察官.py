    now=('此刻','这会儿','如今','眼下','现在','仍在','还在','又开始','我从怀里','我从胸口','我低头')
    for m in re.finditer(r'半[块枚]玉', text):
        lo=max(0, text.rfind('。',0,m.start())+1)
        hi=text.find('。',m.end())
