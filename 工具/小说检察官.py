def intra_repeat(text, k=6, dist=350):
    """章内近距重复:同一≥6字短语在≤dist字内出现两次(排除有意叠句白名单)。"""
    hz = [(i, c) for i, c in enumerate(text) if '\u4e00' <= c <= '\u9fa5']
    s = ''.join(c for _, c in hz)
    pos = [i for i, _ in hz]
    seen, hits = {}, {}
    for i in range(len(s) - k + 1):
        g = s[i:i+k]
        if len(set(g)) < 4:            # 叠字/花样少的放过
            continue
        if any(w in g for w in INTRA_WHITELIST):
            continue
        if g in seen and 40 <= i - seen[g] <= dist:
            hits[g] = (seen[g], i)
        seen[g] = i
    # 合并重叠 gram 成最长串
    merged = []
    for g in sorted(hits, key=lambda x: hits[x][0]):
        if merged and g[:-1] == merged[-1][0][1:]:
            merged[-1] = (merged[-1][0] + g[-1], merged[-1][1])
        else:
            merged.append((g, hits[g]))
    out = []
    for g, (a, b) in merged[:4]:
        out.append(f'[近距重复] 「{g}」相隔约{pos[b]-pos[a]}字内出现两次 —— 同章几行内重复同一说法,改一处(2026-07-04十六章梁脊案立规)')
    return out

