def _paras(body): return [x.strip() for x in re.split(r'\n\s*\n',body) if x.strip()]
def cardiogram(n,files):
    f,nm,t=files[n]; body=re.sub(r'^.*?第.+?章[^\n]*\n','',t,count=1,flags=re.S)
    ps=_paras(body)
    print('【八·章内心电图+感官配比】(机器测,AI裁节奏病)')
    lens=[len(re.findall(r'[\u4e00-\u9fff]',x)) for x in ps]
    bar=''.join('▁▂▃▄▅▆▇█'[min(7,l//22)] for l in lens)
    print(f'   段长心电:{bar}  段数{len(ps)} 均{sum(lens)//max(1,len(lens))}字 峰{max(lens)} 谷{min(lens)}')
    import statistics
    sents=[s for s in re.split(r'(?<=[。！？…])',body) if s.strip()]
    slens=[len(s) for s in sents]
    print(f'   句长方差:{int(statistics.pvariance(slens)) if len(slens)>1 else 0}(过小=节奏平;>900=忽长忽短审)')
    sense={'视':'看|望|见|瞧|盯|瞥|色|光|影','听':'听|响|声|鸣|吼|嘶|静','触':'烫|凉|冷|暖|湿|疼|麻|颤|贴','嗅':'味|气|腥|香|臭|嗅'}
    cc={k:sum(len(re.findall(w,body)) for w in v.split('|')) for k,v in sense.items()}
    print('   感官配比:',' '.join(f'{k}{v}' for k,v in cc.items()),'←嗅触≪视听=平面感,酌情补体感')
    from collections import Counter
    bg=Counter(body[i:i+2] for i in range(len(body)-1) if re.match(r'[\u4e00-\u9fff]{2}',body[i:i+2]))
    stop={'我们','他们','一个','没有','什么','就是','这个','那个','的一','一样','出来','起来','是一','了一','这一','都是','自己','一句','一点','那些','这些','里的','上的','一眼'}
    top=[(w,c) for w,c in bg.most_common(40) if w not in stop and c>=6][:6]
    heads=[x[0] for x in ps if x]
    run=1;mx=1
    for i in range(1,len(heads)):
        run=run+1 if heads[i]==heads[i-1] else 1
        mx=max(mx,run)
    if mx>=4: print(f'   段首复读:同一开头字连排{mx}段(如我我我…),审是否催眠')
    if top: print('   高频双字:',' '.join(f'{w}×{c}' for w,c in top),'←≥6次者自审是否口头禅')
