def diff_gate(n, base="HEAD"):
    """改动闸：拿本章与git上一版做diff，只查变动段及其左右邻段——新伤只长在缝口上。"""
    import subprocess as _sp
    fs=_chapters()
    if n not in fs: print('  ✗未找到第%d章正文'%n); return 1
    fp=fs[n][0]
    rel=os.path.relpath(fp,REPO_ROOT)
    try:
        old=_sp.run(['git','show',base+':'+rel],cwd=REPO_ROOT,capture_output=True,text=True).stdout
    except Exception as e:
        print('  ✗取上一版失败:',e); return 1
    if not old.strip():
        print('  ℹ本章为新增章，无上一版可比，改动闸跳过'); return 0
    new=open(fp,encoding='utf-8').read()
    ob=[x.strip() for x in old.split('【本章亮点】')[0].split('\n') if x.strip()]
    nb=[x.strip() for x in new.split('【本章亮点】')[0].split('\n') if x.strip()]
    oset=set(ob)
    changed=[(i,x) for i,x in enumerate(nb) if x not in oset]
    print('\n'+'█'*3+' 改动闸 · 第%d章（只查缝口·新伤只长在这里） '%n+'█'*3)
    print('  段数 %d → %d ；变动段 %d'%(len(ob),len(nb),len(changed)))
    if not changed:
        print('  ✓ 本章较上一版无文本变动'); return 0
    idxs=set()
    for i,_ in changed:
        for j in (i-1,i,i+1):
            if 0<=j<len(nb): idxs.add(j)
    zone='\n'.join(nb[j] for j in sorted(idxs))
    bad=0
    print('\n  ── 一·机械层（仅变动段及左右邻段） ──')
    for name,pat in [('破折号','—'),('半角逗号',','),('英文',r'[A-Za-z]'),
                     ('抖族','哆嗦|颤'),('永禁机制词','点亮|鼎心|气运|换锚|阵眼'),('骊山僵尸','骊山|僵尸')]:
        m=re.findall(pat,zone)
        if m: bad+=len(m); print('    ⛔%s×%d'%(name,len(m)))
    five=[s.strip() for s in re.split(r'(?<=[。！？…])',zone) if s.count('，')>=5]
    for s in five: bad+=1; print('    ⛔五逗:',s[:40])
    print('    %s'%('✓机械层干净' if bad==0 else '⛔机械层%d处，必须清零'%bad))
    print('\n  ── 二·自造重复（新增四字串在本章他处已有） ──')
    rest=''.join(x for i,x in enumerate(nb) if i not in [k for k,_ in changed])
    rep=[]
    for _,x in changed:
        for k in range(len(x)-3):
            g4=x[k:k+4]
            if re.fullmatch(r'[\u4e00-\u9fff]{4}',g4) and rest.count(g4)>=1 and g4 not in rep:
                rep.append(g4)
    print('    '+('⚠疑似自造重复：'+ '、'.join(rep[:8]) if rep else '✓无'))
    print('\n  ── 三·悬空指代（变动段首句以代词起，须查先行词） ──')
    dang=[x[:26] for _,x in changed if re.match(r'^[他她它那这]',x)]
    print('    '+('⚠须查先行词：'+' ｜ '.join(dang[:6]) if dang else '✓无'))
    print('\n  ── 四·器物动线（变动段涉及之器物，全章出现处须逐一对齐） ──')
    hit=[pn for pn in _PROPS if any(pn in x for _,x in changed)]
    for pn in hit:
        cnt=sum(1 for x in nb if pn in x)
        print('    ▣ %s：本章共%d处 —— 逐处核对位置与归属（P18处方）'%(pn,cnt))
    if not hit: print('    ✓变动段未涉器物')
    print('\n  ── 五·数字冲突（变动段中的数，与全章同类数对表） ──')
    nums=sorted(set(re.findall(r'[一二三四五六七八九十百千两]{1,4}(?:息|步|根|道|尺|天|回|声|指|寸|丈)',''.join(x for _,x in changed))))
    print('    '+('▣ '+ '、'.join(nums) +' —— 逐个与全章及前章对表' if nums else '✓变动段无数字'))
    print('\n  ── 五·五·章号泄漏（第一人称正文不得出现章号） ──')
    _bd=re.sub(r'^.*?第.+?章[^\n]*\n','',new.split('【本章亮点】')[0],count=1,flags=re.S)
    _ln=re.findall(r'[一二三四五六七八九十百]+章',_bd)
    if _ln: bad+=len(_ln); print('    ⛔章号入正文×%d:'%len(_ln), '、'.join(_ln[:5]), '（叙述者不可能说出章号＝作者出画）')
    else: print('    ✓无')
    print('\n  ── 六·五·亮点段专检（P19：改正文必重写亮点段，重写必先自检） ──')
    _h=new[new.find('【本章亮点】'):] if '【本章亮点】' in new else ''
    if not _h:
        print('    ⚠本章无亮点段')
    else:
        _b1=_h.count('—'); _b2=sum(1 for s in re.split(r'(?<=[。！？…])',_h) if s.count('，')>=5); _b3=_h.count(',')
        print('    破折%d／五逗句%d／半角逗%d  %s'%(_b1,_b2,_b3,'✓' if _b1+_b2+_b3==0 else '⛔亮点段未清零，禁同步'))
        if _b1+_b2+_b3: bad+=_b1+_b2+_b3
    print('\n  ── 六·段间空行（变动区） ──')
    print('    '+('⛔漏空行' if re.search(r'。\n(?!\n)(?=[^\n])',new) else '✓无'))
    print('█'*3+' 改动闸毕：机械层%s '%('通过' if bad==0 else '未过')+'█'*3)
    return 1 if bad else 0

