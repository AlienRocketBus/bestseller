def near_repeat(text, win=38, a=2, b=4, cap=6):
    s = ''.join(ch for ch in text if '\u4e00' <= ch <= '\u9fff')
    seen, hits = {}, {}
    for L in range(a, b + 1):
        for i in range(len(s) - L + 1):
            w = s[i:i + L]
            if w[0] in _NR_LEAD or any(c in _NR_FILLER for c in w) or w in _NR_STOP:
                continue
            if w in seen and 0 < i - seen[w] <= win:
                hits[w] = hits.get(w, 0) + 1
            seen[w] = i
    keep = []
    for w in sorted(hits, key=lambda x: (-len(x), -hits[x])):
        if not any(w != k and w in k for k in keep):   # 去掉被更长词包含的碎片
            keep.append(w)
    return keep[:cap]


