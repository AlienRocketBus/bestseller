export const meta = {
  name: '全书记忆',
  description: '全书记忆：逐字读全书，每章立一份详记（事、人、物、日、要句、悬线），再立总览与索引；以後调取即知全书，不必重读（0927 作者令）',
  phases: [{ title: '逐章详记' }, { title: '总览' }],
}
// args: { 起?: 1, 止?: 379 }（只重记某几章时传）
const 起 = (args && args.起) || 1, 止 = (args && args.止) || 379
const 底 = `你在长篇小说仓库 /home/user/the-novel 里。正文在 \`正文/\`（文件名含「第某章」之汉字章号）；圣经 \`设定/00_镇冢秘术_唯一总圣经.md\`。
⛔【律⑮·动盘之禁】旁有别席在写盘——不许跑 \`git checkout\`／\`git stash\`／\`git reset --hard\`／\`git clean\`／\`git add -A\`。
⭐【律⑳·总编辑之权】不许写「交作者裁」而停下；须裁之事当场照「书更好看」裁并写其由。
⛔尽全力、完美主义：这份记录是全书之记忆——以後一切审、改、续写都凭它调取，不再重读；错一处、漏一处，後面全跟着错。⛔不许凭印象，不许扫读。`

const 式 = `# 第N章《章名》
- 正文档：正文/xxx.md｜sha1：（\`sha1sum\` 之前十二位）｜字数约
- 线与日：主线／暗线；天字式或日字式之第几日；在哪一站、何地
- 在场之人：（逐一，含其此刻之状：伤、所携、所知）
- 物：（本章出现之要物，及其去向——谁拿着、放在哪、用掉没有）
## 发生了什么（按拍，逐拍一两句，写到能凭此复述全章）
1. …
## 要句（原句照录，3—6 句：本章最重之拍、人物之要话、日後要回收之句，各注行号）
## 本章之新知（读者在本章新知道了什么；人物新知道了什么——二者分开）
## 悬线（本章开了什么、接了哪一章的什么、还欠什么——注章号）
## 一句之要`

const 段 = []
for (let a = 起; a <= 止; a += 10) 段.push([a, Math.min(a + 9, 止)])

phase('逐章详记')
const 记 = await parallel(段.map(([a, b]) => () => agent(`${底}

你是全书记忆之记录者（第 ${a}—${b} 章）。⛔独立、尽全力：**逐字读完这 ${b - a + 1} 章全部正文**，逐章各写一份详记，存为 \`设定/全书记忆/第N章.md\`（N 为阿拉伯数字，如 第7章.md），每份照下式，⛔一栏不许空（确无者写「无」）：
${式}
写毕逐份自核：凡人名、数目、日号、物之去向，回原文再对一遍。⛔只写这些档，不 git add。
返回：所写档之列与每章「一句之要」。`, { label: `记·${a}-${b}`, phase: '逐章详记', effort: 'max',
  schema: { type: 'object', properties: { files: { type: 'array', items: { type: 'string' } }, gists: { type: 'array', items: { type: 'object', properties: { n: { type: 'number' }, gist: { type: 'string' } }, required: ['n', 'gist'] } } }, required: ['files', 'gists'] } })))
const 失 = 记.map((r, i) => r ? '' : `${段[i][0]}-${段[i][1]}`).filter(Boolean)
if (失.length) throw new Error('详记有失：' + 失.join('、'))

phase('总览')
const 览 = await agent(`${底}

你是全书记忆之总览席。第 ${起}—${止} 章之逐章详记已在 \`设定/全书记忆/第N章.md\`。逐份读完，然後写（或更新）：
1. \`设定/全书记忆/总览.md\`：①全书至今一页之要；②按站（E1 柏冢、E2 楼兰、E3 青溪、E4 巴蜀水下、E5 贺兰……）分段，每站：章号范围、此站之事（一段）、此站读者之所知与所欠；③逐章一行索引表：| 章 | 章名 | 线·日 | 一句之要 |。
2. \`设定/全书记忆/人物.md\`：每一人物：首见章、至今之状（伤、所携、所知、所瞒）、其线上每一要事之章号。
3. \`设定/全书记忆/物件.md\`：每一要物：首见、历次易手与去向（注章号）、今在何处。
4. \`设定/全书记忆/悬线.md\`：全书至今未结之线（开於何章、欠何物、宜於何处结）。
5. \`设定/全书记忆/用法.md\`：怎么调取（查某章→第N章.md；查某人→人物.md；……），以及⛔规矩：正文一改，该章详记与四份总档当场同改（sha1 须与正文相符，\`工具/全书记忆.py\` 验）。
⛔各档之说须能回溯到某章某份详记；有互相矛盾者，回原文裁定并改正详记。然後 git add \`设定/全书记忆/\` 下诸档（明路径）并 commit（末两行：
Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>
Claude-Session: https://claude.ai/code/session_016Hgfc2SSNvGktFmk2LX825），⛔不推。返回一段摘要。`, { label: '总览', phase: '总览', effort: 'max' })
return { 章: `${起}-${止}`, 记: 记.map(r => r.gists).flat().length, 览 }
