export const meta = {
  name: 'du-xi-32',
  description: '#14 三十二章之弱·读席：只读白文，判须落到拍号（不改一字）',
  phases: [{ title: '读', detail: '一章一席，只读白文，判落到拍号' }],
}

const SCHEMA = {
  type: 'object',
  properties: {
    ch: { type: 'integer' },
    where: { type: 'string' },
    verdict: { type: 'string' },
    slack: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          beats: { type: 'string' },
          what: { type: 'string' },
          cost: { type: 'string' },
          fix: { type: 'string' },
        },
        required: ['beats', 'what', 'cost'],
      },
    },
    best: { type: 'string' },
    notweak: { type: 'string' },
  },
  required: ['ch', 'verdict', 'best'],
}

phase('读')
const out = await parallel(args.map(n => () => agent(
`你是《镇冢秘术》第 ${n} 章的**读席**。你只做一件事：**像一个读者那样把这一章读完，然后说它在哪儿松了。**

【怎么读】
工作目录 /home/user/the-novel。用 \`ls 正文/ | grep 第${n}章\` 找到本章，**只读【本章亮点】以前的白文**。
⛔【律⑮·动盘之禁·0924 补进每一份席令】**你在跑之时，旁边可能还有别的席、别的器正在写盘**——**一律不许跑动整个工作区的命令**：\`git checkout\`（含 \`checkout .\`／\`checkout -- 档\`）／\`git stash\`／\`git reset --hard\`／\`git clean\`／\`git add -A\`。**要看改前改後**：\`git show HEAD:<路径> > /tmp/旧.md\` 再比；**要复原你自己改坏的一档**：从 \`版本/第N章/vNN.md\` 抄回来，⛔不许 checkout。（其由：0924·363 救章，一席误跑 \`git checkout\` 把正文退回 HEAD，幸当场自 v20 复原。）
**不许看**：本章的【本章亮点】骨记、设定/ 下任何册子、版本/ 下任何轮记。
——**读得到答案就判不出堵**（看官之律①）。
你可以读**前一章的白文**（第 ${n - 1} 章），只为知道昨天发生了什么；别的一概不读。

【拍】白文以「＊」分拍。**你的每一条判都必须落到拍号**（第几拍到第几拍），
不许写「读者会觉得闷」——那不算判；「拍 93 至 106 连十四拍无一动作」才算（看官之律②）。

【要答的】
一、**verdict**：这一章弱不弱？**弱在哪一样**？一句话。
   ★允许你判「**它不弱**」——诸席点它的名，未必点对。若不弱，把**它好在哪儿**写进 notweak，举拍号。
二、**slack**：逐条列它松的地方。每条要有：
   · beats：拍号区间（如「拍 41—58」）
   · what：那几拍里**实际发生了什么**（用你读到的话说，不用评语）
   · cost：**读者在这儿丢了什么**——是丢了「谁在干什么」，是丢了「这一拍跟上一拍有什么不同」，
     还是丢了「今天跟昨天有什么不同」。**必须说得出丢的是哪一样，说不出就别列。**
   · fix：**一句话的补法**，且只许是这三样里的一样：
     ①**删**（这几拍与前文重复，删掉读者不丢东西）；
     ②**挪**（章里后头某一拍搬到前头来，读者就跟得上了——写明从第几拍挪到第几拍）；
     ③**换**（某一句替读者把感觉做完了，删掉那句判语，读者自己就感觉得到——写出那一句）。
   **不许写「补一拍新的」**——加笔要有原场撑，你只读了白文，撑不起。
三、**best**：这一章**最好的那一拍是哪一拍，好在哪儿**。（一章不可能全松；找不出最好的一拍，
   多半是你没读进去。）
四、**where**：本章白文之档名与总拍数。

【本坐要提防你的两样】
· **别为了交差而凑判**。判不出就写「读下来没有堵得住的地方」，那是有用的答案。
· **别拿写作课的话当判**（「节奏拖沓」「缺乏冲突」一律不算）。**只说读者丢了什么。**

**一个字也不许改。** 你是读席，不是修席。`,
  { label: `读:${n}`, phase: '读', schema: SCHEMA })))

return out.filter(Boolean)
