export const meta = {
  name: 'lian-guan',
  description: '连贯席：一段十来章只读白文，判这条线走得顺不顺——断层／失速／倒挂，判必落到章号与拍号',
  phases: [{ title: '连贯', detail: '一段一席，只读白文，逐段判其线' }],
}

// 用法：Workflow({scriptPath:'工具/席/连贯席.js', args:{段:[[296,305],[286,295]]}})
const 段 = (args && args.段) || [[296, 305]]

const SCHEMA = {
  type: 'object',
  properties: {
    span: { type: 'string' },
    verdict: { type: 'string' },
    breaks: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          kind: { type: 'string' },
          where: { type: 'string' },
          what: { type: 'string' },
          cost: { type: 'string' },
          fix: { type: 'string' },
        },
        required: ['kind', 'where', 'what', 'cost'],
      },
    },
    spine: { type: 'string' },
    best_join: { type: 'string' },
  },
  required: ['span', 'verdict', 'spine'],
}

phase('连贯')
const out = await parallel(段.map(([a, b]) => () => agent(
`【第一律】**只许优化，不许降低质量。**质量是第一优先级。
**半成品不许交**：交白卷比交一刀假的强；**把红原样交上来，比把红压下去强。**
工作目录 /home/user/the-novel。

你是《镇冢秘术》**第 ${a} 至 ${b} 章之连贯席**。

【你只做一件事】**像一个连着读完这十来章的读者那样读一遍，然后说这条线在哪儿断了。**

【怎么读·硬律三条】
① **只读白文**（每章末一段【本章亮点】是骨记，**不许看**）；
　**不许看** \`设定/\` 下任何册子、\`版本/\` 下任何轮记。
　★**其由**：\`工具/看官.py\` 立器之日自记「四庭俱过九回，判不过零回——**那只『读者之眼』看的不是文，
　是我自己的轮记**」。**读得到答案，就判不出堵。**
② **判必落到章号与拍号**（白文以「＊」分拍）。「读起来不连贯」不算判；
　「第 298 章拍 41 立的那条规矩，到 303 章一次也没有再出现，而 303 拍 60 又当它还在」才算。
③ **许你判「这一段走得顺」**——**而判顺也要举出是哪几处把它接起来的。**

【本书两条线，先分清再读】
主线·苏衍（第一人称「我」）与暗线·沈鸢（第三人称「她」），**逐章交替**，各有各的日历
（主线「第N天」／暗线「第N日」，两历相差 6）。**跨线的「昨天」是不成立的**——
读的时候把两条线各自抽出来，**先各读一条，再看两条并在一起顺不顺。**

【你要找的三样·只此三样】
· **断层**：前头立起来的一样东西（一条规矩／一个人的一件事／一样物件／一个数），
　**后头再没出现、也没交代它去哪儿了**。写明它立在哪一章哪一拍、断在哪一章。
· **失速**：连着几章，**这条线上没有一样东西往前动过一格**。
　写明是哪几章，以及「若把这几章整段拿掉，后头哪一句会接不上」——**答不出，那就是真失速。**
· **倒挂**：后头某一章**当作理所当然的一样东西，前头从来没有给过**（不是事实相犯——
　事实之犯有器在守；是**读者手里没有那张牌，而书当他有**）。

【每一条要写四样】kind（断层／失速／倒挂）｜where（章:拍）｜what（读到的话，不用评语）｜
cost（**读者在这儿丢了什么**：丢了「谁在干什么」／「这一章跟上一章有什么不同」／
「今天跟昨天有什么不同」／「这件事为什么要紧」——**说不出丢的是哪一样，就别列**）｜
fix（一句话的补法；**不许写「补一章」**，只许「哪一章里补一拍」或「哪一章里删／挪」）。

【另交两样】
· **spine**：这一段的**脊**——一句话说清这十来章合起来把读者带过了哪一程。
　★**写不出来，本身就是最大的一条判**（那说明这一段没有脊），**其时照写「无脊」并说明你为什么找不到**。
· **best_join**：这一段里**接得最好的那一处章与章之交**是哪一处，好在哪儿。

【本坐要提防你的两样】
· **别为了交差而凑判**。判不出就写「这一段读下来没有断处」，那是有用的答案。
· **别拿写作课的话当判**（「节奏拖沓」「张力不足」一律不算）。**只说读者丢了什么。**

**一个字也不许改。** 你是连贯席，不是修席。`,
  { label: `连贯:${a}-${b}`, phase: '连贯', schema: SCHEMA })))

return out.filter(Boolean)
