# ★第2轮只查回述词（想起/昨天/那一回），★★第3轮只查数；
# ★★★而「昨天他立了一个判，今天本章认它、翻它、还是没提它」——无一轮问。
# ★★★★而其证：208之「老头照着一个已经不在的数使力气」是我写时想到的，不是闸逼出来的。
# ★★★★★故立此检：取前章收句之骨词，查本章有无回指。
def _line_of(c):
    """★某章属主线还是暗线：以「我」之密度判（<3/千字为暗线之第三人称）。
    ★★其法与质量三闸、跑轮同源（圣经原文：暗线章用第三人称）。"""
    bb = body(c)
    if not bb:
        return None
    w = len(re.sub(r'\s', '', bb))
    if not w:
        return None
    if len(re.findall('我', bb)) / w * 1000 >= 3:
        return '主'
    # ★2026-09-05·机制总审（八路·跨章连贯审第3条）：旧式暗线只一值，霍钧章268、黎东来章277（通篇「他」）被当作沈鸢之同线前章，
    #   270、279遂被令回指另一条线之收句。今暗线分二值：「她」（沈鸢·第三人称限知）与「他」（霍钧／黎东来之视角章）。
    #   其尺：她/千 与 他/千 孰大（268：他26.4/她0；270：她38.5/他0.6）。
    她 = bb.count('她') / w * 1000
    他 = bb.count('他') / w * 1000
    return '她' if 她 >= 他 else '他'


# ★★★★★1016·X01（391 封版之⑮所逮）：⑮之线只以「我」与她/他之密度判（_line_of），而总纲所排之线它一眼不看——
