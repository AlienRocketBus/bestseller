def _号(f):
    m = re.search(r'第([零〇一二三四五六七八九十百]+)章', f)
    if not m:
        return None
    d = {'一': 1, '二': 2, '三': 3, '四': 4, '五': 5,
         '六': 6, '七': 7, '八': 8, '九': 9}
    t = n = 0
    for ch in m.group(1):
        if ch in d:
            n = d[ch]
        elif ch == '十':
            t += (n or 1) * 10
            n = 0
        elif ch == '百':
            t += (n or 1) * 100
            n = 0
    return t + n


def 诸章(路=None):
    out = {}
    for f in glob.glob(os.path.join(路 or os.path.join(ROOT, '正文'), '*第*章_*.md')):
        n = _号(os.path.basename(f))
        if n:
            out[n] = io.open(f, encoding='utf-8', errors='replace').read()
    return out


