def _已封版(n):
    """★只认已交回执之章（⛔草稿不算）。"""
    import glob as _g
    return bool(_g.glob(os.path.join(ROOT, '设定', '回执_*第%d章*' % n)))


_数汉 = '零一二三四五六七八九'


def _汉(n):
    """330 → 三百三十（与档名同式）。"""
    if n < 10:
        return _数汉[n]
    if n < 20:
        return '十' + (_数汉[n % 10] if n % 10 else '')
    if n < 100:
        return _数汉[n // 10] + '十' + (_数汉[n % 10] if n % 10 else '')
    b = _数汉[n // 100] + '百'
    r = n % 100
    if not r:
        return b
    if r < 10:
        return b + '零' + _数汉[r]
    return b + (_数汉[r // 10] + '十' if r >= 20 else '十') + (_数汉[r % 10] if r % 10 else '')


def 复提之章(账号, d, 只封版=True):
    """★返回本笔复提过的诸章之号。两路皆算：
    一·白文或骨记里见其记号；
    二·骨记里明报并带其据（⛔空口一行不算：其後须有 ≥8 字）——**其式认宽**：
      `SUS-A·本章复提：…`｜`悬念哨ＳＵＳ甲本章落一笔，…`｜`SUS-甲…复提…` 皆算。
    ⛔**而只数已封版之章**（回执在盘上者）——**一份还在长的草稿不算数。**"""
    出 = []
    键 = 账号.split('-')[0] + '-' + 账号.split('-')[1]
    宽 = 宽式(账号)
    for n in sorted(d):
        if 只封版 and not _已封版(n):
            continue
        t = d[n]
        if any(k in t for k in 账[账号]) or 宽.search(t) or (只封版 and 严式(账号).search(_回执之文(n))):
            出.append(n)
    return 出


# ★1111·445 封版逮（推闸「器红逾限」）：骨记漏报而回执已载其兑者，器只读正文、恒报红（大审440 #15「器之误」）——
#   今兼读已封版章之回执，⛔而只认严式「SUS-X·本章复提：<据 ≥8 字>」（回执里「SUS-A 未复提」之类之论⛔误认）。
def _回执之文(n):
    out = []
    for f in glob.glob(os.path.join(ROOT, '设定', '回执_*第%d章*' % n)):
        out.append(io.open(f, encoding='utf-8', errors='replace').read())
    return '\n'.join(out)


def 严式(账号):
    键 = re.escape(账号.split('-')[0] + '-' + 账号.split('-')[1])
    return re.compile(r'(?m)' + 键 + r'·本章复提[：:]\s*(\S[^\n]{7,})')


def 宽式(账号):
    甲, A = _宽.get(账号, ('', ''))
    名 = '(?:%s|ＳＵＳ%s|SUS[-－]?%s|SUS[-－]?%s|悬念哨%s)' % (
        re.escape(账号.split('-')[0] + '-' + 账号.split('-')[1]),
        re.escape(甲), re.escape(甲), re.escape(A), re.escape(甲))
    # ★1117 大审460 #10：460:187「悬念哨乙·柄窝：…」之写法（号＋物名＋冒号）亦认——同坑⛔再犯
    物 = '|'.join(re.escape(x) for x in [账号.split('-', 2)[2]] + _别名.get(账号, []))
    return re.compile(名 + r'[^\n]{0,12}?(?:复提|落一笔|当场提|提过|兑|(?:%s)[：:])[^\n]{0,4}[：:，,]?\s*(\S[^\n]{7,})' % 物)


def 判(d=None, 只封版=True):
    d = d or 诸章()
    末 = max(d) if d else 0
    报 = []
    for k in 账:
        ch = 复提之章(k, d, 只封版=只封版)
        末见 = max(ch) if ch else 0
        距 = 末 - 末见 if 末见 else 末
        报.append((k, 末见, 距, 距 > 限))
    return 末, 报


def 印():
    末, 报 = 判()
    print('════ 悬念哨 ════（三条主账·各自之形皆写死「每 %d 章至少一处」·以第%d章计）' % (限, 末))
    红 = 0
    for k, 末见, 距, bad in 报:
        if bad:
            红 += 1
            print('  ⛔ %-14s 末见第%s章｜已隔 %d 章（限 %d）' % (k, 末见 or '—', 距, 限))
        else:
            print('  ✓ %-14s 末见第%s章｜隔 %d 章' % (k, 末见 or '—', 距))
    if 红:
        print('  ★**其复提之形，逐笔写死在 `设定/到期账.json` 其条之「其形」里**——')
        print('  ⛔**不许专开一拍去提、不许把它答死、不许用同一句式**；')
        print('  ⛔**而「这一章没位子」不是由**：没位子即改挂到走得到的那一章，当场写明。')
    return 0


