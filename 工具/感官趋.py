def 底自比带():
    """⛔底不自造：跑 `比带.py` 取其「同形」那一条带之底。跑不着即回空（本器随之不判）。"""
    import subprocess
    表 = 密度表()
    if not 表:
        return {}
    末 = max(表)
    出 = {}
    try:
        r = subprocess.run([sys.executable, os.path.join(ROOT, '工具', '比带.py'), str(末), '--全'],
                           capture_output=True, text=True, timeout=300)
        感 = None
        for ln in (r.stdout or '').splitlines():
            m = re.search(r'比带 · 第\d+章 · 项「(.)」', ln)
            if m:
                感 = m.group(1)
            m2 = re.search(r'同形.*带 ([\d.]+)—', ln)
            if m2 and 感:
                出[感] = float(m2.group(1))
    except Exception:
        return {}
    return 出


