def 密度表():
    出 = {}
    for d in sorted(glob.glob(os.path.join(ROOT, '版本', '第*章'))):
        m = re.search(r'第(\d+)章', os.path.basename(d))
        p = os.path.join(d, '_台账.json')
        if not m or not os.path.exists(p):
            continue
        try:
            vs = json.load(io.open(p, encoding='utf-8')).get('版本') or []
        except Exception:
            continue
        if not vs:
            continue
        s = vs[-1].get('soft', {})
        w = s.get('净重') or 0
        if not w:
            continue
        出[int(m.group(1))] = {k: round((s.get(k, 0) or 0) * 1000.0 / w, 2) for k in 诸感}
    return 出


def 查(表, 底, 段N=None, 连N=None):
    """回 [(感, 末段中位, 底, 连着低几章)]。⛔底由外给（自 比带 之同形带取），不自造。
    ⛔`连N` 只为旧签名留着，今不参与判（其由见器头）。"""
    g = 段 if 段N is None else 段N
    ns = sorted(表)
    if len(ns) < 2:
        return []
    末 = ns[-g:]
    红 = []
    for k in 诸感:
        if k not in 底:
            continue
        vals = [表[n][k] for n in 末 if k in 表[n]]
        if not vals:
            continue
        中 = statistics.median(vals)
        连 = 0
        for n in reversed(ns):
            if 表.get(n, {}).get(k, 0) < 底[k]:
                连 += 1
            else:
                break
        if 中 < 底[k]:
            红.append((k, round(中, 2), 底[k], 连))
    return 红


