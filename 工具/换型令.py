def 型(均段):
    return '短' if 均段 < 15 else ('中' if 均段 <= 21 else '长')


def 章型(n):
    p = os.path.join(ROOT, '版本', '第%d章' % n, '_台账.json')
    if not os.path.exists(p):
        return None
    try:
        d = json.load(open(p, encoding='utf-8'))
    except Exception:
        return None
    vs = d.get('版本') or []
    if not vs:
        return None
    return 型(vs[-1].get('soft', {}).get('均段', 0))


def 封了版(n):
    """★只数封了版的章：回执在盘上者方算（⛔正在写的那一章不算，㊵ 之通例）。

    ⛔★★★★★2026-09-23·限359（第358章封版之日当场所逮）：**补第二处之查。**
      ★**其实**：**第358章封版席毕、两份回执俱在盘上**
        （`设定/回执_20260923_第358章案席.md`｜`…封版席.md`），**且其交提已落**；
        **而 `封了版(358)` 回 `False`**——**其由只一样：本器只看 `版本/第N章/` 那一处。**
      ★★**逐章亲数**：**354—357 四章之案席回执写在 `版本/第N章/_回执.md`；
        358 之案席回执写在 `设定/回执_*第358章案席.md`**——**同一份文书，两处归档。**
      ⛔**於是一章明明封了版，本器看不见它**：**链长少算一章（26 而非 27）**，
        **且 358 虽係「长」而逃出红榜。**
      ★★★**故补查 `设定/回执_*第N章*`**——⛔**此改令本器更严，非更宽**：
        **它把一章从「看不见」拉回「看得见」，而 358 正是「长」，补上即入红。**
      ⛔**而本坐不去改那两份回执的归处**：**一份案席回执是一席之工，其归处係那一席之择**；
        **本器该做的是两处都认得，⛔不是逼着人把文书挪来挪去。**
    """
    return (bool(glob.glob(os.path.join(ROOT, '版本', '第%d章' % n, '*回执*')))
            or bool(glob.glob(os.path.join(ROOT, '版本', '第%d章' % n, '_回执.md')))
            or bool(glob.glob(os.path.join(ROOT, '设定', '回执_*第%d章*.md' % n))))


def 查(诸章型, 封版者=None):
    """诸章型：{章号: 型}。回诸红 [(章, 型, 连锁之长)]。
    ⛔封版者给了就用给的（便於负测回灌）；不给则去盘上问。"""
    ns = sorted(诸章型)
    红 = []
    连, 型名, 自 = 0, None, None
    for n in ns:
        t = 诸章型[n]
        if t == 型名:
            连 += 1
        else:
            连, 型名, 自 = 1, t, n
        # ★逾限之後那一章：若仍同型且已封版，即红
        if 连 > 限 + 1 and n >= 起:
            已封 = (n in 封版者) if 封版者 is not None else 封了版(n)
            if 已封:
                红.append((n, t, 连))
    return 红


def 须换型(n, 诸章型=None):
    """★**前瞻之判**：第 n 章（尚未写）是不是「非换型不可」的那一篇。⛔返回 (须换否, 其语)。

    ★★★★★2026-09-23·限359 立（与本日 `分量闸::须厚` 同一个治法·同一个由）。
      ⛔`查()` 係**回望之判**：一章封了版、而它仍是那一型、而链已逾限，它才红。
        ★**於是它逐回落在已封之章上**——**治它须回头重排一章之段**，逐坐皆挂；
        **今日之实：354／355／356／357 四章连红，链长 23、24、25、26，一章未治。**
      ★★**而这一条红与本日大审所判係同一样东西**（`设定/大审_至第357章.md` §五）：
        「**这本书的方法已经成了，成到可以自动地写下去——而「可以自动地写下去」正是它此刻最大的险。**」
        **二十六章不换一回段之呼吸，正是「自动地写下去」量得出来的那一个数。**
      ★★★**故补此判**：**凡本章之前那一链已及於限，则本章当场判「非换型不可」，写进开镜卡。**
      ⛔**而它不是一条段长令**：**其治照本器自书——「不是把段砍短，是让这一章的事需要那一种段」**
        （`裁_0913_净重之趋`）；**为它硬砍段者，`净重趋`／`爆窗`／`感官趋` 三闸照旧在後头等着。**
    """
    if 诸章型 is None:
        诸章型 = {}
        for k in range(起, n):
            v = 章型(k)
            if v:
                诸章型[k] = v
    前 = sorted(x for x in 诸章型 if x < n)
    if not 前:
        return False, '★第%d章之前无章可数，本判免测' % n
    型名 = 诸章型[前[-1]]
    连 = 0
    for x in reversed(前):
        if 诸章型[x] == 型名:
            连 += 1
        else:
            break
    if 连 <= 限:
        return False, ('★第%d章不须换型：其前「%s」型连 %d 章，未及於限 %d'
                       % (n, 型名, 连, 限))
    return True, ('⛔**第%d章非换型不可**：其前「%s」型已连 %d 章（限 %d），'
                  '**自第%d章起一章未换。**\n'
                  '    ⛔**而其治不是把段砍短**——**是让这一章的事需要那一种段**'
                  '（`裁_0913_净重之趋`：治在事之择，不在字数；本器自书之语，逐字照录）。\n'
                  '    ★**故填卡之时须当场自答一句并写在问五**：'
                  '**「本章之事要的是短段还是长段？何以？」**——'
                  '⛔**答不出即不许填本格。**\n'
                  '    ★★**并及一件**：**本日大审之得逐字係「可以自动地写下去正是它此刻最大的险」**；'
                  '**这一条链就是那一句话量得出来的那个数。**'
                  % (n, 型名, 连, 限, 前[-1] - 连 + 1))


