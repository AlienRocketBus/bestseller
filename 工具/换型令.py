def 型(均段):
    return '短' if 均段 < 15 else ('中' if 均段 <= 21 else '长')


def 章型(n):
    p = os.path.join(ROOT, '版本', '第%d章' % n, '_台账.json')
    if not os.path.exists(p):
        return None
    try:
        d = json.load(open(p, encoding='utf-8'))
    except Exception:
        return None
    vs = d.get('版本') or []
    if not vs:
        return None
    return 型(vs[-1].get('soft', {}).get('均段', 0))


def 封了版(n):
    """★只数封了版的章：回执在盘上者方算（⛔正在写的那一章不算，㊵ 之通例）。"""
    return bool(glob.glob(os.path.join(ROOT, '版本', '第%d章' % n, '*回执*'))) or \
           bool(glob.glob(os.path.join(ROOT, '版本', '第%d章' % n, '_回执.md')))


def 查(诸章型, 封版者=None):
    """诸章型：{章号: 型}。回诸红 [(章, 型, 连锁之长)]。
    ⛔封版者给了就用给的（便於负测回灌）；不给则去盘上问。"""
    ns = sorted(诸章型)
    红 = []
    连, 型名, 自 = 0, None, None
    for n in ns:
        t = 诸章型[n]
        if t == 型名:
            连 += 1
        else:
            连, 型名, 自 = 1, t, n
        # ★逾限之後那一章：若仍同型且已封版，即红
        if 连 > 限 + 1 and n >= 起:
            已封 = (n in 封版者) if 封版者 is not None else 封了版(n)
            if 已封:
                红.append((n, t, 连))
    return 红


def 自测():
    格 = []
    def 报(名, 得, 期):
        格.append((名, 得 == 期, 得, 期))

    长13 = {n: '长' for n in range(317, 330)}          # 317—329：连 13，已逾限 12
    # ①连锁逾限而下一章换了型·绿
    d = dict(长13); d[330] = '长'; d[331] = '中'
    报('①换了型者绿', 查(d, 封版者={330, 331}), [])
    # ②⛔连锁逾限而仍同型且已封版·红
    d = dict(长13); d[330] = '长'; d[331] = '长'
    报('②不换者红', [x[0] for x in 查(d, 封版者={330, 331})], [331])
    # ③★正在写的那一章不算（未封版即不红·㊵ 之通例）
    报('③未封版不红', 查(d, 封版者=set()), [])
    # ④未逾限者不辖（连 12 而第 13 章同型·仍绿）
    d2 = {n: '长' for n in range(319, 331)}; d2[331] = '长'
    报('④未逾限不报', 查(d2, 封版者={331}), [])
    # ⑤逾限後连欠二章·逐章皆红
    d3 = dict(长13); d3[330] = '长'; d3[331] = '长'; d3[332] = '长'
    报('⑤欠二章报二笔', [x[0] for x in 查(d3, 封版者={330, 331, 332})], [331, 332])
    # ⑥换了型即重起连锁·其後同型不红
    d4 = dict(长13); d4[330] = '长'; d4[331] = '中'; d4[332] = '长'
    报('⑥换型後重起', 查(d4, 封版者={330, 331, 332}), [])
    # ⑦★同源之验：本器之限须与 书级体检 之限逐字相同（⛔二处分家即红）
    try:
        src = open(os.path.join(ROOT, '工具', '书级体检.py'), encoding='utf-8').read()
        m = re.search(r'TYPE_CHAIN_LIMIT\s*=\s*(\d+)', src)
        报('⑦限与书级体检同源', int(m.group(1)) if m else None, 限)
    except Exception:
        报('⑦限与书级体检同源', 'err', 限)
    # ⑧型之档须与 书级体检 同（短<15／中15-21／长>21）
    报('⑧档·14短', 型(14), '短'); 报('⑧档·15中', 型(15), '中')
    报('⑧档·21中', 型(21), '中'); 报('⑧档·22长', 型(22), '长')

    # ⑨★起役之齿：330 虽逾限而不在本器之辖（其红归 书级体检②）
    d5 = dict(长13); d5[330] = '长'
    报('⑨330不在本器之辖', 查(d5, 封版者={330}), [])
    # ⑩⛔而 331 仍不换即红——「331 再说」那一句赖不掉
    d6 = dict(长13); d6[330] = '长'; d6[331] = '长'
    报('⑩331不换即红', [x[0] for x in 查(d6, 封版者={330, 331})], [331])
    # ⑪★331 换了型即绿
    d7 = dict(长13); d7[330] = '长'; d7[331] = '中'
    报('⑪331换型即绿', 查(d7, 封版者={330, 331}), [])

    过 = sum(1 for _, ok, _, _ in 格 if ok)
    for 名, ok, 得, 期 in 格:
        if not ok:
            print('  ⛔%s：得 %r，期 %r' % (名, 得, 期))
    print('%s 换型令·自测 %d/%d' % ('✓' if 过 == len(格) else '⛔', 过, len(格)))
