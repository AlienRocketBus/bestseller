_汉 = {'零': 0, '一': 1, '二': 2, '三': 3, '四': 4, '五': 5,
       '六': 6, '七': 7, '八': 8, '九': 9}


def _cn2i(x):
    """★汉数转整（与 `看官.py::_cn2i` 同法·只认本书档名里用得着的那几形）。"""
    t = 0
    n = 0
    for ch in x:
        if ch in _汉:
            n = _汉[ch]
        elif ch == '十':
            t += (n or 1) * 10
            n = 0
        elif ch == '百':
            t += (n or 1) * 100
            n = 0
    return t + n


