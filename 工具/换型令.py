def 认欠之章():
    """★读 `设定/换型欠账.md` 上判了「认欠」的那几章 → {章: 其记因}。

    ⛔**其三条限死，与 `分量闸::认欠之章` 逐字同**：
      ⛔**认欠一笔不抹**（其章照旧印一行 ⛔）｜⛔**须写明其事何以非那一型不可**｜⛔**有其额**。
    ★**其所以非「写明」不可**：**一笔不须解释的认欠，与把闸删掉没有分别。**
    """
    if not os.path.exists(欠账):
        return {}
    out = {}
    txt = io.open(欠账, encoding='utf-8').read()
    for m in re.finditer(r'\|\s*\*{0,2}(\d+)\*{0,2}\s*\|([^\n]*)', txt):
        n, rest = int(m.group(1)), m.group(2)
        if '认欠' not in rest:
            continue
        # ⛔③其事何以非那一型不可——答不出即不认
        因 = rest.split('认欠')[-1].strip(' |*：:')
        if len(re.sub(r'[\s*|]', '', 因)) < 12:
            continue
        out[n] = 因
    return out


