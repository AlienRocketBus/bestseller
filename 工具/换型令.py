def 全书():
    诸 = {}
    for d in sorted(glob.glob(os.path.join(ROOT, '版本', '第*章'))):
        m = re.search(r'第(\d+)章', os.path.basename(d))
        if not m:
            continue
        n = int(m.group(1))
        t = 章型(n)
        if t:
            诸[n] = t
    红 = 查(诸)
    if 红:
        for n, t, 连 in 红:
            print('  ⛔第%d章：其前「%s」型已连锁逾 %d 章，而本章封了版仍是「%s」（连 %d）'
                  % (n, t, 限, t, 连))
        print('⛔ 换型令：%d 章该换而没换' % len(红))
        print('  ★其治⛔不是把段砍短——**是让这一章的事需要那一种段**（裁_0913_净重之趋）。')
        return 1
    print('✓ 换型令：无「该换而没换」者')
    return 0


