import os, sys, json, glob, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
限 = 12    # 与 书级体检 TYPE_CHAIN_LIMIT 同源（⛔二处若分家，见 自测⑦）
起 = 331   # ⛔自此章起在役。**其由须逐字写明，⛔不许含糊：**
