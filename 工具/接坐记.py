    def 报(名, 得, 期):
        格.append((名, 得 == 期, 得, 期))

    import tempfile
    def 造(版时, 轮记):
        d = tempfile.mkdtemp()
        json.dump({'章': 999, '版本': [{'版': 'v%02d' % (i + 1), '时': t} for i, t in enumerate(版时)]},
                  open(os.path.join(d, '_台账.json'), 'w', encoding='utf-8'), ensure_ascii=False)
        open(os.path.join(d, '_轮记.md'), 'w', encoding='utf-8').write(轮记)
        return d

    # ①一坐一口气跑完·不须声明
    报('①隙短不报', 查一章(造(['09-14 03:30', '09-14 05:00'], ''))[0], False)
