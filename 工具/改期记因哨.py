import os, sys, json, io

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
账档 = os.path.join(ROOT, '设定', '到期账.json')
起 = 331   # ⛔自此章起硬拦（其到期章≥起者）；此前只报不拦
最短 = 12  # 记因之最短字数——⛔「因故改期」四字不算记因


def 有改期之迹(it):
    return bool(it.get('改期时') or it.get('原限') or it.get('reschedule_note')
                or it.get('改期记因'))


def 查(items, 起章=None):
    q = 起 if 起章 is None else 起章
    新, 旧 = [], []
    for it in items:
        if not isinstance(it, dict) or not 有改期之迹(it):
            continue
        因 = str(it.get('改期记因') or '').strip()
        if len(因) >= 最短:
            continue
        n = it.get('到期章') if isinstance(it.get('到期章'), int) else it.get('立账章')
        (新 if isinstance(n, int) and n >= q else 旧).append((it.get('id'), n, len(因)))
    return 新, 旧


def 自测():
    格 = []
    def 报(名, 得, 期): 格.append((名, 得 == 期, 得, 期))
    I = lambda **k: dict(k)

    # ①无改期之迹者不辖
    报('①未改期不报', 查([I(id='a', 到期章=340)])[0], [])
    # ②⛔有改期之迹而记因空·红
    报('②空记因即红', [x[0] for x in 查([I(id='b', 到期章=340, 改期时='0915')])[0]], ['b'])
    # ③记因齐备·绿
    报('③有记因者绿', 查([I(id='c', 到期章=340, 改期时='0915',
                          改期记因='其物在主线柄上，暗线碰即破线，改挂334')])[0], [])
    # ④⛔一行「因故改期」不算记因（不足最短字数）
    报('④含糊者不算', [x[0] for x in 查([I(id='d', 到期章=340, 改期时='0915',
                                       改期记因='因故改期')])[0]], ['d'])
    # ⑤★旧账只报不拦
    新, 旧 = 查([I(id='e', 到期章=300, 改期时='0901')])
    报('⑤旧账不入新红', 新, []); 报('⑤旧账入旧报', [x[0] for x in 旧], ['e'])
    # ⑥reschedule_note 亦算改期之迹（canon 之式）
    报('⑥note亦算迹', [x[0] for x in 查([I(id='f', 到期章=340, reschedule_note='x')])[0]], ['f'])
    # ⑦★SUS-B 之真局：改期而记因齐备者绿
    报('⑦SUS-B真局', 查([I(id='SUS-B-磨窝', 到期章=334, 改期时='0915',
                          改期记因='其物係他那一头柄上之器，暗线碰即破线，改挂334（下一主线之章）')])[0], [])
    # ⑧⛔记因只有空白者不算
    报('⑧空白不算', [x[0] for x in 查([I(id='g', 到期章=340, 改期时='0915', 改期记因='   ')])[0]], ['g'])

    过 = sum(1 for _, ok, _, _ in 格 if ok)
    for 名, ok, 得, 期 in 格:
        if not ok:
            print('  ⛔%s：得 %r，期 %r' % (名, 得, 期))
    print('%s 改期记因哨·自测 %d/%d' % ('✓' if 过 == len(格) else '⛔', 过, len(格)))
    return 0 if 过 == len(格) else 1


def 全书():
    d = json.load(io.open(账档, encoding='utf-8'))
    新, 旧 = 查(d.get('items') or [])
    for i, n, L in 旧:
        print('  ⚠%s（其章 %s）：改过期而记因 %d 字｜**旧账·只报不拦**' % (i, n, L))
    for i, n, L in 新:
        print('  ⛔%s（其章 %s）：改过期而记因 %d 字（须 ≥%d）' % (i, n, L, 最短))
    if 新:
        print('⛔ 改期记因哨：%d 笔改过期而没写为什麽（另有旧账 %d 笔只报不拦）' % (len(新), len(旧)))
        print('  ★其治：於该条 `改期记因` 写明**这一回为什麽挪**，并带其据（回执之逐字或白文之拍号）。')
        print('  ⛔**而一行「因故改期」不算**——**记因那一格是把历回之由摞在一起的地方，摞到第四回人自己就看见了。**')
        return 1
    print('✓ 改期记因哨：新账无「改过期而不写为什麽」者（旧账只报不拦 %d 笔）' % len(旧))
    return 0


if __name__ == '__main__':
    sys.exit(自测() if '--自测' in sys.argv else 全书())
