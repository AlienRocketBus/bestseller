ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CN = {'零': 0, '〇': 0, '一': 1, '二': 2, '三': 3, '四': 4,
      '五': 5, '六': 6, '七': 7, '八': 8, '九': 9}


def cn2i(s):
    """★中文数字转整（只管百以内，「N个字」之数不会更大）。"""
    if not s:
        return -1
    tot, cur = 0, 0
    for ch in s:
        if ch in CN:
            cur = CN[ch]
        elif ch == '十':
            tot += (cur or 1) * 10
            cur = 0
        elif ch == '百':
            tot += (cur or 1) * 100
            cur = 0
        else:
            return -1
    return tot + cur


def _han(s):
    """★只数汉字：标点不计。其据在本书自己的记法——
    ★★271:585「写：一天，没薄。四个字」（四）／285:645「过水，四个人抬，我在前头。头比脚重。」「十四个字」（十四）
    ★★★二处皆不计逗号句号，故此式与全书之例相符。"""
    return re.sub(r'[^一-鿿]', '', s)


# ★取引文之式（按其可信之序）：
#   ①「说／问／答／写的是／写：…：短句。」——冒号之后至行末
#   ②「短句」——全角引号之内
_引冒 = re.compile(r'[：:]\s*([^：:]+?)\s*$')
_引号 = re.compile(r'[「“]([^」”]{1,30})[」”]')


def _取引(前几行):
    """★自近而远取一处引文；取不到即返 None（宁可漏，不可诬）。

    ★★2026-09-01 治二处误抓（其伤在闸不在文）：
      ①151:291「他跟刘二说了三个字：你在后。」／293「刘二应了一个字：成。」——
        ★此式抓了上一行之「你在后」，而「一个字」所指是「成」⛔
        → ★★治：凡该行自带「说了N个字」之数者，其引文归它自己，不许越行去认。
      ②196:61「老头『嗯』了一声，说：『那他手上有准头。』」——
        ★一行之内二引，此式抓了头一个「嗯」⛔ → ★★治：取该行最末一引。
    """
    for l in 前几行[::-1]:
        t = l.strip()
        if not t:
            continue
        # ★该行自带其数者，其引归它自己——不许越行
        自带 = re.search(r'[一二三四五六七八九十百]+个字', t)
        ms = list(_引号.finditer(t))
        if ms:
            引 = ms[-1].group(1)          # ★一行二引者取其末
            return (None, t) if 自带 else (引, t)
        if re.search(r'(说|问|答|喊|叫|写的是|写|念)', t):
            m = _引冒.search(t)
            if m:
                return (None, t) if 自带 else (m.group(1), t)
    return None


# ★★2026-09-01 再治（首版之误报三形，皆由「冒号之后一路吃到行末」而来）：
#   ①206:43「而昨天老头那三个字：手不够，今天四个人的手一双也没多。」——
#     ★「三个字」所指只是「手不够」，其后是执笔之释 ⛔；
#   ②17:43「牌子上写着四个字：此地有主。有主的场子，闲人自己绕道走。」——同形；
#   ③8:139「却一个字是一个字：『是你。』」——「一个字是一个字」是成语，不是数 ⛔。
#   ★★故：有引号者只取引号之内；无引号者只吃到头一个句号为止；
#     ★★★且「一个字是一个字」一形径直不认。
_行内 = re.compile(
    r'(?<!一个字是)([零〇一二三四五六七八九十百]+)个字[：:]\s*'
    # ★★2026-09-01 三治：无引号那一支原只吃到头一个句号，
    #   ★而 233:173「第五十二行我写过六个字：他不急。我们急。」之六字跨两句，遂被读成三字 ⛔；
    #   ★★故改为吃到行末（限三十字），而其滥由 _该报 之二律（前缀合／差逾四）把住。
    r'(?:[「“]([^」”\n]{1,30})[」”]|([^\n]{1,30}))')



# ★★★★★2026-09-01 二治·去五处误报（其伤在闸不在文；今日修尺一役所逼出）：
#   ①**引文之後跟着执笔之释语**，而器把释语也吃了进去：
#     ·169:147「第一行五个字：往回还五天，如今已经错了两天。」——五个字只指「往回还五天」✓
#     ·206:43「而昨天老头那三个字：手不够，今天四个人的手一双也没多。」——只指「手不够」✓
#     ·230:277「传上去就只剩一个字：在，或者不在。」——只指「在」✓
#   ②**引文跨句**：233:173「第五十二行我写过六个字：他不急。我们急。」——六字跨两句 ✓
#   ③**冒号之後是「其意」不是「其字」**：256:961「我看见的是六个字：不是那两圈，不是那两道麻，不是七步。」
#     ★那六个字写在别处，冒号後是它的意思 ✓
# ★★故加二律，二律缺一即仍报：
#   甲·**凡引文之任一自然前缀（逗、句为界）之汉字数等於其标，即不判**——治①②③之大半；
#   乙·**差逾四者不判**——★★其据是今日所修三十处之实测：最大之差为 3（九→十二），
#      ★★★无一处差逾三；而释语之差动辄八九十五 ⛔。
def _前缀合(引, n):
    """★引文之任一自然前缀（以，。！？、；为界）之汉字数等於 n 者，即判其合。"""
    if _han(引) and len(_han(引)) == n:
        return True
    acc = ''
    for ch in 引:
        acc += ch
        if ch in '，。！？、；,;':
            if len(_han(acc)) == n:
                return True
    return False


def _该报(引, n):
    h = _han(引)
    if not h or len(h) == n:
        return False
    if _前缀合(引, n):
        return False
    # ★乙·差逾五者判为释语，不判。
    #   ★★其界初定为四，而负测当场逮出它吞了一处真伤：246「底下八个字：推不动」差五 ⛔；
    #   ★★★复量今日所修三十处之差：最大者正是这个五，其余皆三以内；
    #     ★★★★而五处误报之差为 8／12／9（另二处由前缀之律清掉）——**五与八之间有一道真缝**。
    if abs(len(h) - n) > 5:
        return False
    return True


def 扫行内(ls):
    """★一行之内自带其数者：「他说了三个字：『他下得来。』」——
    ★★此形旧式抓不着（其数与其引同行），而 224:859 正是此形，且它错了：
       「他下得来」四字而标三，且下一行又标一遍三。"""
    bad = []
    for i, l in enumerate(ls):
        t = l.strip()
        m = _行内.search(t)
        if not m:
            continue
        n = cn2i(m.group(1))
        h = _han(m.group(2) or m.group(3) or '')
        引 = m.group(2) or m.group(3)
        if n > 0 and h and len(h) <= 30 and _该报(引, n):
            bad.append((i + 1, 引, n, len(h)))
    return bad


def 扫(path, win=4):
    """★扫一份正文，返回不符者之列 [(行号, 引文, 标, 实)]。

    ★★2026-09-01 补·并扫【本章亮点】（LAW-287A：亮点段亦是正文）。
      ★其由：修尺一役之负测当场逮出——224、225、226 三章之正文已改而亮点未改，
      ★★而亮点里同样写着「钱满接三个字：「水是它的。」」；
      ★★★数闸原本 split 掉亮点，於是**改了一半的错它一处也看不见** ⛔。
    """
    t = io.open(path, encoding='utf-8').read()
    ls = t.split('\n')
    bad = []
    for i, l in enumerate(ls):
        m = re.match(r'^([零〇一二三四五六七八九十百]+)个字[。．]?$', l.strip())
        if not m:
            continue
        n = cn2i(m.group(1))
        if n <= 0:
            continue
        got = _取引(ls[max(0, i - win):i])
        if not got or got[0] is None:
            continue
        引, 原行 = got
        if '…' in 引 or '⋯' in 引:
            continue          # ★省略号者不判
        h = _han(引)
        if not h or len(h) > 30:
            continue
        if _该报(引, n):
            bad.append((i + 1, 引, n, len(h)))
    seen = {x[0] for x in bad}
    for x in 扫行内(ls):
        if x[0] not in seen:
            bad.append(x)
    return sorted(bad)


def 全书(quiet=False):
    out = []
    for f in sorted(glob.glob(os.path.join(ROOT, '正文', '*.md'))):
        for 行, 引, 标, 实 in 扫(f):
            out.append((os.path.basename(f), 行, 引, 标, 实))
    if not quiet:
        print('════ 数闸 · 全书 ════')
        print('  【其式】独立成行之「N个字。」，取其上四行内之引文，剥标点数汉字，与N比。')
        if not out:
            print('  ✓ 零处不符。')
        else:
            print('  ⛔ 不符 %d 处：' % len(out))
            for x in out:
                print('     %-34s 行%-5d 标%-3d 实%-3d ｜%s' % (x[0][:34], x[1], x[3], x[4], x[2]))
    return out


