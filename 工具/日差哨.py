def 表(章库):
    """章库：[(n, body)] 已排序。返回逐章 dict 列表，暗线之章带「日差」与「变」。"""
    out = []
    上主 = None
    上暗差 = None
    上同线 = {}   # 线 → (章, 日)：同线上一有标之章（★同线之日不倒退）
    for 项 in 章库:
        n, body = 项[0], 项[1]
        线, 日 = 线与日(body, 项[2] if len(项) > 2 else None)
        row = {'章': n, '线': 线, '日': 日, '日差': None, '变': False, '退': None}
        if 线 in ('主', '暗') and 日 is not None:
            前 = 上同线.get(线)
            if 前 is not None and 日 < 前[1]:
                row['退'] = 前   # (上一同线章, 其日)
            上同线[线] = (n, 日)
        if 线 == '主':
            # ⛔0922 立·其二：主线之章若读不出日，`上主` 当场作废（⛔不许把上上章之日留着当锚）
            #   ★**其由係本器自己注里那一句**：「**宁不判，不许拿邻章去补**」——
            #   ⛔**而旧式正是拿邻章去补**：352 读不出，`上主` 便留着 350 之 133，
            #     **下一暗线章（353）遂拿一个隔了两章的锚去减，得出一个假差。**
            #   ★★**今改作：读不出即置 None**，**其後之暗线章印「?」不判**——**宁不判。**
            上主 = 日
        elif 线 == '他':
            pass   # 他视角之章不入二线之历
        else:
            if 日 is not None and 上主 is not None:
                row['日差'] = 上主 - 日
                if 上暗差 is not None and row['日差'] != 上暗差:
                    row['变'] = True
                上暗差 = row['日差']
        out.append(row)
    return out


def 读库():
    fs = sorted(glob.glob(os.path.join(ROOT, '正文', '*.md')), key=章号)
    库 = []
    for p in fs:
        n = 章号(p)
        if n < 起:
            continue
        库.append((n, io.open(p, encoding='utf-8').read().split('【本章亮点】')[0], 骨日(n)))
    return 库


def 判(rows):
    """返回 (犯, 漂)。犯：新章（≥新章起）之日差有变者；漂：旧章之日差有变者（只报）。"""
    犯 = []
    for r in rows:
        if r['变'] and r['章'] >= 新章起:
            # ★canon 之出口：该章开镜卡写明「页差改为N·其由」且 N 即本章之差，方许变
            卡 = os.path.join(ROOT, '版本', '第%d章' % r['章'], '_开镜卡.md')
            允 = False
            if os.path.exists(卡):
                m = re.search(r'页差改为\s*(\d+)\s*·', io.open(卡, encoding='utf-8').read())
                允 = bool(m) and int(m.group(1)) == r['日差']
            if not 允:
                犯.append(r)
    漂 = [r for r in rows if r['变'] and r['章'] < 新章起]
    return 犯, 漂


def 退判(rows):
    """返回 (退犯, 退漂)：同线之日倒退者，新章入犯、旧章入漂。"""
    退犯 = [r for r in rows if r['退'] and r['章'] >= 新章起]
    退漂 = [r for r in rows if r['退'] and r['章'] < 新章起]
    return 退犯, 退漂


