ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _读(p):
    try:
        with open(os.path.join(ROOT, p), encoding='utf-8', errors='ignore') as f:
            return f.read()
    except Exception:
        return ''


def _全仓文():
    """诸席之提示、诸器之码、诸令之文——凡人或器读得到的地方。"""
    out = []
    for pat in ('工具/*.py', '工具/席/*.js', '工具/席/*.md', '设定/*.md'):
        for f in glob.glob(os.path.join(ROOT, pat)):
            out.append((os.path.relpath(f, ROOT), _读(os.path.relpath(f, ROOT))))
    return out


def 甲_哑器():
    """接在全测里而从来没在全测之印里出过声的器。
    ★判据之源律：名单不写在本器里——**当场跑一回全测之印**太贵，
      故取其代：读 `工具/全测.py` 之码，取它 run(...) 过的器名，
      再与 `设定/机制体检账.md` 所记之「曾逮出」对照。"""
    qc = _读('工具/全测.py')
    跑过 = set(re.findall(r"run\(\s*'([^']+)'\s*,\s*\['工具/([^']+)'", qc))
    账 = _读('设定/机制体检账.md')
    哑 = []
    for 名, 档 in sorted(跑过):
        if 名.startswith('负测'):
            continue          # 负测之职本就是「不出声即对」，不入此路
        if ('曾逮出·' + 档) in 账 or ('曾逮出·' + 名) in 账:
            continue
        哑.append((名, 档))
    return 哑


# ★必读之册：诸席被写死「动笔前整份读完」者——**住在这里头的令，天天有人读**，
#   故不入乙路（判据之源律：这份名单亦当场自诸席之提示里读，不写死）。
def _必读之册():
    册 = set()
    for f in glob.glob(os.path.join(ROOT, '工具', '席', '*.js')):
        t = _读(os.path.relpath(f, ROOT))
        for m in re.finditer(r'(设定/[^\s`\u3000]+\.md)', t):
            册.add(m.group(1))
    return 册


def 乙_无人读之令():
    """自立之坑／律／令，**住在没人必读之册里、且全仓再无第二处提它**者。
    ★**其形之要**：一条令若住在诸席「动笔前整份读完」的那几册里（起草令／自判之尺…），
      它天天有人读，纵使别处不提也不算没人读——**故先剔去必读之册，再数。**
    ★★这一层是立器当日改的：初版不剔，遂把「坑①—坑④」（皆住在起草令里）报成无人读——
      **那是假红，而一个会喊狼的核对器比没有更糟。**"""
    文 = _全仓文()
    必读 = _必读之册()
    名 = {}
    for p, t in 文:
        if not p.startswith('设定/') or p in 必读:
            continue
        for m in re.finditer(r'(坑[㉑-㉿①-⑳]|【第[一二三四五六七八九十]+律】|常令[一二三四五六七八九十])', t):
            名.setdefault(m.group(1), p)
    出 = []
    for n, 家 in sorted(名.items()):
        c = sum(t.count(n) for _, t in 文)
        if c <= 1:
            出.append((n, c, 家))
    return 出


# ★2026-09-13 立：一行里引着的旧限，不是一笔活挂账。
#   ⛔其事：本器逐坐报「逾限之挂账 3 笔」，而三笔逐行亲读，皆係**已了之账在讲自己的来历**：
#     `人物挂账:39` 之「寨老」那一行自书「**还**·其还处在第318章拍78—85」，
#     其後才引「旧书『限315章』」；`:62` 同人同事，其行自书「限318章……0911 追上……非无声顺延」；
#     `大问挂账:147` 引的是「305 第12轮跑它时印⚠『门后物·限306章』」——**一句转述**。
#   ★**即：本器把「一句话里出现过的限」当成了「这一笔此刻挂着的限」**；
#     ⛔**而一道逐坐报三笔假红的闸，下一坐只会学着不看它**（与 ㊟「一盏没灭过的灯」同骨）。
#   ★★故立此判：**同一行里若已写明它了结了、或它引的是旧限、或它是在转述别处之报，即不作活挂账论。**
#   ⛔**而其牙不许拔**：**凡没有这些记号的逾限之行，照旧逐笔报**（负测之②③格钉住）。
_了结之记 = ('还', '已还', '已销', '已清', '已治', '判驳', '追上',
             '旧书', '旧限', '陈账', '本条已结', '已执', '已付', '改期至', '改限')
_转述之记 = ('印⚠', '印「', '之报', '所报', '逐字', '其红在哪一行', '当日印')


def _活挂账(line):
    """★这一行是「一笔此刻挂着的账」，还是「一句讲旧事的话」。

    ★★2026-09-23 补一式（⛔**其所由来係本坐自己写的一份裁档**）：
      **`设定/裁_0922_大问挂账_血图与爷爷逾352.md:4` 逐字引着器之印**
      （「> 「⛔挂了账而逾了自己那个限者 2 样：血图（限352章，今354章）……」」）——
      **那是一句引文，而本器把它读成了一笔此刻挂着的账**，`负测_活挂账 ③` 当场判红。
    ★★★**故加一式**：**markdown 之引块（行首 `>`）一律不算活挂账**——
      **引块之义即「这不是我在说，是我在引」**；⛔**而其余诸式一格未动。**
    ⛔**其价写明**：**若有人把一笔真账写进引块里，本器此後看不见它**——
      **故立一条**：**真账不许写在引块里**（账要么在表里，要么在列里）。
    """
    if line.lstrip().startswith('>'):
        return False
    for k in _了结之记 + _转述之记:
        if k in line:
            return False
    return True


def 丙_逾限之挂账():
    出 = []
    for p in glob.glob(os.path.join(ROOT, '设定', '*挂账*.md')):
        rp = os.path.relpath(p, ROOT)
        for i, line in enumerate(_读(rp).split('\n'), 1):
            m = re.search(r'限\s*第?\s*(\d+)\s*章', line)
            if m and _活挂账(line):
                出.append((rp, i, int(m.group(1)), line.strip()[:70]))
    末 = 末章()
    return [x for x in 出 if x[2] < 末]


def 末章():
    n = 0
    while glob.glob(os.path.join(ROOT, '正文', '*第*章_*.md')) and _章在(n + 1):
        n += 1
    return n


_汉 = '零一二三四五六七八九'


def _汉数(n):
    if n < 0 or n >= 1000:
        return ''
    if n < 10:
        return _汉[n]
    if n < 20:
        return '十' + (_汉[n % 10] if n % 10 else '')
    if n < 100:
        return _汉[n // 10] + '十' + (_汉[n % 10] if n % 10 else '')
    s = _汉[n // 100] + '百'
    r = n % 100
    if r == 0:
        return s
    if r < 10:
        return s + '零' + _汉[r]
    return s + _汉[r // 10] + '十' + (_汉[r % 10] if r % 10 else '')


def _章在(n):
    return bool(glob.glob(os.path.join(ROOT, '正文', '*第%s章_*.md' % _汉数(n))))


