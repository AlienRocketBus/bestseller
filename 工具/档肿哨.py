import os, sys, io

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
硬界 = 8 * 1024 * 1024    # ⛔逾此即红（远端拒收之界，非美观之界）
软界 = 2 * 1024 * 1024    # ⚠逾此只报
重界 = 4.0                # 非空行 ÷ 唯一非空行 ≥ 此数即算空转之形
重行底 = 1000             # ⛔而行数不足此数者不辖（短档天然多重句）
查之处 = ('版本', '设定', '工具')
查之尾 = ('.md', '.json', '.txt')


def 判(名, 字节, 非空行, 唯一非空行):
    """⛔纯判·不碰盘。回 ('红'|'黄'|'绿', 其由)。"""
    if 字节 >= 硬界:
        return '红', '字节 %d 逾硬界 %d（推不上去之界）' % (字节, 硬界)
    if 名.endswith('.md') and 非空行 >= 重行底 and 唯一非空行 > 0 \
            and 非空行 / float(唯一非空行) >= 重界:
        return '红', '非空行 %d ÷ 唯一非空行 %d ＝ %.1f 倍（追加之器空转之形）' % (
            非空行, 唯一非空行, 非空行 / float(唯一非空行))
    if 字节 >= 软界:
        return '黄', '字节 %d 逾软界 %d' % (字节, 软界)
    return '绿', ''


def 量(路):
    字节 = os.path.getsize(路)
    非空, 集 = 0, set()
    if 路.endswith('.md') and 字节 < 512 * 1024 * 1024:
        with io.open(路, encoding='utf-8', errors='replace') as f:
            for ln in f:
                s = ln.strip()
                if s:
                    非空 += 1
                    集.add(s)
    return 字节, 非空, len(集)


def 走():
    红, 黄 = [], []
    for 处 in 查之处:
        base = os.path.join(ROOT, 处)
        if not os.path.isdir(base):
            continue
        for dp, dns, fns in os.walk(base):
            dns[:] = [d for d in dns if d not in ('.git', '__pycache__', 'node_modules')]
            for fn in fns:
                if not fn.endswith(查之尾):
                    continue
                p = os.path.join(dp, fn)
                try:
                    字节, 非空, 唯一 = 量(p)
                except OSError:
                    continue
                色, 由 = 判(fn, 字节, 非空, 唯一)
                rel = os.path.relpath(p, ROOT)
                if 色 == '红':
                    红.append((rel, 由))
                elif 色 == '黄':
                    黄.append((rel, 由))
    return 红, 黄


