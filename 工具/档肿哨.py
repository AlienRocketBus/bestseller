    报('②硬界红', 判('_轮记.md', 113178856, 424670, 1385)[0], '红')
    # ③★重肿而未逾硬界者亦红——**本器之所以不只是一把尺**
    报('③重肿亦红', 判('_轮记.md', 3000000, 40000, 1385)[0], '红')
    # ④⛔短档天然多重句·不辖
