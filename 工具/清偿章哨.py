import os, sys, json, io

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
账档 = os.path.join(ROOT, '设定', '到期账.json')
了结 = ('done', 'closed', '已清', '已还')
章之上限 = 1000   # ⛔逾此者係「不设到期章」之哨兵，非章号
起 = 331   # ⛔自此章起硬拦；此前者只报不拦（其由见器头）


def 查(items, 起章=None):
    """回 (新红, 旧报)。⛔items 可由外给，便於负测回灌。"""
    q = 起 if 起章 is None else 起章
    新, 旧 = [], []
    for it in items:
        if not isinstance(it, dict):
            continue
        if str(it.get('状态', '')).lower() not in [x.lower() for x in 了结]:
            continue
        if it.get('清偿章'):
            continue
        # ★哨兵之治（0915 立器当日自逮）：`到期章` 有以 1000000000 记「**不设到期章**」者
        #   （`PLOT-113B`·背景线·随归寨随时可出）——⛔**那不是一个章号**，
        #   **拿它去比 `起`，一笔旧账就被判成新账**。故逾 `章之上限` 者退取 `立账章`。
        d = it.get('到期章')
        n = d if isinstance(d, int) and d <= 章之上限 else it.get('立账章')
        (新 if isinstance(n, int) and n >= q else 旧).append((it.get('id'), n))
    return 新, 旧


def 自测():
    格 = []
    def 报(名, 得, 期): 格.append((名, 得 == 期, 得, 期))
    I = lambda **k: dict(k)

    # ①了结而有清偿章·绿
    报('①有清偿章不报', 查([I(id='a', 状态='done', 到期章=331, 清偿章=331)])[0], [])
    # ②⛔了结而清偿章空·红（新账）
    报('②空者红', [x[0] for x in 查([I(id='b', 状态='done', 到期章=331)])[0]], ['b'])
    # ③closed 亦在辖（FS03-331 之真局：其状态写作 closed 而非 done）
    报('③closed亦辖', [x[0] for x in 查([I(id='FS03-331', 状态='closed', 到期章=331)])[0]], ['FS03-331'])
    # ④未了结者不辖（open 之账本就没清，非本器所问）
    报('④open不报', 查([I(id='c', 状态='open', 到期章=331)])[0], [])
    # ⑤★旧账只报不拦（330 之五笔之真局）
    新, 旧 = 查([I(id='ARC-330', 状态='done', 到期章=330)])
    报('⑤旧账不入新红', [x[0] for x in 新], [])
    报('⑤旧账入旧报', [x[0] for x in 旧], ['ARC-330'])
    # ⑥无到期章者取立账章
    报('⑥取立账章', [x[0] for x in 查([I(id='d', 状态='done', 立账章=340)])[0]], ['d'])
    # ⑦⛔「已还」「已清」二式亦辖（⛔不许只认 done 一个词·㊯ 之族）
    报('⑦已还亦辖', [x[0] for x in 查([I(id='e', 状态='已还', 到期章=331)])[0]], ['e'])
    报('⑦已清亦辖', [x[0] for x in 查([I(id='f', 状态='已清', 到期章=331)])[0]], ['f'])
    # ⑧★哨兵之齿（PLOT-113B 之真局）：到期章＝1000000000 係「不设到期章」，
    #   ⛔不许据它判作新账——须退取立账章（113），故只入旧报
    新8, 旧8 = 查([I(id='PLOT-113B', 状态='done', 到期章=1000000000, 立账章=113)])
    报('⑧哨兵不入新红', [x[0] for x in 新8], [])
    报('⑧哨兵入旧报', [x[0] for x in 旧8], ['PLOT-113B'])
    # ⑨清偿章为 0 不算有（0 不是章号）
    报('⑨零不算有', [x[0] for x in 查([I(id='g', 状态='done', 到期章=331, 清偿章=0)])[0]], ['g'])

    过 = sum(1 for _, ok, _, _ in 格 if ok)
    for 名, ok, 得, 期 in 格:
        if not ok:
            print('  ⛔%s：得 %r，期 %r' % (名, 得, 期))
    print('%s 清偿章哨·自测 %d/%d' % ('✓' if 过 == len(格) else '⛔', 过, len(格)))
    return 0 if 过 == len(格) else 1


