def 挑刺客(n):
    """本章白文＋前章白文。问：哪一处前后对不上／哪一句是替人物想的。

    ★★★★★2026-09-02·九席审读所逮·当日治：**此席之抬头与 docstring 两处自称
      「本章白文＋前章白文」，而函数体只取 `白文(n)`——前章一次也没取过**；
      ★故其头一问「哪一处前后对不上」**根本没有代码**，而它每章印一行抬头，
      教人以为那一问查过了。★★**这正是令§一⑤所指的那一种**：
      **它不是查过了判无罪，它是压根没查。**
      ★★★今补取前章，并把「前後对不上」实做成一问（见问〇）。"""
    f, t = 白文(n)
    if not t:
        return ['⛔第%d章白文取不着' % n], []
    _fp, 前 = 白文(n - 1)
    _fp2, 前2 = 白文(n - 2)
    bs = 拍(t)
    out = ['── 挑刺客·第%d章白文＋前二章白文（第%s章／第%s章）──'
           % (n, (n - 1) if 前 else '⛔', (n - 2) if 前2 else '⛔')]
    挂 = []

    # 问〇·前後对不上（2026-09-02 补·此问立於首日而无代码，今补）
    #   ★其法只查一样机器答得准的：**同一句短语在本章与前章逐字重出**——
    #     ★★而这一样单章之查重看不见（查重只在章内比），连读客亦看不见（它只比末笔与开篇）；
    #     ★★★其实证：291「不热，不凉。中间这一档我没有名字给它。」与
    #       292「多的那一点不到半节。她没有名字给它。」——**隔一章，一个「我」一个「她」，
    #       同一个句式一字未改**；★★★★**两个第一人称共用一句口头禅，全书无一闸看得见。**
    #   ★而它认不着的：换一整套词说同一件事者（那是人判的，见「一事几陈」）。
    # ★★★★★2026-09-03·294第7轮所逮·当日补：**问〇只比 n 与 n-1，而本书二线交替**——
    #   ★**同线之前章是 n-2**；★★其实证：**292拍77「外头有人从门前走过去，脚步在门槛外头
    #     顿了一下，没进来」与 294拍53 几乎逐字相同**，而问〇（只看293）一处也没报；
    #   ★★★**即：这道闸立起来是为了逮跨章重出，而它偏偏看不见同一条线上的重出**——
    #     **而同线才是最容易重的那一条**（同一个人、同一间屋、同一件事）。
    #   ★★★★故今兼比 n-1 与 n-2，并各自标出其来处。
    if 前 or 前2:
        _a = {}
        for _src, _t in ((n - 1, 前), (n - 2, 前2)):
            if not _t:
                continue
            for _x in 拍(_t):
                for _j in range(len(_x) - 5):
                    _a.setdefault(_x[_j:_j + 6], _src)
        _重 = []
        for _i, _x in enumerate(bs):
            for _j in range(len(_x) - 5):
                _g = _x[_j:_j + 6]
                if _g in _a and not re.fullmatch(r'[，。、；：？！\s]+', _g):
                    _重.append((_i + 1, _g, _a[_g]))
                    break
        _重 = _重[:8]
        if _重:
            out.append('   ── 问〇「与前章逐字重出之语」──')
            for _i, _g, _s in _重:
                out.append('     拍%-4d「%s」（出第%d章）' % (_i, _g, _s))
            out.append('     ★六字以上逐字重出者 %d 处；★★而其中若有一处是二线共用之句式，'
                       '**那是两个第一人称共用一副嗓子**，非承前。' % len(_重))
            挂.append('挑刺客·与前二章逐字重出 %d 处（首处拍%d「%s」出第%d章）'
                      % (len(_重), _重[0][0], _重[0][1], _重[0][2]))
        else:
            out.append('   ✓问〇：与前二章无六字以上逐字重出之语。')

    # 问一·替人物想的（写他人心中事）
    越 = []
    人 = r'(他|她|它|老头|钱满|刘二)'
    心 = r'(以为|想的是|知道|打算|准备|怕|盼|巴不得|舍不得|心想|暗想|心里明白|心里清楚|心里一沉|觉得)'   # ★2026-09-05 添六词（八路·硬闸探伤审第9条：九例漏七）
    for i, x in enumerate(bs):
        if re.search(人 + r'(?:心里)?' + 心, x) and not re.match(r'^(我|她)', x):
            越.append((i, x[:32]))
    if 越:
        挂.append('挑刺客·疑越权：%d处' % len(越))
        out.append('   ⚠问一「哪一句是替人物想的」：%d处。' % len(越))
        for i, x in 越[:3]:
            out.append('     拍%d：%s' % (i, x))
    else:
        out.append('   ✓问一：无替人物想之句。')

    # 问二·数之无着（出数而全章不复见者）
    数 = Counter(re.findall(r'[一二三四五六七八九十百零]+(?=天|日|页|行|回|下|个|把|寸|尺|遍)', re.sub(r'\s', '', t)))
    孤 = [(k, v) for k, v in 数.items() if v == 1 and len(k) >= 2]
    out.append('   ── 问二「哪个数只出现一回，往后没人再提」──')
    if 孤[:5]:
        for k, v in 孤[:5]:
            out.append('     「%s」1回' % k)
        out.append('     ★只出一回之数未必是伤；然若它是本章之据，须有第二处与之相比。')
    else:
        out.append('   ✓无孤数。')
    return out, 挂


