def 生客(n):
    """只读本章白文。问：哪一拍看不懂／哪儿忘了人在干什么／几处要回头。"""
    f, t = 白文(n)
    if not t:
        return ['⛔第%d章白文取不着' % n], []
    bs = 拍(t)
    out = ['── 生客·只读第%d章白文（%s），不看前章、不看轮记 ──' % (n, f),
           '   全章%d拍。' % len(bs)]
    挂 = []

    # 问一·哪一段读着忘了人在干什么（连续无动之最长一段）
    最长, 起, 当前, 当前起 = 0, 0, 0, 0
    for i, x in enumerate(bs):
        if 手.search(x):
            当前, 当前起 = 0, i + 1
        else:
            当前 += 1
            if 当前 > 最长:
                最长, 起 = 当前, 当前起
    if 最长 >= 12:
        挂.append('生客·无动之段：拍%d—%d连%d拍无一手上之事' % (起, 起 + 最长 - 1, 最长))
        out.append('   ⛔问一「读到哪儿忘了她手上在干什么」：')
        out.append('     拍%d—%d，连%d拍无一手上之事。' % (起, 起 + 最长 - 1, 最长))
        out.append('     首拍：%s' % bs[起][:34])
        out.append('     末拍：%s' % bs[起 + 最长 - 1][:34])
    else:
        out.append('   ✓问一：最长无动之段%d拍（限12）。' % 最长)

    # 问二·哪一拍要回头（承前之字而前拍未出其指）
    # ★★★★★2026-09-01 量而不改·287第11轮。★此式只认「拍首之没」＋「其次字不在前一拍」，
    #   ★★而数其群：全书命中 109 处、报红 90 章（31%），随手取八处皆假
    #     （「没有人说」「没有人答」「没有味」「没头的空压人」）⛔。
    #   ★★★然今日拟过一式（本拍有定指之词那X／这X而其所指不在近二拍者方红），
    #     ★★★★当场量之：287 由 1 处涨至 39 处，其中「那块平石」「那个弯」皆是初出之物，
    #        ★以「那」引新物本是此书之常法——新式误报远多於旧式 ⛔。
    #   ★★故照令§六④「改后它还逮不逮得住它本来要逮的东西」之问：判不改闸，只记其量。
    #     ★★★而在换成之前，此闸之红一律由人当场裁，且每回把裁语写进轮记。
    回头 = []
    for i, x in enumerate(bs):
        if i == 0:
            continue
        m = re.match(r'^(没|这一|那一|它|他|她)(.)', x)
        if not m:
            continue
        if m.group(1) == '没' and m.group(2) not in bs[i - 1]:
            回头.append((i, x[:30]))
    if 回头:
        挂.append('生客·要回头：%d处' % len(回头))
        out.append('   ⚠问二「哪一句读了两遍才懂」：%d处承前之字，其前拍未出所指。' % len(回头))
        for i, x in 回头[:3]:
            out.append('     拍%d：%s' % (i, x))
    else:
        out.append('   ✓问二：无承前失指之拍。')

    # 问三·同一名物在一章内出多少回（读者会觉得绕的那个）
    t2 = re.sub(r'[\s＊]', '', t)
    # ⛔★★★★★2026-09-23·限359（本坐跑 `--生客 357` 时所逮）：
    #   ★**旧式之窗跨句而取**，於是 357 之报头一行印作「**。她把指**」11回——
    #     **那一点句号是上一句的尾巴，不是这一样东西的名字。**
    #   ⛔**而其害不止於难看**：**本问所数者係「有没有一样东西说得太多」**，
    #     **而一个带着句号的窗只数得着「句首那几个字」**——
    #     **同一个词落在段中者，它一个也数不着**；★**於是它报的数比实数小，而它印得像个实数。**
    #   ★★**并及一件**：**带标点那一支还占着 `top[:3]` 的位子**，
    #     **把真正说得太多的那一样挤下榜**（357 即如此）。
    #   ★★★**故凡窗内含标点者不计**——**一样东西的名字不跨句**。
    #   ⛔**而「句首同形」那一路不是本问之职，盘上另有器在看**（`比带.py` 逐章数「她把」之比）；
    #     **本改一格未动它。**
    _标 = '。，、；：？！「」『』（）—…·《》'
