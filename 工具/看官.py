def _线(n):
    """三值（与 开轮六检._line_of 同尺）：主（我≥3/千）｜她｜他。"""
    _f, t = 白文(n)
    if not t:
        return None
    w = len(re.sub(r'\s', '', t)) or 1
    if t.count('我') / w * 1000 >= 3:
        return '主'
    return '她' if t.count('她') >= t.count('他') else '他'


def _prev_same(n):
    me = _线(n)
    if me is None:
        return None
    for k in range(n - 1, max(0, n - 13), -1):
        if _线(k) == me:
            return k
    return None


def _重出率(x, y):
    """★x与y两章之白文，逐拍找≥10字逐字重出，返回其占y之拍数之百分比。
    ★★只量白文（`白文()` 已去章题、亮点段），不量轮记。"""
    _f1, t1 = 白文(x)
    _f2, t2 = 白文(y)
    if not t1 or not t2:
        return None
    A, B = 拍(t1), 拍(t2)
    if not A or not B:
        return None
    sa = set()
    for p in A:
        q = re.sub(r'[\s＊]', '', p)
        for L in range(10, 26):
            for i in range(len(q) - L + 1):
                sa.add(q[i:i + L])
    n = 0
    for p in B:
        q = re.sub(r'[\s＊]', '', p)
        for L in range(25, 9, -1):
            if any(q[i:i + L] in sa for i in range(len(q) - L + 1)):
                n += 1
                break
    return 100.0 * n / len(B)


