def 评论员(n, 比=6):
    """第五席·最好的评论员。

    ★★★★★此席亦强制出负：不许说「好」，只许说**这一章弱在哪一处**，且须拿数说话。
      其法是横比——把本章与前若干章逐项比，取其最差一项，指为本章之弱。
    ★而须自陈一限：**它比得出「本章与旧章之别」，比不出「本书与他书之别」。**
      我没有一把尺能拿它跟外头的书比。此限写在这儿，免得日后拿它当文学史使。
    """
    f, t = 白文(n)
    if not t:
        return ['⛔第%d章白文取不着' % n], []
    import statistics as st

    def 量(x):
        bs = 拍(x)
        if not bs:
            return None
        L = [len(y) for y in bs]
        L2 = sorted(L)
        ss = [y for y in re.split(r'[。！？]', re.sub(r'\s', '', x)) if y]
        动 = sum(1 for y in bs if 手.search(y))
        return {'拍': len(bs), '最长': max(L),
                '段方差': st.pvariance(L),
                '90分位': L2[int(len(L2) * 0.9)],
                '句方差': st.pvariance([len(y) for y in ss]),
                '长拍%': round(100 * sum(1 for y in L if y >= 33) / len(L)),
                '动拍%': round(100 * 动 / len(bs))}

    本 = 量(t)
    旧 = []
    for m in range(n - 比, n):
        _, x = 白文(m)
        if x:
            v = 量(x)
            if v:
                旧.append((m, v))
    out = ['── 最好的评论员·第%d章（%s）──' % (n, f),
           '   ★本席不许说好。本席只说：**这一章弱在哪一处**，且拿数说话。']
    挂 = []
    if not 旧:
        out.append('   ⛔无旧章可比，本席失职。')
        return out, ['评论员·失职：第%d章无可比之章' % n]
    弱 = []
    for k in ['最长', '段方差', '90分位', '句方差', '长拍%', '动拍%']:
        中 = st.median([v[k] for _, v in 旧])
        if 中 and 本[k] < 中:
            弱.append((round(100 * (中 - 本[k]) / 中), k, 本[k], 中))
    弱.sort(reverse=True)
    out.append('   横比前%d章（%s）：' % (len(旧), '、'.join(str(m) for m, _ in 旧)))
    for k in ['拍', '最长', '段方差', '90分位', '句方差', '长拍%', '动拍%']:
        中 = st.median([v[k] for _, v in 旧])
        记 = '⚠' if (k in dict((z[1], 1) for z in 弱)) else ' '
        out.append('     %s%-6s 本章%7s ｜ 前%d章中位%7s'
                   % (记, k, round(本[k], 1), len(旧), round(中, 1)))
    if 弱:
        d, k, a, b = 弱[0]
        out.append('   ⛔本章之弱，在「%s」：本章%s，而前%d章中位%s，低%d%%。'
                   % (k, a, len(旧), round(b, 1), d))
        挂.append('评论员·第%d章之弱在「%s」（%s对中位%s，低%d%%）' % (n, k, a, round(b, 1), d))
    else:
        out.append('   ⛔本席失职：逐项皆不低於中位，出不了负。**而这多半是尺不够，不是章太好。**')
        挂.append('评论员·失职：第%d章出不了负，尺须加' % n)
    out.extend(_三条带(n, 本, 量, [k for _, k, _, _ in 弱]))
    out.append('   ★★而此席之限：它比得出本章与旧章之别，比不出本书与他书之别。')
    return out, 挂


def _三条带(n, 本, 量, 弱项):
    """★评论员之第二、第三条带（2026-09-03·298第13轮·补跑第7轮所立）。

    ★立此带之由：本席之群只一条——「前6章之窗」；★★而 `比带.py` 两造之前就立过
      「一个数报三条带（全书／同镜／同形），三条带若不同判，以同形为先」，
      且其档头自陈「本坐第5、7、8三轮各栽一回，皆因只看同镜那一条」。
    ★★★而298第13轮实逮：本席判「本章之弱在动拍%：本章46，前6章中位54.5，低17%」——
      **而全书200至298章之中位是42.0，同形「做事」41章之中位是43.0；本章46，两条带皆在其上。**
      ★★★★即：那个「弱」是六章之窗造出来的（292—297恰是一段动拍极密之章，其带46—62）。
    ★而本带只添不减：**本席照旧强制出负，其判一字不改**；
      ★★此三行只答一句「这个弱，出自本章，还是出自那六章」——**判归判，其群另报。**
    ★★★其判据（令§六④：立闸须写「它认哪几样，本书同类共几样」）：
      · 它认哪几样：**只认本席自己那七项之中被判为弱者**，逐项报三条带（前N章之窗／全书／同形）。
      · 本书同类共几样：**报「一个数」而只取一条群者，全仓另有一处**——旧 连读客（〔1119 W908 环7 汰〕）之
        「群31对·中位2.1%」係全书相邻同线之章之全集，非窗，**故它不在此病之列**；
        **即本病之同类共一样，已治**。
    """
    import statistics as st
    if not 弱项:
        return []
    try:
        import importlib.util as _iu
        _sp = _iu.spec_from_file_location(
            '_bidai', os.path.join(ROOT, '工具', '比带.py'))
        _bd = _iu.module_from_spec(_sp)
        _sp.loader.exec_module(_bd)
        我形 = _bd._形(n)
    except Exception:
        return ['   ⚠三条带取不着（比带.py 不可读）：本席之判只出自前N章之窗。']
    全书, 同形 = [], []
    for m in range(1, n):
        _, x = 白文(m)
        if not x:
            continue
        v = 量(x)
        if not v:
            continue
        全书.append(v)
        try:
            if _bd._形(m) == 我形:
                同形.append(v)
        except Exception:
            pass
    if not 全书:
        return []
    o = ['   ★★★★★而本席之群只一条（前N章之窗）；今另报二条（令§六②·数其群）：',
         '     本章之形「%s」｜全书 %d 章｜同形 %d 章' % (我形, len(全书), len(同形))]
    for k in 弱项:
        for xs, lab in ((全书, '全书'), (同形, '同形「%s」' % 我形)):
            if not xs:
                continue
            ys = sorted(v[k] for v in xs)
            中 = st.median(ys)
            判 = '★本章在其上' if 本[k] > 中 else (
                '本章在其下' if 本[k] < 中 else '本章正在中位')
            o.append('     %-6s %-10s 章数%-4d 带 %s—%s 中位 %s ｜本章 %s  %s'
                     % (k, lab, len(ys), round(ys[0], 1), round(ys[-1], 1),
                        round(中, 1), round(本[k], 1), 判))
    o.append('     ★而三条带若不同判，以同形为先——**一个「弱」若只在窗里弱，'
             '它弱的是那几章，不是本章。**')
    return o


def _判之键(判):
    """★1020 W53·X23：判之身——连读客问五之判以「章对＋率」为身（窗移则限变，判不变）；余判回 None（仍以 (判, 限) 为键）。"""
    m = re.search(r'(\d+)→(\d+) 达 ([\d.]+)%', 判 or '')
    return ('重出', int(m.group(1)), int(m.group(2)), m.group(3)) if m else None


def _称治(状):
    """状称已治（治／已治／已办）者——同判再现即治而未治，须再记；余状（open、驳、裁、判不治、并入…）皆「已在账」。"""
    return str(状 or '').startswith(('治', '已治', '已办'))


def 记账(条目, 限=None, 重=None):
    """★★★★★「限」须落笔即带（2026-08-27 立）。

    ★其由：看官账之律早写着「每笔须带限」，而本函数根本没有这个字段——
      故十七笔之限皆空，账积而无期。
    ★★律写在数据里，而写数据的代码不认它——此与坑01同型（写下来的法不生效），
      只是这一回它连闸都不是，是一句只对自己说的话。
    ★★★故今焊之：不给限即报错，不许再落无限之笔。
    """
    d = {'说明': '看官账：三席所判之不过，挂於此；下一章开镜卡上带着。★不许当场辩。',
         'items': []}
    if os.path.exists(账):
        d = json.load(open(账, encoding='utf-8'))
    import datetime
    # ★★★★★2026-09-02·九席审读所逮·当日治：**本函数无去重，全测每跑一次即重挂一条**；
    #   ★其实：账 105 笔里 33 笔是逐字重出者（31%）——「生客·要回头：1处」重了七回；
    #   ★★而 `落凭()` 反而是按「席+章」去重的——**去重写在了不要紧的那一头**；
    #   ★★★其害不在多几行，在**把账变成噪声**：真的那几笔（连读客逮着的开篇重出）
    #     淹在一堆重复里，於是 105 笔里 93 笔无人清（88.6%）。
    #   ★★★★故按 (判, 限) 去重：同一席同一章同一判，只留一条。
    # ★★★★★1020·W53·X23（396 推所逮）：**(判, 限) 之键认不着「窗移」**——394、395 封版各跑连读客（窗 N-4—N），
    #   二窗俱含 392→394，判逐字同（11.4%）而限 395／396 异，遂重记二笔，违律②「重跑不重记」；
    #   ★今加判之身：连读客问五以「章对＋率」为身，同身已在账（状非「治／已治／已办」）者⛔重记；
    #   ⛔率变即新判（文改了）；称治而同率再现即治而未治，照记。重者交 `重`（主跑者当面印其状与限）。
    #   ★1020 独立验席（X23）：旧键 (判, 限) 不撇称治者——同章内标治後重跑，同限同判仍⛔重记（违上句）；今二键俱只认未称治者。
    _在 = [x for x in d['items'] if not _称治(x.get('状态'))]
    _身 = {}
    for x in _在:
        _s = _判之键(x.get('判'))
        if _s:
            _身.setdefault(_s, (str(x.get('状态') or ''), str(x.get('限'))))
    _旧 = {(x.get('判'), str(x.get('限'))): (str(x.get('状态') or ''), str(x.get('限'))) for x in _在}
    _已 = set(_旧)
    for x in 条目:
        _k = (x, str(限) if 限 else '★未定·须补')
        _s = _判之键(x)
        if _k in _已 or (_s and _s in _身):
            if 重 is not None:
                重.append((x, _身.get(_s) or _旧.get(_k) or ('本回已记', _k[1])))
            continue
        _已.add(_k)
        if _s:
            _身[_s] = ('open', _k[1])
        d['items'].append({'判': x, '时': datetime.date.today().isoformat(),
                           '状态': 'open', '限': str(限) if 限 else '★未定·须补'})
    json.dump(d, open(账, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    return len(d['items'])


