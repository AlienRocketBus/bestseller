def 末章():
    CN = {'零': 0, '〇': 0, '一': 1, '二': 2, '三': 3, '四': 4, '五': 5,
          '六': 6, '七': 7, '八': 8, '九': 9}
    best = 0
    for p in glob.glob(os.path.join(ROOT, '正文', '*.md')):
        m = re.search(r'第([零〇一二三四五六七八九十百]+)章', os.path.basename(p))
        if not m:
            continue
        t = n = 0
        for ch in m.group(1):
            if ch in CN:
                n = CN[ch]
            elif ch == '十':
                t += (n or 1) * 10
                n = 0
            elif ch == '百':
                t += (n or 1) * 100
                n = 0
        best = max(best, t + n)
    return best


