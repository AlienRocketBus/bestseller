    def 报(名, 得, 期): 格.append((名, 得 == 期, 得, 期))
    I = lambda **k: dict(k)

    # ①尚在限内者不辖
    报('①限内不辖', 判([I(状态='open', 限='340', 判='x')], 338)[0], [])
