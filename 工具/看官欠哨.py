def _重跑其数(判语):
    """★一笔账上写着的那个数，拿今日之盘重跑一回，回 (册上, 今跑) 二数；取不着者回 (None, None)。

    ★★★★★2026-09-22 立（其裁在 `设定/裁_0922_看官账_347至349之重出.md` §五之三）：
      ⛔**其红之实证**：**346→348 一笔入账时作 23.1%，而 0922 本坐拿末版白文重跑得 7.7%。**
      ★**其所以漂**：**348 自入账之後末版由 v? 走到 v13，第9／10 轮各删过一刀**，
        **删掉的正可能是那几串**；
      ★★**而要紧的不是它为什么漂，是「一笔入了账的数，没有一道器在它所指之章改版之後重跑它」**
        ——⛔**於是账上那个数与盘上那个数各走各的，而闸读的是账上那一个。**
      ★★★**故本器印一笔之前先重跑，印作「册上 N％／今跑 M％」**；
        ⛔**若二者不合，其红不是那一章的，是那一笔账的。**
      ⛔**而本路只印不判**：**它不改那一笔之状、不销它、不替它挪限**——
        **一笔账该不该销，是人的判；本路只把「它说的还算不算数」摆在那句判语旁边。**
      其负测：`工具/看官欠哨.py --自测` 之 ⑦⑧。
    """
    m = re.search(r'(\d+)\s*→\s*(\d+)', 判语 or '')
    if not m:
        return (None, None)
    a, b = int(m.group(1)), int(m.group(2))
    m2 = re.search(r'(\d+(?:\.\d+)?)\s*%', 判语 or '')
    册 = float(m2.group(1)) if m2 else None
    try:
        import importlib.util
        _p = os.path.join(ROOT, '工具', '看官.py')
        _s = importlib.util.spec_from_file_location('_kg', _p)
        _m = importlib.util.module_from_spec(_s)
        _s.loader.exec_module(_m)
        今 = _m._重出率(a, b) if hasattr(_m, '_重出率') else None
    except Exception:
        今 = None
    return (册, 今)


