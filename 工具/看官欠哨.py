def 末章():
    CN = {'零': 0, '〇': 0, '一': 1, '二': 2, '三': 3, '四': 4, '五': 5,
          '六': 6, '七': 7, '八': 8, '九': 9}
    best = 0
    for p in glob.glob(os.path.join(ROOT, '正文', '*.md')):
        m = re.search(r'第([零〇一二三四五六七八九十百]+)章', os.path.basename(p))
        if not m:
            continue
        t = n = 0
        for ch in m.group(1):
            if ch in CN:
                n = CN[ch]
            elif ch == '十':
                t += (n or 1) * 10
                n = 0
            elif ch == '百':
                t += (n or 1) * 100
                n = 0
        best = max(best, t + n)
    return best


def 读():
    d = json.load(io.open(账档, encoding='utf-8'))
    return d.get('items') or []


def 判(items, 末, 起章=None):
    """⛔纯判·不碰盘。返回 (新红, 旧账)。**过其限而仍 open 者方入。**"""
    q = 起 if 起章 is None else 起章
    新, 旧 = [], []
    for x in items:
        if not isinstance(x, dict) or x.get('状态') != 'open':
            continue
        lim = str(x.get('限') or '').strip()
        if not lim.isdigit():
            continue
        n = int(lim)
        if n >= 末:                      # ★尚在限内者不辖
            continue
        (新 if n >= q else 旧).append((n, str(x.get('判') or '')[:60]))
    return sorted(新), sorted(旧)


