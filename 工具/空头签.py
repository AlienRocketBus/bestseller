def 查(根=None):
    R = 根 or ROOT
    fps = sorted(glob.glob(os.path.join(R, '设定', '回执_*.md')))
    坏, 含签, 旧式自销, 早签 = [], 0, 0, []
    for fp in fps:
        m = re.search(r'第(\d+)章', os.path.basename(fp))
        if not m:
            continue
        C = int(m.group(1))
        tx = io.open(fp, encoding='utf-8', errors='replace').read()
        ns = set(int(x) for x in re.findall(r'(\d+)章冷眼轮', tx))
        if ns:
            含签 += 1
        if C in ns:
            # ★★★★★2026-09-22 补·**否决在先，签核在後**（353 封版之日所逮）
            #   ⛔**其红之实**：353 之封版席在一节之内写下那六个字，**而同节当场落其否决记**
            #     （「**COLD-353·本章未执**」），**并逐字写明「本席写下这六个字，不是为了销一笔账」**；
            #   ★**亲跑坐实其未销**：`开轮六检.py::_cold_done(353)` → **False**——**那一笔一分未销。**
            #   ★★**即本器报了一条假红，而其假之形，正是 `开轮六检` 0918「三治」早已学会避开的那一种**：
            #     ⛔**「一处『说起它』，被当成了一笔『签了它』」**。
            #   ★★★**故本器照那一条判序补上**：**一份回执若同时带 `COLD-<C>·本章未执` 之否决记，
            #     其六字即非签核**，⛔**不入坏。**
            #   ⛔**而其严不松**：**否决记须带其号（`COLD-C`）与「本章未执」四字**——
            #     **光写一句「没执」过不去**（免它成了一句万能的免罪符）。
            #   其负测：`工具/负测_空头签.py` 之 ⑨⑩。
            if re.search(r'COLD-%d\b[^\n]{0,12}本章未执' % C, tx):
                pass   # ⛔否决在先：此六字非签核，不入坏（0922立）
            elif C >= 新式之首:
                坏.append((C, os.path.basename(fp)))
            else:
                旧式自销 += 1
        # ★第二路·早签：同一行内，六字（N≠C）与否定语并见 → 一面说没执，一面把签核落下去
        for line in tx.split('\n'):
            if not 否定语.search(line):
                continue
            for mm in re.finditer(r'(\d+)章冷眼轮', line):
                N = int(mm.group(1))
                if N != C:
                    早签.append((C, N, os.path.basename(fp), line.strip()[:90],
                                 C >= 新式之首))
    return fps, 含签, 坏, 旧式自销, 早签


