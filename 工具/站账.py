import sys
import statistics as st
import importlib.util as _iu

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_sp = _iu.spec_from_file_location('_bd', os.path.join(ROOT, '工具', '比带.py'))
_mb = _iu.module_from_spec(_sp)
_sp.loader.exec_module(_mb)

# ── 站表（首章·名·三数所立之章数·其据）────────────────────────────
# ★凡改此表者，须同日写明所据之档与其行——**表是报，档是场**（令§五）。
站表 = [
    (201, '收E3', 30, '02_全书之约_逐站事数表.md 二·「收E3（201—230）｜30」'),
    (272, 'E4巴蜀水下', 23, '开站三数_E4巴蜀水下.md 三·「约23章约86,000字」'),
]


def _净(k):
    t = _mb._白(k)
    return _mb._净(t) if t else 0


def _末章():
    """★末章须以「正文在不在」为准，不以「版本目录在不在」为准。
    ★★其由：翻页八件套一办，下一章之版本目录（只一张开镜卡）即已在盘上；
      ★★★而那一章尚未起草——**把它算进本站，本站之章数即虚长一章**
      （293封版当日即见：E4本为22章，而以目录计得23，恰好抵着其三数）。"""
    ns = []
    for f in os.listdir(os.path.join(ROOT, '版本')):
        m = re.match(r'第(\d+)章$', f)
        if m and _净(int(m.group(1))):
            ns.append(int(m.group(1)))
    return max(ns) if ns else 0


def _对站之记(名):
    """★对站之记有二处：专档，或轮记里带「对站」二字之一节。"""
    p = os.path.join(ROOT, '设定', '站账_%s_对站.md' % 名)
    if os.path.exists(p):
        return p
    return ''


def 账():
    末 = _末章()
    rows, 判 = [], []
    for i, (首, 名, 约章, 据) in enumerate(站表):
        尾 = (站表[i + 1][0] - 1) if i + 1 < len(站表) else 末
        用 = 尾 - 首 + 1
        ws = [w for w in (_净(k) for k in range(首, 尾 + 1)) if w]
        均 = (sum(ws) / len(ws)) if ws else 0
        记 = _对站之记(名)
        rows.append((名, 首, 尾, 用, 约章, 均, 记))
        # ★判一·章数已及其三数而无对站之记
        if 用 >= 约章 and not 记:
            判.append('⛔%s：约%d章，已用%d章，而对站之记不在——'
                      '★约之令曰「每写完一站，回来对一次」（其法在 工具/站账.py）。'
                      % (名, 约章, 用))
        # ★判一之b·近其数而未及者，先出声（★2026-09-02 立闸当日所补）
        #   ★★其由：立闸之日我写了「E4已绿，因其对站之记在」——**而那是错的**：
        #     **E4当时22章而其三数23，闸根本没到点，绿的是「还没走满」，不是「已对过账」**；
        #     ★★★负测③当场逮着（抽掉E4之记而闸不复红）。
        #   ★★★★**而由此见闸差一格**：**等走满才问，已经晚了**——
        #     **一站还剩一章时才发觉四件事没写，那时改的只能是章数，不是书**；
        #     ★**故九成即出声，报而不拦**：**早一章问，还来得及改次序。**
        elif 用 >= 约章 * 0.9 and not 记:
            判.append('⚠%s：约%d章，已用%d章（%.0f%%），对站之记未立——'
                      '★报而不拦；★★而此时问还来得及改次序，走满了再问只改得动章数。'
                      % (名, 约章, 用, 100.0 * 用 / 约章))
        # ★判二·逾其三数半数以上者，另报（收E3 之形）
        #   ★★而此判之销，须其对站之记里**写着这个实用之数**——
        #     **一份不带这个数的对站，多半是照模子填的，没真去数它花了多少**；
        #   ★★★**而写明了即销，不许它天天红**：**一道天天要绕的闸，错的是闸不是人**（令§六③）。
        if 用 >= 约章 * 1.5:
            _说 = ''
            if 记:
                try:
                    _说 = io.open(记, encoding='utf-8', errors='replace').read()
                except OSError:
                    _说 = ''
            if str(用) not in _说:
                判.append('⛔%s：约%d章而用%d章（%.2f倍）——'
                          '★约第五节第3条曰「三数任一掉了，当场压章」；'
                          '★★而此处走的是反面，须在其对站之记里写明其由，'
                          '★★★且那一记里须见「%d」这个数（不见即多半是照模子填的）。'
                          % (名, 约章, 用, 用 / 约章, 用))
    return rows, 判


def 印():
    rows, 判 = 账()
    print('\n════ 站账 · 以第%d章计 ════' % _末章())
    print('  【其职】不催字数（催字数即犯令§二）；**只逼你在一站走满时回来对一次账**。')
    print('  %-12s %-11s %-6s %-7s %-9s %s' % ('站', '章界', '实用', '约之数', '均净重', '对站之记'))
    for 名, 首, 尾, 用, 约章, 均, 记 in rows:
        print('  %-12s %d—%-6d %-6d %-7d %-9.0f %s'
              % (名, 首, 尾, 用, 约章, 均, os.path.basename(记) if 记 else '⛔无'))
    # ★均净重之趋（报而不拦——它是「压章」之据，不是「添字」之据）
    seg = [(a, b) for a, b in ((169, 200), (201, 230), (231, 260), (261, 280), (281, _末章()))
           if b >= a]
    print('  ── 均净重之趋（★此数只作「压章」之据，不作「添字」之据·令§二）──')
    for a, b in seg:
        ws = [w for w in (_净(k) for k in range(a, b + 1)) if w]
        if ws:
            print('     %d—%-6d 章%-4d 均%5.0f  中位%5.0f'
                  % (a, b, len(ws), sum(ws) / len(ws), st.median(ws)))
    for x in 判:
        print('  ' + x)
    if not 判:
        print('  ✓各站俱在其三数之内，或对站之记已在。')
    print('  ★而它数不出「事摸完几件」——**那一判是人下的**；'
          '★★它只保证你走到那一步时非回头看一眼不可。')
    return 判


if __name__ == '__main__':
    _p = 账()[1] if '--闸' in sys.argv else 印()
    if '--闸' in sys.argv:
        for x in _p:
            print('  ' + x)
    raise SystemExit(1 if _p else 0)
