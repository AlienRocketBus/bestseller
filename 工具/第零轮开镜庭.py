def _占位数(t):
    """卡内占位符之数。★1027 W75 实踩（丝滑·⛔误拦）：剧情庭之单於卡首添「〔1027 据 剧情庭_势_第411段 …〕」之注，
    旧式 t.count('〔') 把这一处随裁之注当作未填之占位符而拦——随裁之注（〔…据…〕，诸册通例）⛔算；模之占位符（〔拍N〕〔写在此处〕…）照旧算。"""
    return t.count('〔') - len(re.findall(r'〔[^〔〕\n]*据[^〔〕\n]*〕', t))


