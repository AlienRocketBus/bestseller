"""约到期闸（2026-09-02·作者令「一切服务於质量」之後·九席审读所逮）

★所治之伤（非设想，逐字可验）：
  **第291章拍137—139 明写**：「两天一个样，我说不出它是停住了还是慢下来了。／
  停住和慢下来在鼻子里是一样的。／**要分出来得有第三天。**」
  ★★**而第一百零四天（第293章）正是那第三天**；
  ★★★**而293全章93拍：东头0次｜担架0次｜毡子0次｜甜0次｜馊0次｜刘二0次｜玉0次**——
  **它一步也没去看。**
  ★★★★**而十三轮＋封版之序＋五十八项全测＋看官五席，没有一处出声。**

★**何以没出声（此係本闸之判据所自）**：
  **`书级体检.py::①人物在场衰减` 印的是「东头 缺席2章（限5）✓」**——
  ★**它量的是「缺席多久」，而291立的是「到第三天就得去看」**；
  ★★**一个到期的约，缺席计数器看不见**：**它只认天数，不认承诺。**
  ★★★**而 FS闸 认承诺，可它只认已经登记成 FS 的那些**——
  **一句写在正文里、没人登记的约，两边都漏。**

★★**它认哪几样（令§六④·立闸之日须写明）**：
  ①**认正文里自陈的约**：其式为「要…得有第N天／第N回／第N次」「等到…才」「过了N天再」
    「明天／後天／第N天…就知道／就分得出／才说得清」；
  ②**认其到期之章**：以日号推之（本书一章一日，日号在章首「第N天／第N日」）；
  ③**认其到期之章有没有去看**：以立约那一拍里的实词（物名、人名）在到期章之数为准。
★★★**它认不着的（不许把它的绿读成「本章无欠约」）**：
  ①**没有数的约**（「等他回来」「往后再说」）——无到期之日，本闸不管；
  ②**跨线之约**（主线立而暗线到期）——日号不同轨，本闸只在同线内推；
  ③**已登记为 FS 者**——那是 FS闸 之职，此处不重报。

用法：
    python3 工具/约到期.py            ← 扫全书之约，报到期而未看者
    python3 工具/约到期.py --闸        ← 只出判（供全测调用）
    python3 工具/约到期.py --扫 291    ← 只看某章立了哪些约
"""
import io
import os
import re
import sys
import importlib.util as _iu

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_sp = _iu.spec_from_file_location('_bd', os.path.join(ROOT, '工具', '比带.py'))
_mb = _iu.module_from_spec(_sp)
_sp.loader.exec_module(_mb)

_HAN = {'一': 1, '二': 2, '两': 2, '三': 3, '四': 4, '五': 5,
        '六': 6, '七': 7, '八': 8, '九': 9, '十': 10}

# ★立约之式（凡加一式，须同日写明它在全书命中几处·令§六④）
_约式 = [
    (re.compile(r'要(?:分|看|说|认)(?:得)?出来?[^。]{0,6}得有第([一二三四五六七八九十两]+)[天日回次]'), '得有第N天'),
    (re.compile(r'得有第([一二三四五六七八九十两]+)[天日回次]'), '得有第N天'),
    (re.compile(r'(?:要|须|得)(?:等)?到第([一二三四五六七八九十两]+)[天日回次]'), '等到第N天'),
    (re.compile(r'第([一二三四五六七八九十两]+)[天日回次].{0,8}(?:就|才)(?:知道|分得出|说得清|看得出|认得出)'), '第N天才知道'),
]


def _日号(k):
    """★取本章之日号（本书一章一日，其号在章首）。"""
    b = _mb._白(k) or ''
    m = re.search(r'第([一二三四五六七八九十百零]+)[天日]', b[:120])
    if not m:
        return None
    s, tot, num = m.group(1), 0, 0
    for ch in s:
        if ch in _HAN and ch != '十':
            num = _HAN[ch]
        elif ch == '十':
            tot += (num or 1) * 10
            num = 0
        elif ch == '百':
            tot += (num or 1) * 100
            num = 0
        elif ch == '零':
            num = 0
    return tot + num


def _镜(k):
    b = _mb._白(k) or ''
    return '暗' if b.count('她') > b.count('我') else '主'


_书 = {}


def _常物():
    """★本书之常物：凡二字之词见於三章以上者方算「一样东西」。
    ★★其由（立闸当日所改）：初版取拍文里所有二字串，遂取出「不起／为那／事撑」这类残片，
      **而残片在任一章里都容易撞上，於是闸恒绿**；★★★故改为「须是本书反覆用的那些词」。"""
    if _书:
        return _书
    from collections import Counter
    c = Counter()
    for k in range(1, 300):
        b = _mb._白(k)
        if not b:
            continue
        for w in set(re.findall(r'[一-鿿]{2}', b)):
            c[w] += 1
    _书.update({w: n for w, n in c.items() if n >= 3})
    return _书


def _实词(拍文):
    """★取立约之场里的实词，作为「有没有去看」之凭。
    ★★只取本书反覆用的那些词（见於三章以上），且去虚。"""
    stop = {'一样', '什么', '这一', '那一', '一个', '出来', '不是', '就是', '今天',
            '昨天', '明天', '前天', '一回', '分出', '停住', '慢下', '我说', '他说',
            '得有', '第三', '第二', '两天', '三天', '一天', '没有', '起来', '下去',
            '上头', '底下', '里头', '外头', '这么', '那么', '还是', '就是', '要是'}
    常 = _常物()
    return [w for w in re.findall(r'[一-鿿]{2}', 拍文)
            if w not in stop and 常.get(w, 0) >= 5 and 常[w] <= 120]


def 扫(lo=200, hi=None):
    """★逐章找立约之句，推其到期之章，验到期章有没有去看。"""
    hi = hi or _末章()
    日 = {k: _日号(k) for k in range(lo, hi + 1)}
    出, 已 = [], set()   # ★已：按号去重——二式命中同一拍者只算一约（291.139 曾报两回）
    for k in range(lo, hi + 1):
        b = _mb._白(k)
        if not b:
            continue
        ps = _mb._拍(b)
        for i, p in enumerate(ps, 1):
            for pat, 名 in _约式:
                m = pat.search(p)
                if not m:
                    continue
                n = _HAN.get(m.group(1))
                if not n or 日.get(k) is None:
                    continue
                # ★【立闸当日所改】「第N天」之起点不定：
                #   ★★291「两天一个样……要分出来得有第三天」——**那两天已经过去了**，
                #     故其第三天是今日之次日（第104日＝293章），非今日+2；
                #   ★★★而别处之「第N天」可能自今日起数。**其起点，文里不总说得清。**
                #   ★★★★故不判一个点，判一个窗：**自今日之次日至今日+N**；
                #     **窗内任一章去看过，即算兑；一章也没去看，方判欠。**
                窗 = [日[k] + j for j in range(1, max(2, n) + 1)]
                同线 = [x for x in range(k + 1, hi + 1)
                        if _镜(x) == _镜(k) and 日.get(x) in 窗]
                if not 同线:
                    continue
                到 = 同线[0]
                到期日 = 日.get(到)
                # ★【立闸当日三改·而这一改是弃一条路，不是补它】
                #   ★★初版要器自己判「到期那一章有没有去看」，其法是取立约之场里的实词
                #     再看它在到期章出现几个；★★★而中文不分词，二字切片切出来的是
                #     「了闻／天一／我蹲」这种碎片，**碎片在任一章都容易撞上，於是闸恒绿**；
                #   ★★★★我改了两回（窗三拍→十拍、常物≥3章→≥5章），碎片照旧。
                #     **再调下去就是「把尺调到它不再抱怨为止」**——审器那一路正是这么点我的
                #     （`手` 正则「靠调到它不再抱怨为止而定标」）。**故弃此路。**
                #   ★**改走 FS闸 那条已验之路**：**器只管找出约与其到期之窗；
                #     到期之章须在其轮记或回执里写一行「约-NNN·<兑或未兑>」**——
                #     ★★**放行之价是一行写下来的字，不是器的一次猜测。**
                # ★【立闸当日再改】窗自三拍放宽到十拍：
                #   ★★291之约在拍139，而其主（东头／担架／毡子／刘二／甜／馊）在拍130—136；
                #   ★★★三拍之窗只够着「两天一个样／在鼻子里是一样的」——**取不着它说的是谁**。
                场 = ''.join(ps[max(0, i - 10):i])
                词 = _实词(场)
                号 = '约-%d.%d' % (k, i)
                if 号 in 已:
                    continue
                已.add(号)
                认 = ''
                for x in 同线:
                    for f in (os.path.join(ROOT, '版本', '第%d章' % x, '_轮记.md'),
                              os.path.join(ROOT, '版本', '第%d章' % x, '_开镜卡.md')):
                        if os.path.exists(f):
                            try:
                                认 += io.open(f, encoding='utf-8', errors='replace').read()
                            except OSError:
                                pass
                for f in os.listdir(os.path.join(ROOT, '设定')):
                    if f.startswith('回执_') and any(('第%d章' % x) in f for x in 同线):
                        认 += io.open(os.path.join(ROOT, '设定', f),
                                      encoding='utf-8', errors='replace').read()
                出.append({'立': k, '拍': i, '式': 名, '文': p[:56], '号': 号,
                           '到期': 到, '到期日': 到期日, '窗': 同线,
                           '场': 场[-90:],
                           '欠': 号 not in 认})
    return 出


def _末章():
    ns = []
    for f in os.listdir(os.path.join(ROOT, '版本')):
        m = re.match(r'第(\d+)章$', f)
        if m and (_mb._白(int(m.group(1))) or ''):
            ns.append(int(m.group(1)))
    return max(ns) if ns else 0


def 印(只闸=False):
    xs = 扫()
    欠 = [x for x in xs if x['欠']]
    if not 只闸:
        print('\n════ 约到期 · 全书 ════')
        print('  【其职】**一句写在正文里的约，到期那一章有没有去看。**')
        print('  ★而缺席计数器看不见它：它只认天数，不认承诺（书级体检①印「东头缺席2章（限5）✓」，'
              '而291立的约正是「要分出来得有第三天」）。')
        print('  ── 全书立约 %d 处 ──' % len(xs))
        for x in xs:
            print('   %s%s｜第%d章拍%-3d「%s」' % ('⛔' if x['欠'] else '✓', x['号'],
                                                x['立'], x['拍'], x['文']))
            print('       其场：…%s' % x['场'][-64:].replace('\n', ' '))
            print('       到期之窗：第%s章（第%s日）' % ('、'.join(str(y) for y in x['窗']),
                                                 x['到期日']))
    for x in 欠:
        print('  ⛔欠约 %s：第%d章拍%d立「%s」，到期在第%s章；'
              '而到期之章的轮记、开镜卡、回执里，一处也没有「%s」这几个字。'
              % (x['号'], x['立'], x['拍'], x['文'],
                 '、'.join(str(y) for y in x['窗']), x['号']))
        print('     ★其治不是补写一段回忆，是**在到期那一章里让它在手上再出现一回**；'
              '★★而若判「本章不兑」，须在其轮记里写明「%s·本章未兑：<其由>」。' % x['号'])
    if not 只闸 and not 欠:
        print('  ✓无到期而未看之约。')
    return 欠


if __name__ == '__main__':
    if '--扫' in sys.argv:
        n = int(sys.argv[sys.argv.index('--扫') + 1])
        for x in 扫(n, n):
            print(x)
        raise SystemExit(0)
    raise SystemExit(1 if 印('--闸' in sys.argv) else 0)
