import io, json, os, re, sys

根 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
总纲 = os.path.join(根, '设定', '02_余章之势_总纲.md')
账档 = os.path.join(根, '设定', '到期账.json')
行式 = re.compile(r'^\|\s*(\d+)\s*\|\s*(主|暗)\s*·\s*(\d+)\s*\|')


def 诸线(文=None):
    """返回 {章号: (线, 日)}。★其据只一处：总纲逐行自书之「主·N／暗·N」。"""
    出 = {}
    src = 文 if 文 is not None else io.open(总纲, encoding='utf-8').read()
    for L in src.split('\n'):
        m = 行式.match(L.strip())
        if m:
            出[int(m.group(1))] = (m.group(2), int(m.group(3)))
    return 出


def 下一个到得了的章(n, 线, 盘):
    """★自 n 起（含 n）头一个与其线相合之章；无则 None。"""
    for k in sorted(x for x in 盘 if x >= n):
        if 盘[k][0] == 线:
            return k
    return None


def 量(账=None, 盘=None):
    """返回 (红, 认得之数, 越盘者)。红 = [(id, 限, 其线, 限之线, 建议章), ...]。"""
    盘 = 盘 if 盘 is not None else 诸线()
    d = 账 if 账 is not None else json.load(io.open(账档, encoding='utf-8'))
    红, 认, 越盘 = [], 0, []
    for x in d.get('items', []):
        if x.get('状态') != 'open':
            continue
        n, 线 = x.get('到期章'), x.get('线')
        if not isinstance(n, int) or 线 not in ('主', '暗'):
            continue          # ⛔不书「线」者不认
        认 += 1
        if n not in 盘:
            越盘.append((x.get('id'), n))
            continue
        if 盘[n][0] != 线:
            红.append((x.get('id'), n, 线, 盘[n][0], 下一个到得了的章(n, 线, 盘)))
    return 红, 认, 越盘


def 跑(报=True):
    红, 认, 越盘 = 量()
    if 报:
        盘 = 诸线()
        print('════ 线限哨 ════（一笔账之限，落在它那条线到不了的章上）')
        print('  自书「线」而在册者 %d 笔｜总纲覆盖 %d—%d 章'
              % (认, min(盘), max(盘)) if 盘 else '  总纲无一行')
        for i, n, 线, 实, 荐 in 红:
            print('  ⛔ %s：限 %d ＝ %s线，而本笔係 %s线——那一章碰它即破线。'
                  % (i, n, 实, 线))
            print('       ★其後头一个到得了的章：%s'
                  % ('第%d章' % 荐 if 荐 else '总纲之内无'))
        for i, n in 越盘:
            print('  ⚠ %s：限 %d 不在总纲之内（只记不拦）' % (i, n))
        if not 红:
            print('  ✓ 凡自书其线者，其限皆落在它到得了的章上。')
        print('  ── ⛔本器只报不拦：改一笔账之限是一庭的事 ──')
    return 红


def 自测():
    R = []
    盘 = 诸线()
    R.append(('①总纲读得出主暗（≥100 章）', len(盘) >= 100))
    R.append(('②主暗两样皆在', len({v[0] for v in 盘.values()}) == 2))
    # ③⛔【本坐 0917 换过一回，其由须留】原作「相邻两章异线」——**当场被盘驳倒**
    #   （相邻同线者四处：314→321、327→333、433→461、485→511）。
    #   ★★**而那一条本就不该由本器来验**：**它验的是书之形，不是本器之约**；
    #   **本器一处也不靠「相间」，它只逐章去盘上查线。**
    #   ★故今改验其真约：`下一个到得了的章` 在真盘上须找得着、须同线、须不小於所求。
    _主 = [k for k in sorted(盘) if 盘[k][0] == '主'][:3]
    _三 = all(下一个到得了的章(k, '主', 盘) == k for k in _主)      # 自身即合者返其自身
    _起 = min(盘)
    _次 = 下一个到得了的章(_起 + 1, 盘[_起][0], 盘)
    R.append(('③下一个到得了的章：同线、不小於所求、真盘上找得着',
              _三 and _次 is not None and _次 > _起 and 盘[_次][0] == 盘[_起][0]))
    # ④⑤⑥假账：有线而错、有线而对、不书线者不认
    假盘 = {10: ('主', 1), 11: ('暗', 2), 12: ('主', 3)}
    假账 = {'items': [
        {'id': 'A-错', '状态': 'open', '到期章': 11, '线': '主'},
        {'id': 'B-对', '状态': 'open', '到期章': 10, '线': '主'},
        {'id': 'C-无线', '状态': 'open', '到期章': 11},
        {'id': 'D-已清', '状态': '清', '到期章': 11, '线': '主'},
        {'id': 'E-越盘', '状态': 'open', '到期章': 99, '线': '主'},
    ]}
    红, 认, 越 = 量(假账, 假盘)
    R.append(('④限落在异线之章，逮得出（且只逮那一笔）',
              len(红) == 1 and 红[0][0] == 'A-错'))
    R.append(('⑤并印出其後头一个到得了的章（11→12）', 红 and 红[0][4] == 12))
    R.append(('⑥不书「线」者不认／已清者不认（其认之数 ＝ 3）', 认 == 3))
    R.append(('⑦越盘者只记不拦', 越 == [('E-越盘', 99)]))
    # ⑧⛔本器之判据里不许写死任何章号（㊸）
    码 = io.open(os.path.abspath(__file__), encoding='utf-8').read()
    身 = 码.split('def 自测', 1)[0].split('"""', 3)[-1]
    R.append(('⑧⛔器身之判据无一个写死之章号（㊸）',
              not re.search(r'[=<>]=?\s*3[0-9]{2}\b', 身)))
    for 名, o in R:
        print(('  ✓ ' if o else '  ⛔ ') + 名)
    print('  自测 %d/%d' % (sum(1 for _, o in R if o), len(R)))
    return all(o for _, o in R)


if __name__ == '__main__':
    if '--自测' in sys.argv:
        sys.exit(0 if 自测() else 1)
