def _读():
    try:
        return json.load(open(档, encoding='utf-8'))
    except Exception:
        return {'说明': '任务流断点账·见 工具/续跑.py 头注', '步': []}


def _写(d):
    t = 档 + '.tmp%d' % os.getpid()
    with open(t, 'w', encoding='utf-8') as f:
        json.dump(d, f, ensure_ascii=False, indent=1)
    os.replace(t, 档)


def 记(事, 章=None, 凭=''):
    if not 事:
        return 2, '一步没有名字，不许记'
    if not 凭:
        return 2, '**没有凭的一步等於没跑**——须带一个可验之凭（sha／档名／数）'
    d = _读()
    d['步'].append({'时': time.strftime('%Y-%m-%d %H:%M:%S', time.gmtime()),
                    '事': 事, '章': 章, '凭': 凭})
    d['当前'] = d['步'][-1]
    _写(d)
    return 0, '第 %d 步已记：%s' % (len(d['步']), 事)


def _下一步(一):
    """★由末一步当场推出下一步。**推不出来就说推不出来**，不许编。"""
    事 = (一 or {}).get('事', '')
    for i, 名 in enumerate(段序):
        候 = [名] + 别名.get(名, [])
        if any(x in 事 for x in 候):
            if i + 1 < len(段序):
                return '下一段：**%s**（十一段之第 %d）' % (段序[i + 1], i + 2)
            return '**封版已是末一段**——办毕即开下一章（`python3 工具/自走.py`）'
    return '（末一步不在十一段之列，下一步须由人当场定）'


def 印(全=False):
    d = _读()
    步 = d.get('步', [])
    print('════ 续跑 ════（共 %d 步）' % len(步))
    if not 步:
        print('  账上一步也没有——**这一坐是从头起的**。')
        return
    for 一 in (步 if 全 else 步[-5:]):
        print('  · %s ｜%s%s｜凭：%s' % (一.get('时', '?'), 一.get('事', '?'),
                                       ('｜第%s章' % 一['章']) if 一.get('章') else '', 一.get('凭', '')))
    末 = 步[-1]
    # ★存底之步是流水（一天几十笔），实事之步才是「跑到哪儿了」——两样须分开印，
    #   否则一串存底会把实事埋掉（0910 当日即见此形，故补）。
    实 = None
    for 一 in reversed(步):
        if not str(一.get('事', '')).startswith('存底·'):
            实 = 一
            break
    print('  ── 跑到哪儿了 ──')
    if 实:
        print('   **实事**：%s%s（%s）'
              % (实.get('事', '?'), ('｜第%s章' % 实['章']) if 实.get('章') else '', 实.get('时', '?')))
        print('   %s' % _下一步(实))
    else:
        print('   账上只有存底之流水，还没有一笔实事。')
    if 实 is not 末:
        print('   （末一笔係存底流水：%s｜%s）' % (末.get('事', '?'), 末.get('时', '?')))
    print('  ★**本档随 `工具/存底.py --存` 一并推上存底枝**——沙盒挂了，下一坐把它读出来即知接哪儿。')


