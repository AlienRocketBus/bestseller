def _num(s):
    tot, cur = 0, 0
    for ch in s:
        if ch in CN:
            cur = CN[ch]
        elif ch == '十':
            tot += (cur or 1) * 10
            cur = 0
        elif ch == '百':
            tot += (cur or 1) * 100
            cur = 0
        elif ch == '千':
            tot += (cur or 1) * 1000
            cur = 0
    return tot + cur


