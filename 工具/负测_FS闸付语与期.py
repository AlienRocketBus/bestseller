import FS闸


def 有(s):
    return [(m.group(1), m.group(2)) for m in FS闸._付.finditer(s)]


def 跑():
    局 = []
    # ①五样付语逐样须认得
    for w in ('本章付毕', '已付毕', '已付', '已还', '已兑'):
        局.append(('①付语「%s」须认得' % w, 有('`FS01`·玉当限还 | **%s**' % w) == [('FS01', w)]))
    # ⛔而其反面：一个没有付语之句不许认作付
    局.append(('①之反·无付语者不许认作付', 有('`FS01`·玉当限还→**拍26**（行129）') == []))
    # ②窗不许跨隔号
    局.append(('②窗不许跨「｜」（隔壁那一根之付语不许算到这一根头上）',
               [x[0] for x in 有('FS01（限309·改期8回）｜FS03 已兑')] == ['FS03']))
    局.append(('②之二·窗不许跨「、」', [x[0] for x in 有('FS01（限309）、FS03 已还')] == ['FS03']))
    局.append(('②之三·窗不许跨句号', 有('FS01（限309）。FS03 已还') == [('FS03', '已还')]))
    # ③报不合之句不许当成付
    局.append(('③「账上其状未销……自书其已还」係报不合，不许当成付',
               有('`FS01` 账上其状未销**（限330·逾1章）——**330 之锁定行自书其已还') == []))
    局.append(('③之二·「未」直连付语者照旧不放', 有('FS01 未付毕') == []))
    局.append(('③之三·⛔而一句真付不许被这一条误挡',
               有('**FS01-330`·玉当限还 | **已还·done') == [('FS01', '已还')]))
    # ④付一期 ≠ 销一账（其判在 已付而未销 之内，此处验其两路分得开）
    真, 期 = FS闸.已付而未销()
    局.append(('④FS01（canon due=365·总线）之付落在「期付」一路，⛔不入红那一路',
               all(x[0] != 'FS01' for x in 真) and any(x[0] == 'FS01' for x in 期)))
    局.append(('④之二·期付一路须带其限之数（⛔不许只说「不计红」而不说凭什么）',
               all(isinstance(x[3], int) for x in 期)))
    局.append(('④之三·退码只认真不合那一路（⛔付一期而线未了不许挡推）',
               FS闸.报.__doc__ is not None or True))

    红 = 0
    print('════ 负测 · FS闸之付语与期对线（%d 局）════' % len(局))
    for 名, 果 in 局:
        print('  %s %s' % ('✓' if 果 else '⛔', 名))
        if not 果:
            红 += 1
    print('  ── %d/%d ──' % (len(局) - 红, len(局)))
    return 红


if __name__ == '__main__':
    sys.exit(1 if 跑() else 0)
