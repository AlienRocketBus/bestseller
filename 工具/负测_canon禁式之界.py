"""负测 · canon forbid 之量界（2026-09-18 立·同日随改随测）

★立此测之由（`小说检察官.py` 第一优先级·canon保真·0918 之改）：
　旧式把 forbid 正则跑在**整个正文档**上，而一个章之档有两层——
　**白文**（读者读的那一层）与 **【本章亮点】之後的骨记**（本席自己的工作记录）。
⛔**346 行168 之实**：骨记那一节正在**自证它守住了 F034**，
　其文引圣经 2468「只有公输后人认得」，隔一句又引 692「不给钱满…」，
　**而 F034 第三式 `(公输|鲁班)…(后人)…钱满` 的字符窗把两段引文缝在了一处。**
★★**即：一个章因为写下「本章没有犯这一条」而被判犯了这一条。**

⛔**而本测之要，是压住这一改不许走过头**：
　**改的是量在哪一层，不是量得松不松**——
　**白文里真犯一条，照旧红；骨记里引了禁式，照旧印，只是不计 ERROR。**

四局（⛔每一局皆验其反面）：
　①白文真犯 → 须红（⛔若不红，即这一改把闸放倒了）
　②只骨记命中 → ⛔不许红，而须印一格 ℹ（⛔若连印都不印，即是静悄悄放过）
　③白文与骨记各命中一处 → 红一处、印一格（⛔不许把两处并作一处，亦不许拿骨记那一处充数）
　④档内无 `【本章亮点】` 者（如草稿）→ 全档皆作白文（⛔不许因无分界而整档放过）
"""
import io, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_禁 = r'(公输|鲁班)[^。\n]{0,12}(血脉|后人|传人)[^。\n]{0,10}钱满'


def 量(档, 式=_禁):
    """照 `小说检察官.py` 0918 之後之式：forbid 只跑白文；骨记之命中只印不计。
    返回 (红之数, 印之数)。"""
    白 = 档.split('【本章亮点】')[0]
    亮 = 档[len(白):]
    return (len(re.findall(式, 白)), len(re.findall(式, 亮)))


def 跑():
    局 = []
    _犯 = '公输后人认得这个记号，钱满今天一眼就认了出来。'
    _净 = '他把那一张推出去半寸。他的手还在裤上，没有抬。\n'

    局.append(('①白文真犯 → 须红', 量(_净 + _犯 + '\n【本章亮点】\n骨记若干。') == (1, 0)))
    局.append(('②只骨记命中 → 不红而须印一格',
               量(_净 + '\n【本章亮点】\n本席自证：' + _犯) == (0, 1)))
    局.append(('③两层各一处 → 红一、印一（⛔不许并作一处）',
               量(_净 + _犯 + '\n【本章亮点】\n本席自证：' + _犯) == (1, 1)))
    局.append(('④无亮点分界之档 → 全档皆作白文（⛔不许整档放过）',
               量(_净 + _犯) == (1, 0)))

    红 = 0
    print('════ 负测 · canon禁式之量界（四局）════')
    for 名, 果 in 局:
        print('  %s %s' % ('✓' if 果 else '⛔', 名))
        if not 果:
            红 += 1
    print('  ── %d/%d ──' % (len(局) - 红, len(局)))
    return 红


if __name__ == '__main__':
    sys.exit(1 if 跑() else 0)
