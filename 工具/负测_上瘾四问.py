def _判(m, 卡们, c=364):
    d = tempfile.mkdtemp(prefix='上瘾_')
    for n, 文 in 卡们.items():
        os.makedirs(os.path.join(d, '版本', '第%d章' % n))
        io.open(os.path.join(d, '版本', '第%d章' % n, '_开镜卡.md'), 'w', encoding='utf-8').write(文)
    老R, 老前, 老末 = m.ROOT, m._同线之前, m._末拍
    m.ROOT = d
    m._同线之前 = lambda n: 362 if n == 364 else None
    m._末拍 = lambda n: '“还有的你没数着。”' if n == 362 else ''
    try:
        return m._check8(c)[0]
    finally:
        m.ROOT, m._同线之前, m._末拍 = 老R, 老前, 老末
        shutil.rmtree(d, ignore_errors=True)


