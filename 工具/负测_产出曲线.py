def _判(ws, 旧式=False):
    """把 跑轮.py 乙·产出那一段之判逐字搬来（只搬判，不搬印），返 ('红'|'黄'|'绿', 语)。
    ★**判据须与器同源**：本函之码若与器上那一段走岔，本测即成陪跑——
    　故 ⑦ 一格当场把器上那几行抓出来比对。"""
    w0, wmax, wend = ws[0], max(ws), ws[-1]
    gain = wend - w0
    grew = wmax - w0
    wmin = min(ws)
    i谷 = ws.index(wmin)
    rise = (wend - wmin) if i谷 < len(ws) - 1 else 0
    if 旧式:
        return ('红', '自起版至峰值一字未长') if grew <= 0 else ('绿', '')
    if grew <= 0 and rise <= 0:
        return '红', '两把尺俱不过'
    if grew <= 0:
        return '绿', '自起版未长而自谷至终长 %+d' % rise
    if gain < 0 and abs(gain) > grew:
        return '黄', '减得比长得多'
    if gain < w0 * 0.10:
        return '黄', '净增少'
    return '绿', ''


