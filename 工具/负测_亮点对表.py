# -*- coding: utf-8 -*-
"""负测·亮点对表 · 2026-09-01 立（与 工具/亮点对表.py 同日·令§六③）
　★要害不在「会不会报红」，在三样：
　　①**以旧式回灌**：拿 289 v20（第9轮改前之原物）灌回去，须逮出「二十来口气」；
　　②**非陪跑**：若把③路之约数式去掉，回灌当场漏掉那一处；
　　③**非挖空**：现文（v21，已改）须放行，而全书之红率须仍在 1% 上下——
　　　一道红 20% 的路不作闸（引文路与数路已降为「报而不拦」，其数写在器里）。
"""
import io, os, re, sys, glob

根 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(根, '工具'))
import 亮点对表 as A                                    # noqa: E402

过 = []
def t(名, 实, 期):
    过.append((名, 实 == 期, 实, 期))

全 = A.诸章()
V20 = os.path.join(根, '版本', '第289章', 'v20.md')
v20 = io.open(V20, encoding='utf-8').read() if os.path.exists(V20) else ''
now = io.open(全[289], encoding='utf-8').read()

# ①回灌：v20 之「二十来口气」须逮得住
约, 引, 数 = A.三路(v20)
t('①回灌v20·约数路逮出「二十来口气」', '二十来口气' in 约, True)

# ②非陪跑：去掉③路之「来多余几」，同一份 v20 当场漏掉
旧 = [m.group(0) for m in
      re.finditer(r'([一二三四五六七八九十百零两]+)' + A.量词, v20.split('【本章亮点】')[1])
      if m.group(0) not in A.剥(v20.split('【本章亮点】')[0])]
t('②旧式（无「来多余几」）漏掉「二十来口气」', '二十来口气' not in 旧, True)

# ③非挖空：现文放行
约2, _, _ = A.三路(now)
t('③现文v21·约数路放行', 约2, [])

# ④全书红率须在低位（一道红二成的路不作闸）
红 = [n for n in 全 if A.三路(io.open(全[n], encoding='utf-8').read())[0]]
t('④全书约数红 ≤ 全书之5%', len(红) <= len(全) * 0.05, True)
过.append(('④之数（记录·非判）：约数红 %d／%d 章' % (len(红), len(全)), True, 0, 0))

# ⑤⑥ 二路已降为报，其数须仍高——即「它们确实不配作闸」，此判有据
def 率(路):
    c = 0
    for n in 全:
        txt = io.open(全[n], encoding='utf-8').read()
        if 路(A.三路(txt, n, None)):
            c += 1
    return c
t('⑤引文路红率仍逾一成（故只报不拦之判有据）', 率(lambda r: r[1]) > len(全) * 0.10, True)
t('⑥数路红率仍逾一成（同上）', 率(lambda r: r[2]) > len(全) * 0.10, True)

# ⑦ 造一假章：把现文亮点段之一个准数抹成约数，须逮得住
_b, _h = now.split('【本章亮点】', 1)      # ★只动亮点段那一半——
假 = _b + '【本章亮点】' + _h.replace('二十三口气', '二十来口气')  #   正文之准数须留着，否则不成其为「相犯」
t('⑦假章（把准数抹成约数）逮得住', '二十来口气' in A.三路(假)[0], True)

# ⑧ 无亮点段者不报红
t('⑧无亮点段之文零红', A.三路('正文一二三。')[0], [])

# ⑨ 「层」不入量词（其为骨之层，工序之词）
t('⑨「层」不在量词之列', '层' not in A.量词, True)

# ⑩ 剥须剥标点（289第13轮·第二组数所逮：引文路十章之红只差一个逗）
t('⑩剥剥标点（逗、句、顿、斜杠）',
  A.剥('那一堆里头，凭什么有闲的。') == A.剥('那一堆里头凭什么有闲的'), True)
t('⑪剥不剥字（不许把汉字也剥掉）', A.剥('二十三口气') == '二十三口气', True)

# ⑫—⑮ 骨层数之闸（2026-09-02立·290第6轮所逮）
t('⑫骨层数·数与目相符者放行', A.骨层数(now)[0] == A.骨层数(now)[1], True)
_b, _h = now.split('【本章亮点】', 1)
假骨 = _b + '【本章亮点】' + _h.replace('其骨六层', '其骨八层', 1)
_N, _M = A.骨层数(假骨)
t('⑬假章（自书八层而只列六条）逮得住', _N != _M, True)
t('⑭无「其骨N层」者不报', A.骨层数('【本章亮点】无骨之段。'), (None, None))
t('⑮附层（①之二一类）计入其目',
  A.骨层数('x【本章亮点】其骨三层\n①甲\n①之二乙\n②丙\n')[1], 3)

print('════ 负测·亮点对表 ════')
for 名, ok, 实, 期 in 过:
    print('  %s %s' % ('✓' if ok else '✗', 名), '' if ok else '（实 %r 期 %r）' % (实, 期))
n = sum(1 for _, ok, _, _ in 过 if ok)
print('  %d/%d %s' % (n, len(过), '全通' if n == len(过) else '⛔有败'))
sys.exit(0 if n == len(过) else 1)
