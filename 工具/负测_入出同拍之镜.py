def _判(出文, 入=2, 用=2):
    """照 `器物点名.py` 0918 之後之式，判一行之「入出」该不该红。⛔此处只重其判，不重其抄册。"""
    出拍 = int(re.search(r'拍?(\d+)', 出文).group(1))
    开口 = '开口' in 出文
    有去处 = bool(re.search(r'去处[:：]\s*[\u4e00-\u9fa5A-Za-z0-9]', 出文))
    序 = [入, 用, 出拍]
    if 序[0] == 序[2] and not 开口 and not 有去处:
        return '红·入出同拍'
    if 序[0] == 序[2]:
        return '绿·' + ('开口' if 开口 else '有去处')
    if not (序[0] <= 序[1] <= 序[2]):
        return '红·序倒'
    return '绿'


