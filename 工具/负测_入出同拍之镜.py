        ('②写「开口」者照旧不红（旧路一格未动）', _判('拍2(开口)').startswith('绿')),
        ('③写「去处:碗旁边」者不红（新路）', _判('拍2(去处:碗旁边，勺把朝外)').startswith('绿')),
