# -*- coding: utf-8 -*-
"""负测·器物点名（2026-09-03 立·与其闸同日）

★令§六③：改闸／立闸必同日立负测，且须以旧式回灌验；★★一个只会说「零」的闸没有价值。
★★★故本测逐条回灌，每一条都拿「真犯过此项之原物」去撞它（令§十四③）：
  ①今日之册须绿（其基线）
  ②删一格「出」即红——**这正是295第6轮逮出的那一伤**（笔与那一点东西原皆无「出」）
  ③把「用」之拍号改成一个没有该器物之名的拍即红——**295第7轮之坐头一版册即栽在此**
    （本子·用=拍8，而拍8之白文是「递到一半，他伸手接了」，无「本子」二字）
  ④拍号逾全章拍数即红
  ⑤册不在即红
  ⑥旧式回灌：**若判据只数「册上有没有这一行」而不验其拍**，②③④三条俱过——
    **一份在旧式下也全过的测就是陪跑**（令§六③）。
  ⑧**三格之拍号倒了即红**（2026-09-04·299第6轮新立之验）——**把「入」与「出」对调即红**；
    ★★而旧式（只验「那一格有没有拍号」「那一拍有没有其名」）在此条之下**照绿**：
      对调之後三格俱在、三拍俱有其名——**故此条非陪跑。**
  ⑨**「入」与「出」同指一拍即红**——**一件东西在同一拍上又进来又出去，那不是来去，是没动。**
  ⑩**身上的尺之疑（开集⚠）须印得出来**：把册里提「指头」那一处「」抹掉，⚠即现；**它只提醒，不判**（rc 不变）。
"""
import importlib.util as iu, io, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = os.path.join(ROOT, '版本', '第295章', '_器物.md')


def _mod():
    sp = iu.spec_from_file_location('_qw', os.path.join(ROOT, '工具', '器物点名.py'))
    m = iu.module_from_spec(sp)
    sp.loader.exec_module(m)
    return m


def _跑(m, 文):
    io.open(P, 'w', encoding='utf-8').write(文)
    import contextlib
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        rc = m.跑(295)
    return rc, buf.getvalue()


def 跑():
    if not os.path.exists(P):
        print('✗ 负测·器物点名 ⛔前置不在：%s' % P)
        return 1
    原 = io.open(P, encoding='utf-8').read()
    m = _mod()
    坏 = []
    try:
        rc, _ = _跑(m, 原)
        if rc != 0:
            坏.append('★①今日之册本该绿，而它红了（rc=%d）' % rc)
        # ②删一格「出」
        rc, o = _跑(m, re.sub(r'｜出=\d+', '', 原, count=1))
        if rc == 0 or '缺「出」' not in o:
            坏.append('★②删一格「出」而它没红——正是295第6轮那一伤（笔与那一点东西原皆无出）')
        # ③拍号指到无其名之拍
        # ★★★★★2026-09-03 改：此二处原写死「用=92」，而册上那个数随正文而动
        #   （第7轮补一拍，92 即成 93），於是③④当场失灵——**第二十八犯之第十一回**：
        #   **把一个会变的数抄进测里，抄完那一刻就开始陈。**
        #   ★故今改为逐行解出「本子」那一行现有之「用」，再拿它去造变体。
        m用 = re.search(r'^本子.*?用=(\d+)', 原, re.M)
        if not m用:
            坏.append('★前置·册上取不着「本子」那一行之「用」')
            m用 = None
        用旧 = m用.group(1) if m用 else '0'
        rc, o = _跑(m, 原.replace('用=' + 用旧, '用=8', 1))
        if rc == 0 or '无其名' not in o:
            坏.append('★③「用=拍8」而拍8之白文无「本子」二字，它没红——拍号是抄的它也认')
        # ④拍号逾全章
        rc, o = _跑(m, 原.replace('用=' + 用旧, '用=9999', 1))
        if rc == 0 or '不在' not in o:
            坏.append('★④拍号 9999 逾全章而它没红')
        # ⑤册不在
        os.remove(P)
        rc, o = _跑2 = (None, None)
        import contextlib
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            rc = m.跑(295)
        if rc == 0 or '器物册不在' not in buf.getvalue():
            坏.append('★⑤册不在而它没红')
        # ⑥旧式回灌（只数行数，不验拍）
        rows = [l for l in 原.split('\n') if '｜' in l and not l.startswith('#')]
        旧式过 = 0
        for 变 in (re.sub(r'｜出=\d+', '', 原, count=1),
                   原.replace('用=' + 用旧, '用=8', 1),
                   原.replace('用=' + 用旧, '用=9999', 1)):
            n = len([l for l in 变.split('\n') if '｜' in l and not l.startswith('#')])
            if n == len(rows):
                旧式过 += 1
        if 旧式过 != 3:
            坏.append('★⑥旧式回灌本该三条全过（故新式非陪跑），而它过了 %d 条' % 旧式过)
        # ⑧三格之拍号倒了（把本子那一行之入与出对调）
        m行 = re.search(r'^(本子｜入=(\d+)｜用=(\d+)｜出=(\d+))\s*$', 原, re.M)
        if not m行:
            坏.append('★前置·册上取不着「本子」那一整行')
        else:
            全, 入, 用, 出 = m行.group(1), m行.group(2), m行.group(3), m行.group(4)
            倒 = '本子｜入=%s｜用=%s｜出=%s' % (出, 用, 入)
            rc, o = _跑(m, 原.replace(全, 倒, 1))
            if rc == 0 or '倒了' not in o:
                坏.append('★⑧把「入」与「出」对调（入=%s｜出=%s）而它没红——'
                          '「来去」是有方向的，一件东西不能先出后入' % (出, 入))
            # ★而旧式（不验序）在此条之下照绿：三格俱在、三拍俱有其名
            if '无其名' in o or '缺「' in o or '不在' in o:
                坏.append('★⑧之旧式回灌不成立：对调之後旧式那三验已经红了，'
                          '故此条逮的不是「序」——须另择一行造变体')
            # ⑨入与出同指一拍
            同 = '本子｜入=%s｜用=%s｜出=%s' % (入, 用, 入)
            rc, o = _跑(m, 原.replace(全, 同, 1))
            if rc == 0 or '同拍' not in o:
                坏.append('★⑨「入」与「出」同指拍%s而它没红——那不是来去，是没动' % 入)
        # ⑩身上的尺之疑（开集⚠·只提醒不判）
        rc, o = _跑(m, 原)
        有疑 = '身上的尺之疑' in o
        rc2, o2 = _跑(m, 原.replace('「指头」', '指头'))
        if not (有疑 or ('身上的尺之疑' in o2)):
            坏.append('★⑩295拍127「我拿指头比」是一把身上的尺，而开集之疑一条也没印')
        if rc2 != 0:
            坏.append('★⑩身上的尺之疑本该只提醒不判，而它把册判红了（rc=%d）' % rc2)
        # ⑪【301第9轮立】其名逐拍并列之行，须真印得出来，且须真是数出来的
        #   ★其由：本日删一拍之後，本子之「出」旧号未改而器仍印✓（那一拍上也有其名）——
        #     ★★故本行是留给人重数的料，它若不印，那一格的错就一处也看不见。
        rc, o = _跑(m, 原)
        if '在本章共' not in o:
            坏.append('★⑪「其名在本章共N拍」之行一条也没印——'
                      '一格抄旧而未重数者，即无从肉眼比对')
        else:
            import re as _re
            for 名, n, 号 in _re.findall(r'★「(.+?)」在本章共 (\d+) 拍：([\d,]+)', o):
                if len(号.split(',')) != int(n) and int(n) <= 24:
                    坏.append('★⑪「%s」报共%s拍而只摆出%d个号——其数与其料不合'
                              % (名, n, len(号.split(','))))
        # ⑫【301第10轮立】册之注·带引文之拍号，须真验得出来
        #   ★其由：本册数据行逐格重数过，而只有人读得懂的那一半（带引文之注）没有——
        #     ★★301之册七处旧号、300之册一处旧号，逐处皆是这一半上的。
        #   ★★★造变体之法：取本册某一处真注，把它的拍号加一，器须红；
        #     ★★★★而旧式（只验数据行三格）在同一份变体之下必绿——故此测非陪跑。
        #   ★其料取自295正文自己：取其第20拍头十字，造一条真注（拍号对）与一条歪注（拍号加一）。
        拍 = m.分拍(m.正文(295) or '')
        if len(拍) < 25:
            坏.append('★⑫取不着295之正文，此测无料')
        else:
            句 = 拍[19].strip().replace('\n', '')[:10]
            真 = 原 + '\n★ 测·注｜拍20（%s）\n' % 句
            歪 = 原 + '\n★ 测·注｜拍21（%s）\n' % 句
            rc, o = _跑(m, 真)
            if rc != 0 or '册之注' in o:
                坏.append('★⑫一条拍号对的注，器把它判红了——那是把对的也一并杀了')
            rc, o = _跑(m, 歪)
            if '册之注' not in o:
                坏.append('★⑫把一条注之拍号加一而器不报——'
                          '册的另一半（只有人读得懂的那一半）一格也没验着')
            elif rc == 0:
                坏.append('★⑫册之注对不上而它没把册判红（rc=0）')
    finally:
        io.open(P, 'w', encoding='utf-8').write(原)
    # ★还原毕须与测前逐字相同（第二十八犯之处方）
    if io.open(P, encoding='utf-8').read() != 原:
        坏.append('★⑦还原毕之册与测前不同——本测改坏了它所读的盘')
    if 坏:
        print('✗ 负测·器物点名 %d/12 ⛔未过' % (12 - len(坏)))
        for x in 坏:
            print('   ⛔ ' + x)
        return 1
    print('✓ 负测·器物点名 12/12 全通（②③④三条在旧式「只数行数」之下俱过；'
          '⑧在旧式「不验序」之下亦过——故本测非陪跑）')
    return 0


if __name__ == '__main__':
    sys.exit(跑())
