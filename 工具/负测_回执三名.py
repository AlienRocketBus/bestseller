# -*- coding: utf-8 -*-
"""负测·回执三名（限360·2026-09-23 立）

⛔**其所治者**：**一份文书有两三种名目**——作业单（半路所交）／案席（补正所交）／
封版席（末段所交）——**而诸器死认「第N章作业单.md」一种**，
於是一章明明交过封版席，器里仍作「没交」。

★**其所由来**：0923 第358章封版之日，`自走.py::回执在` 判「第358章回执不在」，
  并印出叫人把一章已封版的书**从头再跑一遍**之命（其详逐字在 `自走.py:90—102`）。
  **而 358 那两份回执叫 `…第358章封版席.md` 与 `…第358章案席.md`，无「作业单」三字。**

⛔★★★**并当面报此治之一短·免後坐以为本坐拿了个宽**：
  **全书 358 章逐章亲数，「只有案席／封版席而无作业单」者只有一章——第358章，本坐手上这一章。**
  **即：此治立不住在「全书都在误伤」那一条上**（本日另三治各有 167章／34段／10章之广），
  **只立得住在「封版席本来就是回执，且比作业单更是走完了之凭」这一条上。**
  ★**故本测之要害不在「新式认得」，在每一格皆验其反面：⛔旧式对同一份封版席一个也不认。**

跑：python3 工具/负测_回执三名.py
"""
import os as _o, sys as _s
_s.path.insert(0, _o.path.dirname(_o.path.abspath(__file__)))
try:
    import _账  # 跑账·自记（工具/跑账.py）
except Exception:
    pass
import os, sys, glob, re, tempfile, shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
过 = 败 = 0


def chk(名, 实):
    global 过, 败
    if 实:
        过 += 1
    else:
        败 += 1
        print('  ⛔不过：%s' % 名)


# ── 一·沙盘（⛔不动真盘）──────────────────────────────
_沙 = tempfile.mkdtemp(prefix='回执三名_')
os.makedirs(os.path.join(_沙, '设定'))


def _造(名):
    open(os.path.join(_沙, '设定', 名), 'w', encoding='utf-8').write('沙盘')


_造('回执_20260923_第7章封版席.md')     # 只有封版席
_造('回执_20260923_第8章案席.md')       # 只有案席
_造('回执_20260923_第9章作业单.md')     # 只有作业单（旧式之基准）
# 第10章：一份也没有

新式 = lambda n: any(glob.glob(os.path.join(_沙, '设定', '回执_*_第%d章%s.md' % (n, k)))
                    for k in ('作业单', '案席', '封版席'))
旧式 = lambda n: bool(glob.glob(os.path.join(_沙, '设定', '回执_*_第%d章作业单.md' % n)))

chk('①新式·只有封版席者今算交了', 新式(7))
chk('⛔①之反面·旧式对同一份封版席不认——故上一格非陪跑', not 旧式(7))
chk('②新式·只有案席者今算交了', 新式(8))
chk('⛔②之反面·旧式对同一份案席亦不认', not 旧式(8))
chk('③旧路一格未动·只有作业单者照旧算交了', 新式(9) and 旧式(9))
chk('④⛔三种一份也没有者照旧不算（此治只认名目，不发赦）', not 新式(10) and not 旧式(10))
chk('⑤⛔别章之回执不算本章之交（型须咬住章号）', not 新式(70) and not 新式(77))
shutil.rmtree(_沙)

# ── 二·逐器亲验其源已改（⛔六把器一把不许漏）────────────
_诸器 = {
    '全测.py': '_已封版',
    '十一轮哨.py': '已交回执之章',
    '十轮精进.py': None,
    '小说检察官.py': None,
    '接力.py': '有回执',
}   # 1027 A2：一代「一令封版」之器已彻删——封版.py 承其职
for 名 in _诸器:
    _s = open(os.path.join(ROOT, '工具', 名), encoding='utf-8').read()
    # ⛔只数**活码**那一行，不数注里所引之档名（注里满是「…第313章作业单.md」之引）
    _活 = [l for l in _s.splitlines()
           if 'glob' in l and '回执_*_第' in l and not l.lstrip().startswith('#')]
    chk('%s·活码里已无「只认作业单」那一式' % 名,
        not any(re.search(r"回执_\*_第[^']*章作业单\.md", l) for l in _活))
    chk('%s·三名俱在其活码或其紧邻之表内' % 名,
        all(k in _s for k in ('作业单', '案席', '封版席')))

# ── 三·真盘之实（⛔报其广，不藏其短）──────────────────
_只别 = []
for n in range(1, 400):
    _a = glob.glob(os.path.join(ROOT, '设定', '回执_*_第%d章作业单.md' % n))
    _b = (glob.glob(os.path.join(ROOT, '设定', '回执_*_第%d章案席.md' % n))
          + glob.glob(os.path.join(ROOT, '设定', '回执_*_第%d章封版席.md' % n)))
    if _b and not _a:
        _只别.append(n)
# ⛔★2026-09-23 改·本测立後四小时自栽一回（359 封版之日）：
#   ★**旧式把那个数写死作 `== 1`、那份单写死作 `== [358]`**；
#     **359 封版之日其回执亦只有案席与封版席，单成了 [358, 359]，本测当场红。**
#   ⛔**而那一红不是此治坏了，是本测把「一个当日的数」当成了「一条法」。**
#   ★★**其害更深一层**：**一个写死的数，下一坐见它红，头一个念头是「把 1 改成 2」**——
#     **那就成了「每多一章便放一次行」的暗门**，⛔**正是本测原本要堵的那一样。**
#   ★★★**故改判其不变之式，不判其当日之数**：
#     **此治所及之章，须一章不漏地落在「本坐动它那一日及其後」**（≥358）——
#     ⛔**即它永不回头赦免一章旧书**；**而那份单照旧原样印出来，一个章号不许藏。**
chk('⑥真盘·⛔此治所及者无一章早於 358（即它永不回头赦免一章旧书）',
    all(n >= 358 for n in _只别))
chk('⑦而其单非空——本治确有所及，⛔不是一条空转之令',
    len(_只别) >= 1)
chk('⛔⑦之二·358 在其中（本治之短：头一章正是本坐手上那一章）',
    358 in _只别)

print('  ── 真盘之实：只有案席/封版席而无作业单者 %d 章 %s ──' % (len(_只别), _只别))
print('  负测·回执三名：%d/%d' % (过, 过 + 败))
sys.exit(1 if 败 else 0)
