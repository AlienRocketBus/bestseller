# -*- coding: utf-8 -*-
"""负测·暗线章场景切换闸（2026-09-04·300第5轮立）

★所治之伤：`质量三闸.py::①之c` 之词表原有四样（那一边／另一头／与此同时／同一时候），
　★而全书逐章核过：**此闸三百章里只响过三回，三回皆假**
　　（100章「不在寨子那一边，也不在山那一边」係图上之向｜94章「老头在另一头」係担架两端｜
　　 85章「对着一头吹。另一头有气出来」係竹管两端）；
　★★而真正的切换词「与此同时」「同一时候」**全书零处**。
★★即：会响的那两样一次也没逮着东西，逮得着东西的那两样一次也没响。
★★★故本测断三样，一样也不许松：
　①今式对本书之实文不许乱响（那一边／另一头係寻常方位之词）；
　②今式对真切换词照旧要响（不许成了一个什么也不认的闸）；
　③旧式回灌须报红（拿真犯过此项之原物灌回去·令§十四3）。
★★★★而本测断的是不变之则，不是今日之天气（第二十八犯之戒）。
"""
import glob, io, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
旧式 = re.compile(r'那一边|另一头|与此同时|同一时候')
今式 = re.compile(r'与此同时|同一时候')

ok = bad = 0


def chk(名, 得, 期):
    global ok, bad
    if 得 == 期:
        ok += 1; print('  ✓ %s' % 名)
    else:
        bad += 1; print('  ✗ %s ← 得 %r，期 %r' % (名, 得, 期))


def 白文(f):
    return io.open(f, encoding='utf-8').read().split('【本章亮点】')[0]


def 暗章():
    return [f for f in sorted(glob.glob(os.path.join(ROOT, '正文', '*.md')))
            if '沈鸢' in 白文(f)]


print('════ 负测·暗线章场景切换闸 ════')
章 = 暗章()
chk('①含沈鸢之章取得着（其数须>0，否则本测在空处跑）', len(章) > 0, True)

# ②今式对全书实文：一处也不许响
今响 = [(os.path.basename(f), 今式.findall(白文(f))) for f in 章 if len(今式.findall(白文(f))) > 1]
chk('②今式对全书暗线之实文，一章也不许判红', 今响, [])

# ③旧式回灌：那三章须报红（拿真犯过此项之原物灌回去）
旧响 = sorted(os.path.basename(f).split('_')[1] for f in 章 if len(旧式.findall(白文(f))) > 1)
chk('③旧式回灌须报红，且正是那三章', 旧响, sorted(['第一百章', '第八十五章', '第九十四章']))

# ④而那三章逐处皆非切换（本测之据，写死在此，日后有人翻案须先驳它）
证 = {'第一百章': '不在寨子那一边，也不在山那一边',
      '第九十四章': '老头在另一头，两个人一头一个',
      '第八十五章': '对着一头吹。另一头有气出来'}
逐 = []
for f in 章:
    n = os.path.basename(f).split('_')[1]
    if n in 证:
        逐.append(证[n] in 白文(f).replace('\n', ''))
chk('④那三处之原句逐处仍在（其判之据不许悄悄没了）', 逐, [True, True, True])

# ⑤今式对真切换词照旧要响（不许成了一个什么也不认的闸）
假章 = '她在屋里数那一圈。与此同时，山那头有人在走。同一时候，风起了。'
chk('⑤真切换词灌进去，今式须响', len(今式.findall(假章)) > 1, True)

# ⑥而今式对寻常方位之词不许响（此即本次所去掉的那两样）
寻常 = '碗沿是热的。热的那一边贴上去，凉的那一边没有动。老头在另一头。'
chk('⑥寻常方位之词（那一边／另一头）灌进去，今式一处也不许响',
    len(今式.findall(寻常)), 0)
chk('⑥之b而旧式对同一段须响（证此二样正是旧式之全部火力）',
    len(旧式.findall(寻常)) > 1, True)

# ⑦其码里须留着那三回之实证（下一坐不许把它当无据之改）
src = io.open(os.path.join(ROOT, '工具', '质量三闸.py'), encoding='utf-8').read()
chk('⑦质量三闸之码内留有「三回皆假」之注', '三回皆假' in src, True)
chk('⑦之b并留有「另入法典欠单」之记（不许当作已治）', '欠-300B' in src, True)

print('  ── %d/%d %s ──' % (ok, ok + bad, '全通' if bad == 0 else '⛔未过'))
sys.exit(0 if bad == 0 else 1)
