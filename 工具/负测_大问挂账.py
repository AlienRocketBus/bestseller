# -*- coding: utf-8 -*-
"""负测·大问挂账（八造·2026-09-03 立）

★所治之伤：大问表自 2026-09-01 立起自印「只报不拦」，
　而以294章计逾四十章者七样（血图缺234章、悬赏223、地窖222、寨里那些人186、
　爷爷184、走路的理由116、听针92）——**二百三十四章之内没有一道闸因此拦过一次**。
★★八造改其律为「可以欠，不可以不认」：逾限者须各有一笔挂账，挂账须带限章；
　挂了账而逾了自己那个限者，拦。
★★★**而本测断的是不变之则，不是今日之天气**（第二十八犯之戒）：
　逐条皆「拿掉那一样 → 须红；放回去 → 须绿」，一处也不写死今日之数。
"""
import io, os, re, sys
import importlib.util as _iu

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_p = os.path.join(ROOT, '工具', '大问表.py')
_s = _iu.spec_from_file_location('_dwb', _p)
M = _iu.module_from_spec(_s); _s.loader.exec_module(M)

档 = M.挂账档
原 = io.open(档, encoding='utf-8').read() if os.path.exists(档) else None

ok = bad = 0


def chk(名, 得, 期):
    global ok, bad
    if 得 == 期:
        ok += 1; print('  ✓ %s' % 名)
    else:
        bad += 1; print('  ✗ %s ← 得 %r，期 %r' % (名, 得, 期))


def 跑():
    """静跑一回，返回 (逾, 无挂, 逾限)。★2026-09-04 报() 加第四位「线之犯」，此处只取前三。"""
    return M.报(quiet=True)[:3]


def 写(t):
    io.open(档, 'w', encoding='utf-8').write(t)


try:
    print('════ 负测·大问挂账 ════')

    # ①今日之实：册在，且逐样有挂——须无「无挂」、无「逾限」
    逾0, 无挂0, 逾限0 = 跑()
    chk('①册齐之时，无一样无挂账', 无挂0, [])
    chk('①册齐之时，无一笔逾其自定之限', 逾限0, [])
    chk('①而逾四十章者本身照旧要报（不许因挂了账就不报）', len(逾0) > 0, True)

    # ②抽掉一笔挂账 → 那一样须落进「无挂」；放回 → 须复绿
    某 = 逾0[0]['名']
    行 = [l for l in 原.split('\n') if l.startswith('| ' + 某 + ' ')]
    assert 行, '取不到 %s 之行' % 某
    写(原.replace(行[0] + '\n', ''))
    _, 无挂1, _ = 跑()
    chk('②抽掉「%s」之挂账 → 它须落进无挂' % 某, 某 in 无挂1, True)
    写(原)
    _, 无挂1b, _ = 跑()
    chk('②放回去 → 须复绿', 某 in 无挂1b, False)

    # ③把一笔的限改到今章之前 → 须落进「逾限」；改回 → 须复绿
    # ★不照单元格之貌下手（本测头一版即栽在此：以「**限第N章**」去替，而册里写的是「**N**」，
    #   於是替了个空，测自己绿了。故改为**按栏重建**，不问那一栏长什么样。）
    末, _rows = M.量()

    def 改限(行, 新):
        c = [x.strip() for x in 行.strip().strip('|').split('|')]
        c[3] = '**%d**' % 新
        return '| ' + ' | '.join(c) + ' |'

    改 = 改限(行[0], 末 - 1)
    assert 改 != 行[0], '③之替换须真改了那一栏'
    写(原.replace(行[0], 改))
    _, _, 逾限2 = 跑()
    chk('③「%s」之限改到今章之前 → 须落进逾限' % 某, 某 in [a for a, b in 逾限2], True)
    写(原)
    _, _, 逾限2b = 跑()
    chk('③改回去 → 须复绿', 某 in [a for a, b in 逾限2b], False)

    # ④限正落在今章者，不算逾（限之义是「最晚这一章还」，不是「这一章之前还」）
    改4 = 改限(行[0], 末)
    写(原.replace(行[0], 改4))
    _, _, 逾限3 = 跑()
    chk('④限正落在今章者不算逾（最晚这一章还，仍在期内）', 某 in [a for a, b in 逾限3], False)
    写(原)

    # ⑤状不作「挂」者不算挂账（还过的那几行不许再当欠条使）
    改5 = 行[0].rsplit('|', 2)[0] + '| 还 |'
    写(原.replace(行[0], 改5))
    _, 无挂4, _ = 跑()
    chk('⑤状改作「还」者不再算挂账 → 须落回无挂', 某 in 无挂4, True)
    写(原)

    # ⑥册整个不在 → 逾限者须一样不落地全进「无挂」
    os.rename(档, 档 + '.bak')
    try:
        逾5, 无挂5, _ = 跑()
        chk('⑥册不在 → 逾限者须一样不落地全进无挂', sorted(无挂5), sorted(r['名'] for r in 逾5))
    finally:
        os.rename(档 + '.bak', 档)

    # ⑦其口须真会拿非零退出（一道只会说「零」的闸没有价值·令§六③）
    src = io.open(_p, encoding='utf-8').read()
    chk('⑦其主口拦得动（见 sys.exit(1 ...)）', 'sys.exit(1 if' in src, True)
    chk('⑦旧律「只报不拦」已不在其主口', "sys.exit(0)   # ★只报不拦" in src, False)

    # ────────────────────────────────────────────────────────────────
    # ★★★★★2026-09-04·300第1轮起草之前所加（其红在哪一行，上磁盘核过）：
    #   **PRES-297B刘二·限300·其线苏衍**（291他给东头擦手，东头在担架上，担架在苏衍那一边），
    #   **而300之开镜卡判「暗线·沈鸢·屋内·四人未出洞」**——**刘二一步也走不进那间屋**。
    #   ★而这一笔297挂过、299之轮记抄过、圣经300锚写过、回执写过两回，**四处逐处照抄**，
    #     没有一处问过「那一章是哪条线」；★★而本册§三 2026-09-03 明明审过这一样，
    #     **那一审只扫了立表那一天的七笔，东头/刘二是同日後加的，一笔也没进那一审**
    #     ——即第三十四犯：一份册只在立它那一天跑过一回。
    # ────────────────────────────────────────────────────────────────
    犯0, 疑0 = M.线验()
    chk('⑧今日之册，已判之章无一笔线不对位', 犯0, [])
    chk('⑧而未判之章须落进⚠，不许当作绿（令§一⑤：未印之项记未验）', len(疑0) > 0, True)

    # ⑨旧式回灌（§六③·§十四3）：把刘二那一笔放回它原来的限300 → 须报红
    行9 = [l for l in 原.split('\n') if l.startswith('| **刘二**')]
    assert 行9, '取不到刘二之行'

    def 改栏(行, i, 新):
        c = [x.strip() for x in 行.strip().strip('|').split('|')]
        c[i] = 新
        return '| ' + ' | '.join(c) + ' |'

    # ★2026-09-05：刘二一笔已於301还（§一状栏作「还」，§二有其行）；回灌旧物须连其状一并回到「挂」，否则 挂() 不认此行，测自绿。
    改9 = 改栏(改栏(行9[0], 3, '**300**'), 6, '挂')
    assert 改9 != 行9[0], '⑨之替换须真改了那一栏'
    写(原.replace(行9[0], 改9))
    犯9, _ = M.线验()
    chk('⑨回灌真犯之原物（刘二·限300）→ 须报红', [a for a, *_ in 犯9], ['刘二'])
    写(原)
    犯9b, _ = M.线验()
    chk('⑨改回301 → 须复绿', [a for a, *_ in 犯9b], [])

    # ⑩线未判之章只入⚠，不入犯（宁可不判，不许拿奇偶相间去补）
    改10 = 改栏(改栏(行9[0], 3, '**999**'), 6, '挂')
    写(原.replace(行9[0], 改10))
    犯10, 疑10 = M.线验()
    chk('⑩限落在无卡无锚之章 → 只入⚠，不入犯', ('刘二' in [a for a, *_ in 犯10],
                                        '刘二' in [a for a, *_ in 疑10]), (False, True))
    写(原)

    # ⑪其线一栏不书、或书一个不认之名者，本器不判（它认哪几样：只认苏衍／沈鸢二样）
    改11 = 改栏(行9[0], 4, '**—**')
    写(原.replace(行9[0], 改11))
    犯11, 疑11 = M.线验()
    chk('⑪其线一栏不书之名者，不判亦不疑', '刘二' in [a for a, *_ in 犯11 + 疑11], False)
    写(原)

    # ⑫线()不许被那一行括号里「上一章是哪条线」那半句骗（三处实例·§六第5步）
    #   ★299之卡逐字：「- **本章为**：**主线**（苏衍…；298为**暗线**·沈鸢…）」
    #   ★★头一版写作「if '暗线' in ln」，遂把299判成沈鸢，并当场诬走路的理由一笔——一验即见。
    chk('⑫线(298)＝沈鸢', M.线(298), '沈鸢')
    chk('⑫线(299)＝苏衍（其卡同一行里还写着「298为暗线」，不许被它骗）', M.线(299), '苏衍')
    chk('⑫线(300)＝沈鸢', M.线(300), '沈鸢')

    # ⑬其主口须真拿线之犯当拦（不许只印不拦）
    chk('⑬线之犯已进其主口之退出码', '_fx' in src and 'or _fx' in src, True)

    # ⑭还表（2026-09-05·机制总审·数与册审第3条所立）：一笔照其形还得干净（白文无其名），本器须凭§二之一行认它已还
    #   ★其红在哪一行：305把爷爷一笔当章还了（钥匙当尺），其形写死「不许写他想起」，故305白文「爷爷」零处——
    #     旧式只数其词，末见仍第110章、缺195、逾限305 → 306 起手即拦一笔已还之账。
    H = M.还()
    chk('⑭还表·§二 爷爷一行读得着（还於305）', H.get('爷爷'), 305)
    末14, rows14 = M.量()
    爷 = [r for r in rows14 if r['名'] == '爷爷'][0]
    chk('⑭还表·爷爷末见取还表之章（305），非其词之末见', 爷['末见'], 305)
    # ⑭之二·旧式回灌：抽掉§二爷爷一行，末见须退回其词之末见（<305）且落回「逾」——证此改非陪跑
    行14 = [l for l in 原.split('\n') if l.startswith('| 305 | 爷爷 |')]
    assert 行14, '取不到§二 爷爷之行'
    写(原.replace(行14[0] + '\n', ''))
    _, rows14b = M.量()
    爷b = [r for r in rows14b if r['名'] == '爷爷'][0]
    chk('⑭之二·旧式回灌·无还表之行时爷爷末见退回其词（%d）且逾' % 爷b['末见'], 爷b['末见'] < 305 and 爷b['逾'], True)
    写(原)
    # ⑭之三·还表只认带章号之行，表头与「—」占位行不认
    chk('⑭之三·还表不认表头与占位行', all(isinstance(v, int) and v > 0 for v in H.values()) and '其样' not in H and '—' not in H, True)

finally:
    if 原 is not None:
        写(原)

# ★其末行须依 全测.py::_简测 之式（「N/N 全通」／「N/N ⛔未过」），否则全测报「未见其数」。
print('  ── %d/%d %s ──' % (ok, ok + bad, '全通' if bad == 0 else '⛔未过'))
