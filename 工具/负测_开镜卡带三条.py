chk('⑤其语须说出「事之择」而非「把段砍短」', '砍短' in (_语长 or '') or '事' in (_语长 or ''))
chk('⛔⑥而上一章已换了型者，本章不判——故④非陪跑', _须断 is False)

# ── 三·卡上带没带（⛔本测之要害在这儿）──────────────────
