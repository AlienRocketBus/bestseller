def _载(名):
    sp = iu.spec_from_file_location('_m_' + 名, os.path.join(ROOT, '工具', 名 + '.py'))
    m = iu.module_from_spec(sp)
    sp.loader.exec_module(m)
    return m


_零 = _载('第零轮开镜庭')
_fl = _载('分量闸')
_hx = _载('换型令')

# ── 一·须厚（⛔沙盘之表，不动真盘）──────────────────────
#   暗线之窗：末五篇暗线无一及 2,900 者，本章（其窗末一篇）即「非厚不可」。
_线 = {n: ('暗' if n % 2 else '主') for n in range(340, 362)}
