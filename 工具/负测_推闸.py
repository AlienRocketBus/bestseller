# -*- coding: utf-8 -*-
"""推闸负测（2026-08-28 立·随「改钩子之策」同日）。
★其立之由：推闸一开，闸即从「全绿才许推」放宽为「跑轮期间可推」；
  ★★而放宽之闸若窗划得不准，等於把闸拆了。
★★★故此测专问：那扇窗到底有多窄——凡不该放行者，一样也不许放过去。"""
import sys, importlib.util, tempfile, os, io

spec = importlib.util.spec_from_file_location('qc', '工具/全测.py')
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)

_六 = '⑥·冷轮之欠 ★2笔未执：COLD-284、COLD-285'
_六逾 = '⑥·冷轮之欠 ★2笔未执：COLD-281、COLD-284⛔（其中1笔已逾期）'
_七 = '⑦·第287章锚 ⛔未备'
_零下 = '三·本章之一事（起草前写明） ⛔未立：须先出开镜卡（本工具 --立 288）'
_零本 = '三·本章之一事（起草前写明） ⛔未立：须先出开镜卡（本工具 --立 287）'

案 = []
def chk(名, 实, 期):
    案.append((名, 实 is 期 or 实 == 期, '实=%r 期=%r' % (实, 期)))

def 跑(fails, raw, 封版=False, 末章=287):
    m._末章 = lambda: 末章
    m._已封版 = lambda n: 封版
    m._RAW.clear(); m._RAW.update(raw)
    return m.推闸(fails)[0]

# ① 正当之形：跑轮中，只⑥（不带逾期）＋第零轮索下一章之卡 → 放行
chk('①跑轮中·只此二项 → 放行',
    跑(['开轮十六检', '第零轮'], {'开轮十六检': _六, '第零轮': _零下}), True)
chk('①之b 只⑥一项 → 放行', 跑(['开轮十六检'], {'开轮十六检': _六}), True)
chk('①之c 只第零轮一项 → 放行', 跑(['第零轮'], {'第零轮': _零下}), True)

# ② 本章回执已交（已封版）→ 一律不放行
chk('②已封版 → 不放行（须全绿）',
    跑(['开轮十六检', '第零轮'], {'开轮十六检': _六, '第零轮': _零下}, 封版=True), False)

# ③ ⑥带「逾期」→ 真漏，不放行
chk('③⑥带逾期 → 不放行', 跑(['开轮十六检'], {'开轮十六检': _六逾}), False)

# ④ 开轮十六检里除⑥之外还有别的检 → 不放行
chk('④⑥＋⑦ → 不放行', 跑(['开轮十六检'], {'开轮十六检': _六 + '；' + _七}), False)
chk('④之b 只⑦无⑥ → 不放行', 跑(['开轮十六检'], {'开轮十六检': _七}), False)

# ⑤ 第零轮索的是本章之卡（非下一章）→ 不放行
chk('⑤第零轮索本章之卡 → 不放行', 跑(['第零轮'], {'第零轮': _零本}), False)

# ⑥ 结构性二项之外，任一项红 → 不放行
for 别 in ['医生', '全书检', '质量三闸', '核轮', '检察官自测', '负测·冷轮闸']:
    chk('⑥「%s」红 → 不放行' % 别,
        跑(['开轮十六检', 别], {'开轮十六检': _六}), False)

# ⑦ 原文取不到（器崩）→ 不放行
chk('⑦开轮十六检原文空 → 不放行', 跑(['开轮十六检'], {'开轮十六检': ''}), False)

# ⑧ 正文一篇也无 → 不放行
chk('⑧无正文 → 不放行', 跑(['第零轮'], {'第零轮': _零下}, 末章=0), False)

坏 = [x for x in 案 if not x[1]]
for 名, 过, 详 in 案:
    print(('  ✓ ' if 过 else '  ⛔ ') + 名 + ('' if 过 else '　' + 详))
print('\n★负测 %d 项，过 %d，坏 %d' % (len(案), len(案) - len(坏), len(坏)))
sys.exit(1 if 坏 else 0)
