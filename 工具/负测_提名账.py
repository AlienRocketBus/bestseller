def _旧式认几回(组):
    """旧式：以拍号为身。取四条之交集——**交集为空，故旧式一回也认不出。**"""
    共 = set(组[0])
    for x in 组[1:]:
        共 &= set(x)
    return len(共)


def _新式认几回(条):
    """新式：以白文头十四字为身，以文本之码去重。"""
    d = {}
    for 文, 号, 码 in 条:
        e = d.setdefault(文[:14], {'码': [], '号': []})
        if 码 not in e['码']:
            e['码'].append(码)
            e['号'].append(号)
    return max(len(v['码']) for v in d.values())


