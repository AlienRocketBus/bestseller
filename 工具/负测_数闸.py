def _文件(章):
    import glob
    g = glob.glob(os.path.join(ROOT, '正文', '*%s_*.md' % 章))
    return g[0] if g else None


def 跑():
    m = _器()
    坏 = []
    # ①今日全书须零处不符
    if m.全书(quiet=True):
        坏.append('今日全书仍有不符——修尺未毕')
    # ②逐处灌回旧错，闸须红
    for 章, 今, 旧 in 桩:
        f = _文件(章)
        if not f:
            坏.append('取不到 %s' % 章)
            continue
        orig = io.open(f, encoding='utf-8').read()
        if 今 not in orig:
            坏.append('%s 之今文与本测所记不符（回灌之据已陈）：%s' % (章, 今[:18].replace('\n', '⏎')))
            continue
        try:
            io.open(f, 'w', encoding='utf-8').write(orig.replace(今, 旧, 1))
            if not m.扫(f):
                坏.append('★灌回旧错而闸不红：%s ｜%s' % (章, 旧[:24].replace('\n', '⏎')))
        finally:
            io.open(f, 'w', encoding='utf-8').write(orig)
    # ③五处误报之形不许认
    for 章, 句 in 不许认:
        f = _文件(章)
        if f and m.扫(f):
            坏.append('★误报之形又被认了：%s ｜%s' % (章, 句[:26]))
    n = 1 + len(桩) + len(不许认)
    if 坏:
        print('✗ 负测·数闸 %d/%d' % (n - len(坏), n))
        for x in 坏:
            print('   ⛔ ' + x)
        return 1
    print('✓ 负测·数闸 %d/%d 全通（全书零处不符；%d 处旧错逐处灌回皆红；%d 处误报之形一处未认）'
          % (n, n, len(桩), len(不许认)))
    return 0


if __name__ == '__main__':
    sys.exit(跑())
