    for 名, 文 in 诸回执:
        io.open(os.path.join(d, '设定', 名), 'w', encoding='utf-8').write(文)
    老 = m.ROOT
    m.ROOT = d
    try:
        rows = m.check_loss({500: '白文'})[0]
        return [r for r in rows if r[0] == 500][0][1]
    finally:
        m.ROOT = 老
        shutil.rmtree(d, ignore_errors=True)


