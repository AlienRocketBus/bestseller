import 跑轮


def 对档(记软, 档文):
    """照 `跑轮.py::save` 0918 之後之式：自 `score` 取回再量一回，逐项对。
    ⛔此处**直引 `跑轮.score`**，不另写一份量法（局③之实）。返回不合之项。"""
    _, 软 = 跑轮.score(档文)
    return [(k, 记软[k], 软[k]) for k in ('净重', '段数', '长段数')
            if k in 记软 and k in 软 and 记软[k] != 软[k]]


def 跑():
    文 = ('《镇冢秘术》\n\n第九百九十九章　负测\n\n'
          '他把那一张推出去半寸。他的手还在裤上，没有抬。我把它推了回来。\n\n＊\n\n'
          '点一格，掀一张；掀出来的不是这一行那一张，就放回去，再掀。\n')
    _, 真 = 跑轮.score(文)

    局 = []
    # ①记与档不合 → 须红
    假 = dict(真); 假['净重'] = 真['净重'] + 37
    不合 = 对档(假, 文)
    局.append(('①记与档不合（净重 %+d）→ 须红，且须指出是「净重」这一项'
               % 37, bool(不合) and 不合[0][0] == '净重'))
    # ⛔并验其所印之差係真差，非只报一个「不合」
    局.append(('①之二·所印之差须係真差（%d 对 %d）' % (假['净重'], 真['净重']),
               bool(不合) and 不合[0][1] == 假['净重'] and 不合[0][2] == 真['净重']))
    # ②合者 → 须绿
    局.append(('②记与档相符 → 须绿（⛔天天报红者报的是它自己）', 对档(真, 文) == []))
    # ②之二·段数亦须能红（⛔不许只看净重一项）
    假2 = dict(真); 假2['段数'] = 真['段数'] + 1
    局.append(('②之二·段数不合亦须红（⛔不许只认净重一项）',
               [x[0] for x in 对档(假2, 文)] == ['段数']))
    # ③量之法自 score 取回，不另抄一份
    局.append(('③量之法自 `跑轮.score` 取回，本测一行自己的量法也没有',
               对档.__doc__ is not None and '跑轮.score' in 对档.__doc__))
    # ③之二·档文改了一个字，其数即须跟着动（⛔证它真在读档，不是在读记）
    局.append(('③之二·档文改一字其数即动（⛔证它读的是档，不是记）',
               bool(对档(真, 文 + '再掀一回。\n'))))

    红 = 0
    print('════ 负测 · 版档指纹之当场对档（六局）════')
    for 名, 果 in 局:
        print('  %s %s' % ('✓' if 果 else '⛔', 名))
        if not 果:
            红 += 1
    print('  ── %d/%d ──' % (len(局) - 红, len(局)))
    return 红


if __name__ == '__main__':
    sys.exit(1 if 跑() else 0)
