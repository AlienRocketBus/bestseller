# -*- coding: utf-8 -*-
"""负测·看官之「手上之事」闸（2026-09-01 立·287第11轮）

★立此测之由：生客问一报「第287章拍25—49连25拍无一手上之事」，
　★★而那一段里 抬×5、托×2 皆是手上之事——是此式不识本书自己的主动词。
★★★而令§六③曰：改闸必同日立负测，且须以旧式回灌验。
　★★★★故本测之要害只一条：**下列各拍在旧式下漏认，在新式下认得出**；
　　★漏认者一多，问一那一段就整段错报，而错报之闸会逼人去改对的文。
"""
import io, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

旧式 = re.compile(r'(把|拿|摸|按|抓|挪|捻|捏|压|搁|插|抽|悬|落笔|划|迈|坐下|起身'
                 r'|伸手|量|盖|刮|擦|系|解开|端|舀|磕|撬|抱|递|收|walk'
                 r'|翻[到回开页过一二三四五六七八九十第那这])')


def _新式():
    import importlib.util
    spec = importlib.util.spec_from_file_location(
        '看官', os.path.join(ROOT, '工具', '看官.py'))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m.手


# ★该认而旧式不认者（皆取自正文原场，非杜撰）
须认 = [
    ('我今天抬后头。', '抬'),
    ('抬起来那一下我数了。两下起稳。', '抬'),
    ('我在后头。两只手托着竹竿。', '托'),
    ('托着走了一程，我觉出来了。', '托'),
    ('先前我背他，眼前是路。', '背'),
    ('盘完他把绳挂在自己肩上。', '挂'),
    ('刘二蹲在东头那一头，拿手背贴他额头。', '贴'),
    ('他拿起来甩了一下。绳直了。', '甩'),
    ('我看着他盘。', '盘'),
    ('钱满蹲在那块平石边上。', '蹲'),
    ('昨天垫的是这一件。', '垫'),
    ('我写第三行。', '写'),
    ('昨天前天我就是那么点的。', '点'),
]

# ★不许认者（认了即把「心里在想」当成「手上在做」，闸就不响了）
不许认 = [
    '我数今天办成了几样。',
    '三行是从哪一天起变成三行的，我说不出。',
    '多半是。',
    '在不在，跟办成没办成，对不上。',
    '少那一下是后头轻，还是少一个人，我分不出。',
]


def 跑():
    新式 = _新式()
    坏 = []
    回灌漏 = 0
    for 句, 由 in 须认:
        if not 新式.search(句):
            坏.append('新式漏认（%s）：%s' % (由, 句))
        if not 旧式.search(句):
            回灌漏 += 1
    for 句 in 不许认:
        if 新式.search(句):
            坏.append('新式误认（心里之事作手上之事）：%s' % 句)
    # ★回灌验：这一份测若在旧式下也全过，它就是陪跑（令§六③）
    if 回灌漏 == 0:
        坏.append('★此测在旧式下亦全过——它是陪跑之测，不算数。')
    n = len(须认) + len(不许认)
    if 坏:
        print('✗ 负测·看官手闸 %d/%d' % (n - len(坏), n))
        for x in 坏:
            print('   ⛔ ' + x)
        return 1
    print('✓ 负测·看官手闸 %d/%d 全通（旧式回灌漏认 %d 项，故非陪跑）'
          % (n, n, 回灌漏))
    return 0


if __name__ == '__main__':
    sys.exit(跑())
