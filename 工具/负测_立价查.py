    旧FORMS = [f for f in LJ.FORMS if f[0] not in ('多大就多大', '再X得Y')]
    旧出 = 跑式(300, 旧FORMS)
    今出 = 跑式(300, LJ.FORMS)
    # ★2026-09-04 第12轮改其陈：本器立时300章无一句立价，故旧式回灌印「全章无立价之句」；
