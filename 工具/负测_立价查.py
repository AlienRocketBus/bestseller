    chk('⑤全书之中「新式认得而旧式认不着」者 ≥1 章（此断言不钉在任何一章之现文上）',
        len(新逮) >= 1)
    print('     ★其章 %d 篇%s' % (len(新逮), ('，如 ' + '、'.join(str(x) for x in sorted(新逮)[:6])) if 新逮 else ''))

