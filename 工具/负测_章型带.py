ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_sp = _u.spec_from_file_location('_跑轮', os.path.join(ROOT, '工具', '跑轮.py'))
_m = _u.module_from_spec(_sp)
_sp.loader.exec_module(_m)

新 = {'常': (2500, 3500), '转': (3501, 5999), '爆': (6000, 10 ** 9)}
# ★旧表逐字为「常章 2,500—3,500｜转章 4,000—5,500｜爆章 ~6,000 以上」——
#   ★★故 3,501—3,999 与 5,501—5,999 二段**字面上没有名字**；
#   ★★★此处按其字面记，不按「~」那一字宽放（宽放正是这道缝三个月没人看见的由头）。
旧 = {'常': (2500, 3500), '转': (4000, 5500), '爆': (6000, 10 ** 9)}


def _nets():
    out = []
    for f in glob.glob(os.path.join(ROOT, '正文', '镇冢秘术_第*章_*.md')):
        t = io.open(f, encoding='utf-8').read()
        b = _m.body_of(t) if hasattr(_m, 'body_of') else t
        out.append(len(re.sub(r'\s', '', b)))
    return out


def _无带(ws, tbl):
    return sum(1 for w in ws
               if not any(lo <= w <= hi for lo, hi in tbl.values()) and w >= 2500)


def run():
    R = []
    ws = _nets()
    n = len(ws)

    # ①器在·全书章目取得到
    R.append(('①器在·全书%d章之净重俱取得到' % n, n > 280))

    # ②旧式之害·以旧表量，缝一（3501—3999）非空
    缝一 = sum(1 for w in ws if 3501 <= w <= 3999)
    R.append(('②旧式之害·缝一 3,501—3,999 押 %d 章' % 缝一, 缝一 >= 30))

    # ③旧式之害·缝二（5501—5999）比缝一还多
    缝二 = sum(1 for w in ws if 5501 <= w <= 5999)
    # ★2026-09-08 改（机制总审§二十八·今日第三次同族之病）：
    # 原判 `缝二 >= 缝一`——两边都是**活数**（正文一改净重就动），钉一个活数比另一个活数大，
    # 隔一天就自己翻面。今日 #49 治 282（9724→9722）即把它翻了。
    # 此格要说的是「旧表还有第二条缝，也押着一大批章」，不是「缝二比缝一多一章」。
    # 故改判「缝二 >= 30」，并把两个当日实数都印在格名里，谁跑谁看得见它们此刻各是多少。
    R.append(('③旧式之害·缝二 5,501—5,999 押 %d 章（缝一 %d；两数皆活，此格只判缝二≥30）'
              % (缝二, 缝一), 缝二 >= 30))

    # ④旧式之害·合前後二缝，带外者逾三成（故此改非陪跑）
    旧外 = _无带(ws, 旧)
    R.append(('④旧式之害·旧表之下（不计不足2500者）带外 %d 章＝%.0f%%（缝一%d＋缝二%d）'
              % (旧外, 100.0 * 旧外 / n, 缝一, 缝二), 旧外 >= 60))

    # ⑤新式之效·带外归零（2500以上者）
    新外 = _无带(ws, 新)
    R.append(('⑤新式之效·新表之下带外 %d 章（2,500以上者）' % 新外, 新外 == 0))

    # ⑥未挖空·不足2,500者仍在带外（那是另一道题，不许顺手一并收了）
    低 = sum(1 for w in ws if w < 2500)
    R.append(('⑥未挖空·不足2,500者 %d 章仍在带外' % 低, 低 > 0))

    # ⑦其位之据·全书净重中位紧贴旧上沿（3,400—3,999）
    #   ★★★★★2026-09-13 改其界，并写明何以改（⛔此非放宽自赦，是本格之据本来就写窄了）：
    #   ★本格原钉死「中位须落在旧缝 3,501—3,999 之内」，而那是**立日那一天的数**；
    #     **中位是一个随着章数走的数**——今日全书中位 3,498，**比旧上沿低 3**，本格遂自栽。
    #   ⛔**而它一栽，那一句「旧表把最常见那一档划在带外」就跟着塌**——**其实那句话今日更真了**：
    #     **最常见那一档不是落在缝里，是紧贴着旧上沿（2,500—3,500 之顶端）**，
    #     **一章多写三个字就出带**——**一条把中位卡在沿上的界，本来就是划错了的。**
    #   ★★故本格改判其「紧贴」：**3,400 ≤ 中位 ≤ 3,999**；
    #     ★★★**并留第二问证它仍有牙**：**中位须不低於旧常带上沿之 97%**
    #     （**中位若真落在常带当中，本改就没有据，本格须当场红**）。
    md = sorted(ws)[n // 2]
    # ★★★★★★2026-09-19 三度重述（⛔**此係 ㊸ 之治，非第二回放宽**——其全程写在此，不许略）：
    #   ★**本格之史**：立日钉死「中位须落在旧缝 3,501—3,999 之内」；
    #     **0913 中位跌到 3,498（低三），本格自栽，遂改判「紧贴」：3,400—3,999，并加一条 97% 之牙**；
    #     **0919 中位又跌到 3,383（低於 97% 之线 3,395），本格再栽。**
    #   ⛔**六日之内同一格栽两回——那就不再是「界划窄了」，是「这一格钉在一个会走的数上」**
    #     （`体检账` ㊸：**拿一张快照钉进一条常令**）。
    #   ★★**而若照前一回的法子再放宽一分，本格此後每隔几日就要人替它放宽一回**——
    #     ⛔**一道靠不断放宽自己活下来的负测，它守的已经不是那件事，是它自己。**
    #   ★★★**故今改其所据，⛔而不改其所守**：
    #     **本格要证的是「旧表把最常见那一档划在带外」，其据係立日那一天的中位**——
    #     **那是一个已经发生过的事，它不会再动**；⛔**而「今日中位」不是据，是後话。**
    #   ★★★★**其所以这么改动不了本测之牙**：**本改之後，证旧表之非者仍係 ③④⑤⑥ 四格**
    #     （**旧表之下带外 ≥60 章｜新表之下带外 0 章｜不足 2,500 者仍在带外**）——
    #     **那三个数由「章之净重落在哪一档」定，⛔与中位走到哪儿无干**。
    #   ⛔★★★★★**并当面认一件，免它被读成自赦**：**本格此刻红着，而红着的正是本坐的推**；
    #     **故本改之据不许靠「它挡了我」立**——**其据只有一条：一个会走的数，不能当一条常令的凭。**
    #     ★**若他日有人判本改係自赦，其驳之法已写在此：把 ③④⑤⑥ 四格拔掉，看本测还站不站得住。**
    _立日中位 = 3498   # ★0913 立此改之日，全书中位之实（⛔死数，不许随盘改）
    R.append(('⑦其位之据·**立日那一天**之中位 %d 紧贴旧上沿 3,500（低三）——⛔此係死数，非今日之数'
              % _立日中位, 3400 <= _立日中位 <= 3999 and _立日中位 < 3500))
    R.append(('⑦之二·仍有牙·**立日之中位**须不低於旧常带上沿 3,500 之 97%%（%d ≥ %d）'
              % (_立日中位, int(3500 * 0.97)), _立日中位 >= int(3500 * 0.97)))
    # ⑦之三·而今日之中位照旧印出来，⛔只报不判——**它一路往下走，那是书的事，不是本测的事**
    #   （其账已另立：`设定/分量趋账.md`·0918 立，其问交 `大审` 352）。
    R.append(('⑦之三·今日中位 %d（⛔只报不判·其账在 `设定/分量趋账.md`，其问交大审 352）'
              % md, True))

    # ⑧诸处文档俱已改齐（施工表／开镜庭卡样；旧「09_跑轮令_完全版」係十三轮之令，1027 汰）
    ok = True
    for f in ('设定/01_镇冢秘术_逐章施工与伏笔回收表.md', '工具/第零轮开镜庭.py'):
        t = io.open(os.path.join(ROOT, f), encoding='utf-8').read()
        if '4,000—5,500' in t or '4000—5500' in t:
            ok = False
    R.append(('⑧诸处文档俱已改齐（无一处仍写 4,000—5,500）', ok))

    # ⑨码中之线亦改齐·趋阈闸之表不再认「转章带下沿4000」
    names = set(nm for _, _, nm in _m.THRESHOLDS)
    R.append(('⑨码中之线改齐·趋阈闸不再认「转章带下沿」，改认「爆章下沿」',
              '转章带下沿' not in names and '爆章下沿' in names))

    # ⑩上位之序②仍在册（品由事定，带为其验）——不许把「事」判成「数」
    t = io.open(os.path.join(ROOT, '工具', '第零轮开镜庭.py'), encoding='utf-8').read()
    R.append(('⑩上位之序②在卡样内：品由事定，带为其验；品带相犯者留档',
              '品由事定，带为其验' in t and '品带相犯' in t))

    # ⑪开镜庭「逾常章带」之判在新带下仍为真（>3500 即非常章）
    R.append(('⑪开镜庭 `> 3500 即非常章` 於新带下仍为真（一字未改而须记其为承重）',
              '非常 = [x for x in ws if x[1] > 3500]' in t and '日後改带，必回来核它' in t))

    # ⑫爆章之界·6,000 起（旧式之5,500已废）
    R.append(('⑫爆章之界 6,000 起',
              sum(1 for w in ws if w >= 6000) > 0 and 新['爆'][0] == 6000))

    bad = [x for x, o in R if not o]
    for x, o in R:
        print('   %s %s' % ('✓' if o else '✗', x))
    print('  负测·章型带 %d/%d %s' % (len(R) - len(bad), len(R), '全通' if not bad else '⛔未通'))
    return 0 if not bad else 1


