"""负测·约到期闸（2026-09-02·九席审读所逮之伤·立闸同日）

★所验之闸：`工具/约到期.py`——**一句写在正文里的约，到期那一章须在轮记／回执里回话。**
★★**其要害在③**：**以第291章拍139「要分出来得有第三天」回灌，须报欠**——
   ★★★**其到期在第293章（第一百零四天），而293全章：东头0｜担架0｜毡子0｜甜0｜馊0｜刘二0**；
   ★★★★**而十三轮＋封版之序＋五十八项全测＋看官五席，一处也没出声**——
   **故一份逮不着这一根的测，就是陪跑（令§六③）。**
★**而④另验一样，其位与前者同等要紧**：**此闸不许用「猜」来判兑没兑**——
   立闸当日我试过两回（取实词比字面），**中文不分词，切片切出「了闻／天一／我蹲」，碎片在任一章都撞得上**；
   ★★**故④验其源里没有那条路，且明写弃它之由**。
"""
import io
import os
import sys
import importlib.util as _iu

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_sp = _iu.spec_from_file_location('_yd', os.path.join(ROOT, '工具', '约到期.py'))
_m = _iu.module_from_spec(_sp)
_sp.loader.exec_module(_m)
_SRC = io.open(os.path.join(ROOT, '工具', '约到期.py'), encoding='utf-8').read()

案 = []


def _t(名, 得, 期):
    案.append((名, 得 == 期, 得, 期))


def 跑():
    xs = _m.扫()
    ids = [x['号'] for x in xs]

    # ①器可跑，且找得着约
    _t('①找得着约（≥1处）', len(xs) >= 1, True)

    # ①之b★★★假红须收：229拍136「一个记号得有第二回、第三回来撑」不是约
    #   ★其说的是「同一样东西出现第二次、第三次」，不是第二天、第三天；
    #   ★★立闸当日旧式把它判成到期在230章之约——**假红一处即收，不留「反正只有一处」这句话**。
    _t('①之b 229拍136不作约（回／次须带日词方算）',
       any(x['号'] == '约-229.136' for x in xs), False)
    _t('①之c 而「回／次」带日词者仍算',
       bool(_m._日词.search('明天得有第三回')), True)

    # ②按号去重（二式命中同一拍者只算一约）
    _t('②按号去重', len(ids) == len(set(ids)), True)

    # ③★★★回灌·291拍139那一根须在册，且判欠
    一 = [x for x in xs if x['号'] == '约-291.139']
    _t('③291拍139在册', len(一), 1)
    _t('③之b 其到期之窗含第293章', bool(一) and 293 in 一[0]['窗'], True)
    # ★★★★★2026-09-02·第二十八犯第六形·当日自犯当日自改：
    #   ★此项原写作「判其欠」——**而我当天稍後就把回话写进了293之轮记，它遂不欠，此项当场判红**；
    #   ★★**同一形今日已立第二十八犯（复发5），而我在写完那一犯之後，隔了不到一坐又犯第六回**；
    #   ★★★**故照它自己开的方子改：不断言「此刻欠着」，断言「抽掉回话即欠、还回去即不欠」**
    #     ——**那才是这道闸的理，而「此刻欠不欠」只是今天的天气。**
    _t('③之c 其号成式（约-NNN，可供回话）', bool(一) and 一[0]['号'] == '约-291.139', True)

    # ③之d★而其所以欠，须以正文复核：293里那几样一次也没出现
    b = _m._mb._白(293) or ''
    _t('③之d 293里 东头/担架/毡子/甜/馊/刘二 俱为0',
       sum(b.count(w) for w in ('东头', '担架', '毡子', '甜', '馊', '刘二')), 0)

    # ④★不许用「猜」判兑没兑——那条路已弃，其由须写在源里
    _t('④已弃「取实词比字面」之路', ('中文不分词' in _SRC) and ('故弃此路' in _SRC), True)
    _t('④之b 且不再有 中 这一键', "'中':" in _SRC, False)

    # ⑤认账即销（写一行「约-NNN」进轮记，闸即放行）
    #   ★★★★而验其理之法：**把回话抽掉，须复欠；还回去，须复销**——二向俱验，缺一即半。
    # ★★★★★2026-09-03·295第1轮所修（第二十八犯之形·同日第二回）：
    #   ★原码只抽 293 之回话，**而其断言是「回话只在293」**——那是把断言钉在快照上；
    #   ★★295亦在其到期之窗内（其窗係「第293、295章」），295之轮记一回话，此条当场判红；
    #   ★★★**器一分没坏，坏的还是测所站的那一刻。**
    #   ★★★★**其治**：**抽的不是某一章，是其窗内每一章**——逐章抽毕方验，验毕逐章还原。
    #   ★而其判准（令§六④）：改後它还逮不逮得住它本来要逮的东西？
    #     ——**逮得住**：窗内一处回话也没有时，此约须复欠；有一处回话，即须销。
    _窗 = []
    for _x in _m.扫():
        if _x['号'] == '约-291.139':
            _窗 = list(_x.get('窗') or [])
            break
    if not _窗:
        _窗 = [293, 295]
    # ★★而其所读者有三处，非一处（约到期.py:179—187）：**轮记／开镜卡／到期之章之回执**。
    #   ★头一版之修只抽了轮记，遂又漏——**故此处逐处数它读哪几样**（令§六④）：
    #   ①版本/第N章/_轮记.md ②版本/第N章/_开镜卡.md ③设定/回执_*第N章*.md。
    import glob as _g
    _档 = []
    for _c in _窗:
        for _p in (os.path.join(ROOT, '版本', '第%d章' % _c, '_轮记.md'),
                   os.path.join(ROOT, '版本', '第%d章' % _c, '_开镜卡.md')):
            if os.path.exists(_p):
                _档.append((_p, io.open(_p, encoding='utf-8').read()))
        for _p in _g.glob(os.path.join(ROOT, '设定', '回执_*第%d章*.md' % _c)):
            _档.append((_p, io.open(_p, encoding='utf-8').read()))
    _t('⑤之前置·其窗内三处（轮记／开镜卡／回执）有档可抽（窗＝%s，得%d档）'
       % ('、'.join(str(c) for c in _窗), len(_档)), len(_档) >= 1, True)
    _t('⑤认账即销（今其窗内已有一处回话）',
       any(x['号'] == '约-291.139' and not x['欠'] for x in _m.扫()), True)
    try:
        for _p, _o in _档:
            io.open(_p, 'w', encoding='utf-8').write(_o.replace('约-291.139', '约-XXX.XXX'))
        _t('⑤之b★窗内逐章抽掉回话即复欠（此係本闸之本职）',
           any(x['号'] == '约-291.139' and x['欠'] for x in _m.扫()), True)
    finally:
        for _p, _o in _档:
            io.open(_p, 'w', encoding='utf-8').write(_o)
    _t('⑤之c 还原毕·复销', any(x['号'] == '约-291.139' and not x['欠'] for x in _m.扫()), True)
    _t('⑤之d 还原毕·逐章与测前逐字相同',
       all(io.open(_p, encoding='utf-8').read() == _o for _p, _o in _档), True)

    # ⑥自陈其限须在器上（令§六④）
    _t('⑥自陈其限·三样认不着', ('没有数的约' in _SRC) and ('跨线之约' in _SRC), True)

    # ⑦日号推得准（291＝103日，293＝104日）
    _t('⑦日号', (_m._日号(291), _m._日号(293)), (103, 104))

    # ⑧「第N天」判窗不判点（291之两天已过，其第三天是次日）
    _t('⑧判窗不判点', '判一个窗' in _SRC, True)

    print('\n════ 负测·约到期闸 ════')
    过 = 0
    for 名, ok, 得, 期 in 案:
        print('  %s %s' % ('✓' if ok else '⛔', 名), '' if ok else '  得%r 期%r' % (得, 期))
        过 += ok
    print('  %d/%d %s' % (过, len(案), '全通' if 过 == len(案) else '⛔未过'))
    return 0 if 过 == len(案) else 1


if __name__ == '__main__':
    sys.exit(跑())
