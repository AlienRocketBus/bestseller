# -*- coding: utf-8 -*-
"""负测·起草闸·乙层之日号 · 2026-09-08 立（与 工具/起草闸.py 之二治同日·令§六③）

★这一条负测守的不是「会不会报红」，是**「印给人看的那个数对不对」**。
  乙层【一】那一栏是全器最要紧的一栏——它告诉席「本章为第N天，你这处『昨天』指第N-1天」，
  而相对日词一路占全书回修之 18%，是头号坑。**它印错，席就照着错数去答题。**

★★旧式之两病（0908 由 290 与 293 两席各自逮出，非本坐所见）：
  ①`第([一二三四五六七八九十百]+)天` **不认「日」**——全书暗线诸章章首皆作「第N日」
    （290:5「第九十六日头一件事」），闸跳过章首，取到後文某处回指之「第N天」，印「本章为第93天」。
  ②字集**无「零」**——「第一百零四天」不匹配（293:5），闸又往下取，印「本章为第99天」。
  ★★★上盘一量：**全书 305 章里 41 章（13.4%）旧式所印之日与真日不同**，
    其中 17 章旧式印 None（一个日子也认不出），另 24 章印的是别的日子，
    最远者 289 印 24 而实 102、303 印 45 而实 109、287 印 88 而实 101。

★★★★**这不是「绿而不实」，是另一样东西**：那五六种讲的都是「它该报红而没报」；
  **这一样是它根本不判红——它只是印一个数给人看，而那个数是错的。**
  一个会喊狼的核对器比没有更糟；**一个会报错数的告示牌，比没有告示牌更糟——因为人会照它答题。**
  故此器往後凡加「只报不判」之栏，**每一栏都要有一条负测钉住它印的那个数**。
"""
import os as _o, sys as _s
_s.path.insert(0, _o.path.dirname(_o.path.abspath(__file__)))
try:
    import _账  # 跑账·自记（工具/跑账.py）
except Exception:
    pass
import io, os, re, sys

根 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(根, '工具'))
import 起草闸 as Q                                        # noqa: E402
from 亮点对表 import 诸章                                  # noqa: E402

过 = []
def t(名, 实, 期):
    过.append((名, 实 == 期, 实, 期))

旧式 = re.compile(r'第([一二三四五六七八九十百]+)天')      # 二治以前之式，原样留此作对照


def 旧日(body):
    m = 旧式.findall(body)
    return Q._num(m[0]) if m else None


章 = 诸章()
日 = {}
for n, p in sorted(章.items()):
    b = 乙 = Q.乙层(n)
    日[n] = 乙['本日'] if 乙 else None

# ①两桩祖案·新式印得对
t('①290 之日为 96（其章首作「第九十六日」·旧式印 93）', 日.get(290), 96)
t('②293 之日为 104（其章首作「第一百零四天」·旧式印 99）', 日.get(293), 104)

# ③非陪跑：旧式对同一份原物印的是错数
旧 = {}
for n, p in sorted(章.items()):
    旧[n] = 旧日(io.open(p, encoding='utf-8').read().split('【本章亮点】')[0])
t('③旧式对 290 印 93（非 96）', 旧.get(290), 93)
t('④旧式对 293 印 99（非 104）', 旧.get(293), 99)
差 = sorted(n for n in 章 if 旧.get(n) != 日.get(n))
无 = sum(1 for n in 差 if 旧.get(n) is None)
# ★⑤⑥不写死那个数，写下界并把实数印出来——**其由见 机制总审§二十六**：
#   一个会随正文一动就过时的桩，留着就成了下一个坑（0908 立器之日为 41／20，
#   而同日 296 之席删了一行，旧式那一边当场变成 21）。
#   **此处要钉死的不是「恰好几章」，是「旧式在几十章上印错，而今式逐章对」。**
t('⑤旧式与今式所印不同者 ≥40 章（立器之日 41·其群·令§六④）｜今实 %d 章' % len(差),
  len(差) >= 40, True)
t('⑥其中旧式一个日子也认不出者 ≥20 章（立器之日 20）｜今实 %d 章' % 无, 无 >= 20, True)

# ⑦非挖空：今式不是「一律认出个数来」——它认不出的那些，是章首本来就不报日子的章。
#   ★写在明处（令§六④·其群与其不认）：今式全书仍有 87 章认不出日，其中 109 章以後 26 章
#   （117/119/122/139/140/144—149/151—155/160—166/179/217/277）——那 26 章章首不报日子，
#   **乙层【一】对它们算不出「昨天指第几天」，只能列词不能算日**。这是此器已知之界，不是洞；
#   拿它去猜一个日子出来，才是造第二个 290。
无日 = sum(1 for n in 章 if 日.get(n) is None)
无日後 = sum(1 for n in 章 if n >= 109 and 日.get(n) is None)
t('⑦今式认不出日者 ≤90 章（立器之日 87·此为已知之界，非洞）｜今实 %d 章' % 无日, 无日 <= 90, True)
t('⑦之二·109 章以後认不出日者 ≤30 章（立器之日 26）｜今实 %d 章' % 无日後, 无日後 <= 30, True)
t('⑧暗线之章（章首作「第N日」）认得出：281→92、283→93、292→97',
  (日.get(281), 日.get(283), 日.get(292)), (92, 93, 97))

# ⑨章首之日胜过後文回指之日（240 章内另有「第七十三天」等回指）
t('⑨240 取章首之 76，不为後文回指之日所夺', 日.get(240), 76)

# ⑩主线连号之日逐章加一（289→291→293→295→297→299→301→303→305 为主线单日一章）
主 = [日.get(n) for n in (289, 291, 293, 295, 297, 299, 301, 303, 305)]
t('⑩主线连号之日逐章加一（102→110）', 主, [102, 103, 104, 105, 106, 107, 108, 109, 110])
# ⑪暗线连号之日亦逐章加一（290→292→…→304 为暗线单日一章）
暗 = [日.get(n) for n in (290, 292, 294, 296, 298, 300, 302, 304)]
t('⑪暗线连号之日逐章加一（96→103）', 暗, [96, 97, 98, 99, 100, 101, 102, 103])

print('════ 负测·起草闸·乙层之日号 ════')
for 名, ok, 实, 期 in 过:
    print(('  ✓ ' if ok else '  ⛔ ') + 名 + ('' if ok else '｜得 %r 期 %r' % (str(实)[:60], str(期)[:60])))
好 = sum(1 for _, o, _, _ in 过 if o)
print('  ── 负测·起草闸 %d/%d %s ──' % (好, len(过), '全通' if 好 == len(过) else '有败'))
sys.exit(0 if 好 == len(过) else 1)
