#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""负测 · `重出趋::长串()`（2026-09-22 立·其裁在 `设定/裁_0922_看官账_347至349之重出.md` §四③）

★其所守者：**该报的是串之长，不是章之率。**
⛔其两格係裁档 §四③ 逐字所命之局：
  **拿 349 与 347 回灌，器须单列出那八串；拿 348 与 350 回灌（348→350 仅 3.8%），器须一串不列。**
"""
import os
import sys
import importlib.util

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_s = importlib.util.spec_from_file_location('c', os.path.join(ROOT, '工具', '重出趋.py'))
C = importlib.util.module_from_spec(_s)
_s.loader.exec_module(C)

ok = bad = 0


def chk(名, 得, 期):
    global ok, bad
    if 得 == 期:
        ok += 1
        print('  ✓ %s' % 名)
    else:
        bad += 1
        print('  ⛔ %s：得 %r，期 %r' % (名, 得, 期))


print('════ 负测·重出趋长串 ════（守：该报的是串之长，不是章之率）')
D = C.诸章()

# ①⛔裁档§四③所命之头一局：347→349 须单列八串，其顶 88
_349 = C.长串(D[347], D[349])
chk('①347→349 单列 8 串', len(_349), 8)
chk('①之二·其最长者 88 字', max(L for _, L, _ in _349), 88)

# ②⛔其第二局：348→350（3.8%）须一串不列
chk('②348→350 一串不列', C.长串(D[348], D[350]), [])

# ③★而本器之实：率高而无长串者，须一串不列（342→344 45.8%·最长 28）
_344 = C.长串(D[342], D[344])
chk('③342→344 率 45.8% 而一串不列（⛔证率不是尺）', _344, [])
chk('③之二·其最长串实係 28 字（在顶之下一线）',
    max((L for _, L, _ in C.长串(D[342], D[344], 门=10)), default=0), 28)

# ④⛔顶之齿：门取 29 则 344 当场有串，取 30 则无（⛔证 30 这个数真在缝上）
chk('④门取29·344 有串', len(C.长串(D[342], D[344], 门=29)) > 0, False)
chk('④之二·门取28·344 有串（⛔其顶正是28）', len(C.长串(D[342], D[344], 门=28)) > 0, True)

# ⑤⛔旧式回灌：本器旧只有率，无长串之路——故以率排序，349(41.2) 与 344(15.3) 同列而 344 在後
_率 = {n: r for n, r in C.判()[0]}
chk('⑤旧式·两章之率皆逾界（故旧式判它们同族）',
    (_率.get(349, 0) > 10, _率.get(344, 0) > 10), (True, True))
chk('⑤之二·而今式判它们不同族（一有长串，一无）',
    (len(_349) > 0, len(_344) == 0), (True, True))

print('  ── %d/%d %s ──' % (ok, ok + bad, '全通' if bad == 0 else '⛔未过'))
sys.exit(0 if bad == 0 else 1)
