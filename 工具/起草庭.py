def 对(c):
    """★起草之後：拿第7轮之真五钩，对起草之日的预五钩。
    ★★而此口正是本庭之所以不是摆设的那一处——**一个拟出来的数，事後有人回来算账。**"""
    ct, lt = 读(卡路(c)), 读(轮记路(c))
    print('=' * 66)
    print('  起草庭 · 预实对表 · 第%d章' % c)
    print('=' * 66)
    if ct is None:
        print('  ⛔开镜卡不在'); return 2
    节 = 取节(ct, '乙·预五钩')
    if 节 is None:
        print('  ⛔卡上无「## 乙·预五钩」一格——起草之日没有拟，事後无从对'); return 2
    预 = 取五钩(节)
    if lt is None:
        print('  ⛔轮记不在'); return 2
    实节 = None
    for 头 in ('乙·五钩评分', '乙·五钩之分'):
        实节 = 取节(lt, 头) or 实节
    if 实节 is None:
        m = re.search(r'###\s*乙·五钩[^\n]*\n(.*?)(?=\n###\s|\Z)', lt, re.S)
        实节 = m.group(1) if m else None
    if 实节 is None:
        print('  ⛔轮记里无第7轮之五钩表——★本对须待第7轮跑毕'); return 2
    实 = 取五钩(实节)
    缺 = [n for n in 五钩项 if n not in 实]
    if 缺:
        print('  ⛔第7轮之表缺 %s' % '、'.join(缺)); return 2
    print('  | 项 | 预（起草之日） | 实（第7轮） | 差 |')
    print('  |---|---|---|---|')
    总差 = 0
    for n in 五钩项:
        d = abs(预[n] - 实[n]); 总差 += d
        print('  | %s | %d | %d | %s |' % (n, 预[n], 实[n], ('—' if d == 0 else '**%+d**' % (实[n] - 预[n]))))
    print('  | **合计** | **%d** | **%d** | **逐项之差合计 %d** |'
          % (sum(预.values()), sum(实.values()), 总差))
    print('  ── 其判 ──')
    if 总差 >= 差之限:
        print('  ⛔预实之差合计 %d（限 %d）——★而此红不是「写坏了」，是**「起草之日看错了这一章」**；'
              % (总差, 差之限))
        print('    ★★须於第7轮之记里写一行「预实相犯：<差在哪一项>／<其由>」；')
        print('    ★★★而其治不在改分**，在下一章起草之日拿这一处当据。')
        return 2
    print('  ✓预实之差合计 %d（限 %d）——起草之日看这一章，看得准。' % (总差, 差之限))
    return 0


