# ★**作者所问**：「**看看这个起草它每次到底是不是最好的质量**。」
# ★★**而一道闸只答得出「这一次填了没有」，答不出「这一次认不认真」**——
#   **认不认真，只有事後结算才看得出来。**
# ★★★**故立此账**：**逐章一行，把起草之日所拟的，与事後真跑出来的，并排摆着**：
#   **预五钩／真五钩／其差｜券兑了没有｜预弃卷点中了没有。**
# ★★★★**而其要害在「累积」**：**一章敷衍看不出来，三章敷衍摆在一起，谁都看得出来**；
#   ★**故此账焊进 `一坐.py` 之起手**——**每坐一睁眼就看得见它。**


def _章号全(): 
    out = []
    d = os.path.join(ROOT, '版本')
    if os.path.isdir(d):
        for x in os.listdir(d):
            m = re.match(r'^第(\d+)章$', x)
            if m:
                out.append(int(m.group(1)))
    return sorted(out)


def _一章之账(c):
    ct, lt = 读(卡路(c)), 读(轮记路(c))
    if ct is None:
        return None
    节 = 取节(ct, '乙·预五钩')
    预 = 取五钩(节) if 节 else {}
    实 = {}
    if lt:
        for 头 in ('乙·五钩评分', '乙·五钩之分'):
            n = 取节(lt, 头)
            if n:
                实 = 取五钩(n) or 实
        if not 实:
            # ★同族之第二处（305第7轮·§十一①：记一犯之前须比全表）——账与对二口同病，同日同治。
            m = re.search(r'###\s*[甲乙丙丁戊己庚辛壬癸]·五钩[^\n]*\n(.*?)(?=\n###\s|\Z)', lt, re.S)
            if m:
                实 = 取五钩(m.group(1))
    有预 = len(预) == 5
    有实 = len(实) == 5
    差 = sum(abs(预[n] - 实[n]) for n in 五钩项) if (有预 and 有实) else None
    券 = None
    if 取节(ct, '丙·一句之券') is not None and lt:
        if '券兑' in lt:
            m = re.search(r'券兑[：: ]*\s*\**\s*(兑|未兑|另有更好者)', lt)
            # ★2026-09-05·机制总审（八路·起草庭审第2条）：旧式无「兑／未兑」之词亦读作「已答」——未兑不红。今无判之词即「未判」。
            券 = m.group(1) if m else '未判'
        else:
            券 = '未答'
    弃 = None
    if 取节(ct, '丁·预弃卷点') is not None and lt:
        # ★2026-09-05·机制总审（八路·起草庭审第1条）：旧式只索「预弃卷点」四字即「已对」——中没中从未入账（304、305 之未中无人看见）。
        #   今须其近旁有判：中／未中／对上／没对上／落在／不在／差。
        弃 = '已对' if re.search(r'预弃卷点[^\n]{0,60}(中|未中|对上|没对上|落在|不在|差)', lt) else '未对'
    return {'章': c, '有预': 有预, '有实': 有实, '差': 差, '券': 券, '弃': 弃,
            '四格': sum(1 for _, f in 四格 if f(ct)[0]),
            '认真': sum(1 for _, f in 认真闸 if f(ct)[0])}


