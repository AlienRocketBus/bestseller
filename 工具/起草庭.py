def 读(p):
    if not os.path.exists(p):
        return None
    return open(p, encoding='utf-8', errors='replace').read()


def 取节(t, 头):
    """取自 `## <头>` 起，至下一个 `## ` 止之全文。"""
    m = re.search(r'^##\s*%s[^\n]*$' % re.escape(头), t, re.M)
    if not m:
        return None
    尾 = re.search(r'^##\s', t[m.end():], re.M)
    return t[m.end():m.end() + 尾.start()] if 尾 else t[m.end():]


def 取五钩(节):
    """自一张表里取五项之数。★只认「| **项** | **N** |」之式，与第7轮之表同源。"""
    出 = {}
    for 名 in 五钩项:
        m = re.search(r'\|\s*\*{0,2}%s\*{0,2}\s*\|\s*\*{0,2}\s*(\d)' % re.escape(名), 节)
        if m:
            出[名] = int(m.group(1))
    return 出


