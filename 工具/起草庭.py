_CN = {'〇': 0, '零': 0, '一': 1, '二': 2, '三': 3, '四': 4, '五': 5,
       '六': 6, '七': 7, '八': 8, '九': 9}


def _cn2int(s):
    """★汉数转整（本书章名之形：一、十一、二十、三百、三百零三、三百一十二）。"""
    if s.isdigit():
        return int(s)
    总 = 0      # 已结之段（百、千位）
    段 = 0      # 当前段之值
    数 = None   # 待落之个位
    for ch in s:
        if ch in _CN:
            数 = _CN[ch]
        elif ch == '十':
            段 += (数 if 数 else 1) * 10
            数 = None
        elif ch == '百':
            总 += (数 if 数 is not None else 1) * 100
            数 = None
        elif ch == '千':
            总 += (数 if 数 is not None else 1) * 1000
            数 = None
    return 总 + 段 + (数 or 0)


