def 取节(t, 头):
    """取自 `## <头>` 起，至下一个 `## ` 止之全文。"""
    m = re.search(r'^##\s*%s[^\n]*$' % re.escape(头), t, re.M)
    if not m:
        return None
    尾 = re.search(r'^##\s', t[m.end():], re.M)
    return t[m.end():m.end() + 尾.start()] if 尾 else t[m.end():]


def _真列(节):
    """★第7轮之表可作二列（项｜分），亦可作四列（项｜预｜真｜差）。
    ★★四列者若照旧只取头一个数，取着的是「预」那一列——**而那正是它要拿来对的那一列**：
       预与实一样时它绿得毫无道理，预与实不一样时它把预当成了实。
    ★★★故先读表头，认出「真／实」那一列之位；认不出者作 0（即头一个数）。"""
    for 行 in 节.split('\n'):
        if 行.count('|') < 3 or not re.search(r'项|钩', 行):
            continue
        格 = [g.strip().strip('*') for g in 行.strip().strip('|').split('|')]
        for i, g in enumerate(格[1:], 0):
            if g.startswith('真') or g.startswith('实'):
                return i
        break
    return 0


def 取五钩(节, 列=None):
    """自一张表里取五项之数。★认「| **项** | … |」之式，与第7轮之表同源。
    ★★而其列由 _真列 定：二列之表取头一个数，四列之表取「真／实」那一列。"""
    if 列 is None:
        列 = _真列(节)
    出 = {}
    for 名 in 五钩项:
        m = re.search(r'^\s*\|\s*\*{0,2}%s\*{0,2}\s*\|([^\n]*)$' % re.escape(名), 节, re.M)
        if not m:
            continue
        数 = re.findall(r'\d+', m.group(1))
        if len(数) > 列:
            出[名] = int(数[列])
        elif 数:
            出[名] = int(数[0])
    return 出


