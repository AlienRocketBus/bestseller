def 认真_三条路(t, c=None):
    节 = 取节(t, '甲·三拟')
    if 节 is None:
        return False, '⛔甲格不在，无从验其为三条路'
    # ★★★★★2026-09-04 治（304起草庭头一跑所逮）：原式在全节里搜「形＝／其器＝」，
    #   ★而甲格之说明行里也写着这二字（「每拟须自带二样：形＝、其器＝」），遂被数进去；
    #   ★★其印当场露相：**器印作「——★★★／门口那一圈／册子」**——**头一个是说明行里捡来的**；
    #   ★★★而其害不在多印一样，在**错位**：三拟之器遂只取到二个，
    #     **若三拟真是同形同器，这一错位反倒让它过了**（本闸所守者正是这一样）。
    #   ★★★★故改为：**只认以 ①②③ 起头之行**，逐行各取其形与其器。
    条行 = [l for l in 节.split('\n')
            if re.match(r'^\s*(?:[-*]\s*)?[①②③]', l)]
    形, 器 = [], []
    for l in 条行:
        m1 = re.search(r'形＝\s*\**\s*([^\s＝｜，,、）)*]+)', l)
        m2 = re.search(r'其器＝\s*\**\s*([^\s＝｜，,、）)*]+)', l)
        if m1:
            形.append(m1.group(1).strip('*　 '))
        if m2:
            器.append(m2.group(1).strip('*　 '))
    形 = [x for x in 形 if x and '〔' not in x]
    器 = [x for x in 器 if x and '〔' not in x]
    if len(形) < 3 or len(器) < 3:
        return False, ('⛔三拟未各带其「形＝」「其器＝」（今形 %d／器 %d，各须 3）'
                       '——★一条路＝形＋其器，不写死则三条路验不出真假' % (len(形), len(器)))
    形, 器 = 形[:3], 器[:3]
    if len(set(形)) == 1 and len(set(器)) == 1:
        return False, ('⛔三拟同形（%s）又同器（%s）——★那是三个说法，不是三条路'
                       % (形[0], 器[0]))
    if len(set(形)) == 1 and len(set(器)) < 3:
        return False, '⛔三拟同形（%s）而器只 %d 样——★三条路至少须在形或器上各不相同' % (形[0], len(set(器)))
    return True, '✓三拟真是三条路（形：%s｜器：%s）' % ('／'.join(形), '／'.join(器))


