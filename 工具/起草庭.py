def 甲_三拟(t):
    节 = 取节(t, '甲·三拟')
    if 节 is None:
        return False, '⛔无「## 甲·三拟」一格——★而 102 份旧卡里，比过三条路的只 3 份'
    if '〔' in 节:
        return False, '⛔甲格在而未填毕：占位符 %d 处' % 节.count('〔')
    条 = re.findall(r'^\s*(?:[-*]\s*)?([①②③])', 节, re.M)
    if len(set(条)) < 3:
        return False, '⛔三拟不足三条（今 %d 条）——★一条路不叫择，二条叫两难，三条才比得出高下' % len(set(条))
    if '取①' not in 节 and '取②' not in 节 and '取③' not in 节:
        return False, '⛔三拟在而无「取①/②/③」一行：取了哪一条，须写死'
    if '其由' not in 节:
        return False, '⛔取而不书其由——★所弃之二为何败，第12轮要回来问它'
    return True, '✓甲·三拟：三条俱在，取舍与其由俱已落字'


def 乙_预五钩(t):
    节 = 取节(t, '乙·预五钩')
    if 节 is None:
        return False, '⛔无「## 乙·预五钩」一格——★而 102 份旧卡里提过「五钩」者 0 份'
    if '〔' in 节:
        return False, '⛔乙格在而未填毕：占位符 %d 处' % 节.count('〔')
    d = 取五钩(节)
    缺 = [n for n in 五钩项 if n not in d]
    if 缺:
        return False, '⛔预五钩缺 %d 项：%s' % (len(缺), '、'.join(缺))
