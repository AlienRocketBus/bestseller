根 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MINLEN = 6
SPAN = 3
沓拍 = 3        # ★W53·X12：其串（或其一 MINLEN 字之窗）见於本章 ≥沓拍 拍者＝称／复沓，只报不计
