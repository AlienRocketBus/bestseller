def 诸章():
    d = {}
    for p in glob.glob(os.path.join(根, '正文', '*.md')):
        m = re.search(r'第([一二三四五六七八九十百零]+)章', os.path.basename(p))
        if not m:
            continue
        s, v, u = m.group(1), 0, 0
        for c in s:
            i = '零一二三四五六七八九'.find(c)
            if i >= 0:
                u = i
            elif c == '十':
                v += (u or 1) * 10; u = 0
            elif c == '百':
                v += (u or 1) * 100; u = 0
        d[v + u] = p
    return d


def 分拍(txt):
    """★2026-09-06 改·此器自开张以来最大的一个洞：**它对全书一半的章根本没看。**

    ★原式作 `body.split('\n＊\n')`——只认「＊」分拍。而本书有 **151 章（305 章之半）
      通篇以空行分拍、一个＊也没有**，於是整章塌成 **1 拍**，逐拍相比无从比起，
      它照旧印「✓ 全章无邻拍逐字重出」。**报的是绿，而它一眼没看。**
    ★★逮出它的是 0906 立 `含拍.py` 之後的负测：拿 138 治前之原物（同一段话前後说了两遍、
      约二百字）灌给它，它**一处也报不出**；上盘一量方知——`邻拍重出` 见 138 为 **1 拍**，
      而 `含拍` 见 **223 拍**。
    ★★★今改为按行分拍（空行与＊皆作界）。改後全书由 **554 处**升至 **775 处**，
      多出来的 221 处**全在它此前看不见的那一半里**。
    ★★★★阈值随之重定（旧阈「三处以上」是在只看得见一半、且那一半「常态是零」时定的）：
      实测新式全书 **均 2.5｜中位 2｜75分位 4｜90分位 6｜95分位 8｜顶 17（第222章）**，
      零处之章 79／305。**故取 90 分位 6 为「刀没落到底」之线**，其下只报不判。
      （W53·X12 称沓不计之後，此 6 落在 95 分位、90 分位降为 5；线仍守 6——见 `刀线`。）
    """
    body = txt.split('【本章亮点】')[0]
    return [re.sub(r'[，、。！？：；「」\s]', '', x) for x in body.split('\n')
            if x.strip() and x.strip() != '＊']


def 复沓(b, s):
    """s 或其任一 MINLEN 字之窗见於 b 之 ≥沓拍 拍——卡令统一之称、立法复沓（W53·X12）。"""
    return any(sum(1 for x in b if w in x) >= 沓拍
               for w in {s} | {s[k:k + MINLEN] for k in range(len(s) - MINLEN + 1)})


