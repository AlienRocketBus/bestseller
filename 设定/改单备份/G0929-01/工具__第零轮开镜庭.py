def _格数(l):
    """★只取其答（冒号之後），⛔不取问那一行里的字——此病本文件已栽过两回。"""
    seg = l.split('：', 1)[-1] if '：' in l else l
    seg = seg.split('←')[0]
    m = re.match(r'\s*\*\*(.+?)\*\*', seg)
    ans = m.group(1) if m else seg
    m = re.search(r'\d+', ans)
    if m:
        return int(m.group(0))
    for ch in ans:
        if ch in _汉数:
            return _汉数[ch]
    return None


